def committed_residue(pool: str, run_id: str, ratio_field: str) -> dict:
    """The residue re-derived from a committed results.json ratio field."""
    with open(os.path.join(_run_dir(run_id), "results.json"),
              encoding="utf-8") as fh:
        L = json.load(fh)["ladder"]
    B = L["B"]
    residue = 0
    comparable = 0
    vacuous = 0
    cells = 0
    verdict_agrees = 0
    verdict_checked = 0
    per_functional: dict = {}
    for fkey in L["functionals"]:
        for stat in ("weighted", "unweighted"):
            cells += 1
            seq = [L["cells"][f"{pool}|{fkey}|{r}|{stat}|B{B}"]
                   for r in N_LADDER]
            nd = [c for c in seq if not c["degenerate"]]
            vals_nd = [c[ratio_field] for c in nd if c[ratio_field] is not None]
            vals_all = [c[ratio_field] for c in seq
                        if c[ratio_field] is not None]
            if vals_all:
                comparable += 1
            if len(vals_nd) < 2:
                vacuous += 1
            is_res = not verdict_rises(vals_nd)
            residue += int(is_res)
            per_functional.setdefault(fkey, {"residue": 0, "cells": 0})
            per_functional[fkey]["cells"] += 1
            per_functional[fkey]["residue"] += int(is_res)
            # cross-check the restated rule against the committed boolean on
            # the FULL ladder (the v1 verdict, not the residue construction)
            if ratio_field == "variance_ratio_R_empirical":
                verdict_checked += 1
                mine = verdict_rises(vals_all)
                theirs = L["monotonicity"][f"{fkey}|{stat}"][
                    "ratio_rises_monotonically_along_N_ladder"]
                verdict_agrees += int(mine == theirs)
    return {"residue": residue, "cells": cells, "comparable": comparable,
            "vacuous": vacuous, "by_functional": per_functional,
            "restated_rule_agrees_with_committed_boolean":
                (None if not verdict_checked
                 else f"{verdict_agrees}/{verdict_checked}")}


def reproduction_gate(views: dict) -> dict:
    """SR-B1. Three independent derivations of the OBSERVED residue count.

      D1  committed `variance_ratio_R_empirical`  (the v1 Monte-Carlo ratio)
      D2  committed `variance_ratio_R_closed_form` (exact, zero MC error)
      D3  RECOMPUTED end-to-end from `per_curve.csv` + `rung_table.json`
          through this module's own pipeline -- the identity replicate of the
          shuffle, and the only derivation that certifies the null is measured
          by the same instrument as the observed value.

    THE GATE PASSES ONLY IF ALL THREE RETURN 50. On failure the run STOPS,
    reports both numbers, and adjusts nothing: the frozen 50 is never moved to
    match a re-derivation.
    """
    d1 = {p: committed_residue(p, SOURCE_RUNS[p], "variance_ratio_R_empirical")
          for p in POOLS}
    d2 = {p: committed_residue(p, SOURCE_RUNS[p],
                               "variance_ratio_R_closed_form") for p in POOLS}
    d3_cells = {p: ladder_cells(views[p], views[p].values) for p in POOLS}
    d3 = residue_summary(d3_cells)

    tot1 = sum(v["residue"] for v in d1.values())
    tot2 = sum(v["residue"] for v in d2.values())
    tot3 = d3["residue_count"]

    # degeneracy must be a SUFFIX of the N ladder, or the residue construction
    # would compare rungs that are not adjacent in the ladder.
    suffix_ok = {}
    for p in POOLS:
        flags = [views[p].degenerate[r] for r in N_LADDER]
        suffix_ok[p] = flags == sorted(flags)          # False... then True...

    per_pool_ok = all(
        d1[p]["residue"] == d2[p]["residue"] == d3["by_pool"][p]["residue"]
        == FROZEN_OBSERVED_RESIDUE_BY_POOL[p] for p in POOLS)

    m3_ok = all(d3["m3_family"][k] == FROZEN_OBSERVED_M3[k] for k in M3_FAMILY)

    passed = bool(tot1 == tot2 == tot3 == FROZEN_OBSERVED_RESIDUE
                  and per_pool_ok and all(suffix_ok.values()))

    return {
        "rule": "SR-B1 REPRODUCTION GATE, BLOCKING, RUNS FIRST",
        "frozen_observed_residue_count": FROZEN_OBSERVED_RESIDUE,
        "frozen_observed_by_pool": FROZEN_OBSERVED_RESIDUE_BY_POOL,
        "derivations": {
            "D1_committed_empirical_ratio": {
                "total": tot1,
                "by_pool": {p: d1[p]["residue"] for p in POOLS},
                "comparable_cells": sum(d1[p]["comparable"] for p in POOLS),
                "full_cells": sum(d1[p]["cells"] for p in POOLS),
                "restated_rule_vs_committed_boolean":
                    {p: d1[p]["restated_rule_agrees_with_committed_boolean"]
                     for p in POOLS}},
            "D2_committed_closed_form_ratio": {
                "total": tot2,
                "by_pool": {p: d2[p]["residue"] for p in POOLS},
                "comparable_cells": sum(d2[p]["comparable"] for p in POOLS),
                "full_cells": sum(d2[p]["cells"] for p in POOLS)},
            "D3_recomputed_from_per_curve_csv": {
                "total": tot3,
                "by_pool": {p: d3["by_pool"][p]["residue"] for p in POOLS},
                "comparable_cells": d3["cells_comparable"],
                "full_cells": d3["cells_full"],
                "note": "the identity replicate: same code path the shuffled "
                        "replicates use, with no permutation applied"},
        },
        "denominators": {
            "full_cells": FROZEN_DENOMINATOR_FULL,
            "comparable_cells": FROZEN_DENOMINATOR_COMPARABLE,
            "reproduced_full_cells": d3["cells_full"],
            "reproduced_comparable_cells": d3["cells_comparable"],
            "residue_against_full": f"{tot3}/{d3['cells_full']}",
            "residue_against_comparable": f"{tot3}/{d3['cells_comparable']}",
            "which_the_decision_rule_used": (
                "THE COUNT, over the full 144-cell frame. The frozen "
                "statistic is a COUNT and the null is drawn over the same "
                "144-cell frame, so the denominator does not enter the "
                "p-value at all. 50 reproduces under BOTH denominators "
                "because the six-cell difference is cells with no defined R "
                "at any rung, which cannot be in the residue under either. "
                "Both fractions are reported."),
        },
        "degeneracy_is_a_ladder_suffix": suffix_ok,
        "m3_family_observed": d3["m3_family"],
        "m3_family_frozen": FROZEN_OBSERVED_M3,
        "m3_family_reproduced": m3_ok,
        "observed_cells": d3,
        "gate": "PASS" if passed else "FAIL",
        "on_failure": (
            "STOP. Report the discrepancy as the deliverable, report BOTH "
            "numbers, and do NOT adjust the frozen 50 to match the "
            "re-derivation."),
    }


