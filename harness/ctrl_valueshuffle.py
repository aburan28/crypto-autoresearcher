def derive_shuffle_seed(replicate: int, pool: str, functional: str) -> int:
    """Big-endian SHA-256 of the declared payload, reduced mod 2^64.

        payload = DOMAIN | "SHUFFLE" | pool | functional | replicate
                  | seed0 | seed1 | seed2

    IMPLEMENTATION DECISION, RECORDED BECAUSE THE CONTRACT DOES NOT FIX IT.
    `parameters_frozen.seeds` names three seeds and `parameters_frozen.
    replicates` names 200; the amendment does not say how the three map onto
    the replicates. This derivation consumes ALL THREE for EVERY draw, so no
    seed is favoured, no replicate shares a stream with another, and a third
    party reproduces any single shuffle from (replicate, pool, functional)
    alone. It mirrors `run_blocknull.derive_seed`, which is the convention
    already committed for this experiment. Any other mapping is a different
    (and equally legal) reading of an under-specified field; this one is
    stated here so the difference is visible rather than silent.
    """
    payload = (f"{DOMAIN}|SHUFFLE|{pool}|{functional}|{replicate}"
               f"|{SEEDS[0]}|{SEEDS[1]}|{SEEDS[2]}")
    return int.from_bytes(hashlib.sha256(payload.encode("ascii")).digest(),
                          "big") % (1 << 64)


