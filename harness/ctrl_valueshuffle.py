def _per_functional_null(null: dict) -> dict:
    out: dict = {}
    for rec in null.get("records", []):
        for k, v in rec["by_functional"].items():
            out.setdefault(k, []).append(v)
    return {k: {"mean": sum(v) / len(v), "min": min(v), "max": max(v),
                "n_replicates": len(v)} for k, v in out.items()}


