@dataclass
class PoolView:
    """One frozen pool, reconstructed from its committed run directory.

    Nothing here is re-enumerated or re-measured: `per_curve.csv` supplies the
    curves, their traces and every functional value; `rung_table.json`
    supplies the block partition of each rung. (trace, N), the class sizes and
    the block assignment are READ, never recomputed from a curve.
    """
    name: str
    p: int
    run_id: str
    n: int
    keys: list
    traces_by_curve: list
    class_traces: list                       # class index -> trace
    class_N: list                            # class index -> N (group order)
    class_sizes: list
    labels: np.ndarray = field(repr=False)
    values: dict = field(repr=False)
    blocks: dict = field(repr=False)         # rung -> np.ndarray of block ids
    degenerate: dict = field(default_factory=dict)
    delta_max: dict = field(default_factory=dict)
    n_blocks: dict = field(default_factory=dict)

    @property
    def K(self) -> int:
        return len(self.class_traces)

    @property
    def non_degenerate_ladder(self) -> list:
        return [r for r in N_LADDER if not self.degenerate[r]]


def _run_dir(run_id: str) -> str:
    return os.path.join(_repo(), "experiments", EXPERIMENT_ID, "runs", run_id)


def load_pool_view(pool: str, run_id: str) -> PoolView:
    base = _run_dir(run_id)
    with open(os.path.join(base, "per_curve.csv"), encoding="utf-8") as fh:
        rows = list(csv.reader(fh))
    header, body = rows[0], rows[1:]
    p = int(body[0][0])
    keys = functional_keys(p)
    fixed = ["p", "a", "b", "j", "trace", "order", "aut_order", "fb_m2",
             "fb_m3", "n_targets", "hits_m2", "hits_m3"]
    if header[:12] != fixed:
        raise RuntimeError(f"{run_id}: unexpected per_curve.csv prefix "
                           f"{header[:12]}")
    if header[12:12 + len(keys)] != keys:
        raise RuntimeError(f"{run_id}: unexpected functional columns "
                           f"{header[12:12 + len(keys)]}")

    traces = [int(r[4]) for r in body]
    orders = [int(r[5]) for r in body]
    class_traces: list = []
    for t in traces:
        if t not in class_traces:
            class_traces.append(t)
    index_of = {t: i for i, t in enumerate(class_traces)}
    labels = np.array([index_of[t] for t in traces], dtype=np.int64)
    class_sizes = [int((labels == i).sum()) for i in range(len(class_traces))]
    class_N = []
    for i, t in enumerate(class_traces):
        Ns = {orders[j] for j in range(len(traces)) if traces[j] == t}
        if len(Ns) != 1:
            raise RuntimeError(f"{run_id}: class t={t} carries several N {Ns}")
        class_N.append(int(Ns.pop()))

    values = {k: np.array([float(r[12 + i]) for r in body], dtype=np.float64)
              for i, k in enumerate(keys)}

    with open(os.path.join(base, "rung_table.json"), encoding="utf-8") as fh:
        rt = json.load(fh)[pool]
    blocks, degen, dmax, nblk = {}, {}, {}, {}
    for rung in rb.RUNGS:
        comp = rt[rung]["block_composition_by_trace"]
        blk_of_trace = {}
        for bid, ts in comp.items():
            for t in ts:
                blk_of_trace[int(t)] = int(bid)
        blocks[rung] = np.array([blk_of_trace[t] for t in traces],
                                dtype=np.int64)
        degen[rung] = bool(rt[rung]["degenerate"])
        dmax[rung] = int(rt[rung]["delta_max_N"])
        nblk[rung] = int(rt[rung]["n_blocks"])

    return PoolView(name=pool, p=p, run_id=run_id, n=len(body), keys=keys,
                    traces_by_curve=traces, class_traces=class_traces,
                    class_N=class_N, class_sizes=class_sizes, labels=labels,
                    values=values, blocks=blocks, degenerate=degen,
                    delta_max=dmax, n_blocks=nblk)


def geometry_fingerprint(view: PoolView) -> dict:
    """The bits the shuffle MUST NOT touch, hashed.

    (trace, N) per class, the class sizes, the per-curve class label and the
    per-curve block id at every rung. Recomputed and compared after every
    single replicate: `state_0_INVALID` fires when any of these moves.
    """
    trace_N = ";".join(f"{t}:{N}" for t, N in
                       zip(view.class_traces, view.class_N))
    sizes = ";".join(str(s) for s in view.class_sizes)
    labels = ",".join(str(int(x)) for x in view.labels)
    blocks = {r: _sha(",".join(str(int(x)) for x in view.blocks[r]))
              for r in rb.RUNGS}
    return {
        "trace_N_pairs": trace_N,
        "trace_N_sha256": _sha(trace_N),
        "class_sizes_sha256": _sha(sizes),
        "labels_sha256": _sha(labels),
        "block_assignment_sha256_by_rung": blocks,
        "n_curves": view.n,
        "n_classes": view.K,
    }


def value_multiset_fingerprint(values: dict) -> dict:
    """sha256 of each functional's SORTED value vector.

    Preserved exactly by a permutation; any change means the shuffle did more
    than permute.
    """
    out = {}
    for k, v in values.items():
        s = np.sort(np.asarray(v, dtype=np.float64))
        out[k] = _sha(",".join(repr(float(x)) for x in s))
    return out


