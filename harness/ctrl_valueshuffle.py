def verdict_rises(vals: list) -> bool:
    """harness/run_blocknull.py:1552, restated. NOTE THE VACUOUS TRUE.

    `all()` over an empty or one-element list is True, so a cell with fewer
    than two defined R values scores MONOTONE RISE on no data. That defect is
    OBJ-3 of RT-20260807-743198 and is recorded, NOT repaired, here: the
    amendment states in `what_this_amendment_does_not_do` that fixing it is a
    separate amendment. `n_comparisons` is reported beside every verdict so a
    vacuous pass is visible.
    """
    return all(b >= a - VERDICT_TOLERANCE for a, b in zip(vals, vals[1:]))


def ladder_cells(view: PoolView, values: dict) -> dict:
    """Every (functional, statistic) cell's ladder, from the closed form alone.

    R(rung) = T_obs / E[T_pi | rung] with E[T_pi | rung] the EXACT closed-form
    null mean. T_obs does not depend on the rung, so the whole sequence is one
    fixed numerator over the ladder's denominators.

    The type-A residue indicator is the frozen verdict rule applied to the
    NON-DEGENERATE rungs only, which removes every type-B reversal by
    construction (item 3f of RT-20260807-743198, and `definitions_frozen` of
    the amendment).
    """
    out = {}
    nd = view.non_degenerate_ladder
    for k in view.keys:
        v = values[k]
        t_w = statistic_weighted(v, view.labels)
        t_u = statistic_unweighted(v, view.labels)
        cf = {}
        for rung in N_LADDER:
            cf[rung] = (closed_form_null_mean(v, view.labels,
                                              view.blocks[rung], "weighted"),
                        closed_form_null_mean(v, view.labels,
                                              view.blocks[rung], "unweighted"))
        for si, (stat, T) in enumerate((("weighted", t_w),
                                        ("unweighted", t_u))):
            R = {}
            for rung in N_LADDER:
                m = cf[rung][si]
                R[rung] = (None if m is None or m == 0.0 or
                           (isinstance(m, float) and np.isnan(m))
                           else T / m)
            vals_nd = [R[r] for r in nd if R[r] is not None]
            vals_all = [R[r] for r in N_LADDER if R[r] is not None]
            rises = verdict_rises(vals_nd)
            out[f"{k}|{stat}"] = {
                "T_obs": T,
                "closed_form_null_mean": {r: cf[r][si] for r in N_LADDER},
                "R": R,
                "non_degenerate_rungs": list(nd),
                "n_comparisons": max(0, len(vals_nd) - 1),
                "type_A_residue": (not rises),
                "vacuous": len(vals_nd) < 2,
                "comparable": bool(vals_all),
                "closed_form_applicable": all(
                    cf[r][si] is not None for r in N_LADDER),
            }
    return out


def residue_summary(cells_by_pool: dict) -> dict:
    """Counts over the 144-cell frame, plus the per-functional breakdown."""
    total = 0
    comparable = 0
    full = 0
    vacuous = 0
    per_pool = {}
    per_functional: dict = {}
    bitmap_keys: list = []
    bitmap: list = []
    for pool in POOLS:
        cells = cells_by_pool[pool]
        r = sum(1 for c in cells.values() if c["type_A_residue"])
        cmp_ = sum(1 for c in cells.values() if c["comparable"])
        vac = sum(1 for c in cells.values() if c["vacuous"])
        per_pool[pool] = {"residue": r, "cells": len(cells),
                          "comparable": cmp_, "vacuous": vac}
        total += r
        comparable += cmp_
        full += len(cells)
        vacuous += vac
        for ck in sorted(cells):
            fkey = ck.split("|")[0]
            per_functional.setdefault(fkey, {"residue": 0, "cells": 0})
            per_functional[fkey]["cells"] += 1
            per_functional[fkey]["residue"] += int(cells[ck]["type_A_residue"])
            bitmap_keys.append(f"{pool}|{ck}")
            bitmap.append("1" if cells[ck]["type_A_residue"] else "0")
    return {
        "residue_count": total,
        "cells_full": full,
        "cells_comparable": comparable,
        "cells_vacuous_in_residue_construction": vacuous,
        "by_pool": per_pool,
        "by_functional": per_functional,
        "m3_family": {k: per_functional.get(k, {}).get("residue")
                      for k in M3_FAMILY},
        "cell_bitmap": "".join(bitmap),
        "cell_bitmap_keys_sha256": _sha(";".join(bitmap_keys)),
    }


