    ap.add_argument("--inputs", default=INPUTS_JSON)
    args = ap.parse_args(argv)
    t0 = time.time()
    out = run(npoints=args.points, nother=args.other, seed=args.seed, inputs=args.inputs)
    try:
        import flint  # type: ignore
        fl = flint.__version__
    except ImportError:
        fl = None
    out["provenance"] = {"python_flint": fl, "arkworks_json_sha256": sha256_file(ARKWORKS_JSON),
                         "inputs_json_sha256": sha256_file(args.inputs), "elapsed_s": round(time.time() - t0, 1)}
