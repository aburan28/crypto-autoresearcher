def chain_map(E: Curve, res: EX.ChainResult):
    """The built chain as a callable on F_q-points (None = the point at infinity)."""
    maps, cur = [], E
    for ell, hp in zip(res.steps, res.kernel_polys):
        iso = EX.KernelIsogeny(cur, hp, ell)
        maps.append(iso)
        cur = iso.codomain
    back = Isomorphism(cur, res.isomorphism_u)
    if (back.codomain.a, back.codomain.b) != (E.a, E.b):
        raise AssertionError("the isomorphism does not return to E")
    maps.append(back)
    return Composite(maps)


def unit_map_j0(E: Curve, beta: int):
    p = E.p
    return lambda P: None if P is None else (beta * P[0] % p, P[1])


def apply_element(E: Curve, phi, c0: int, c1: int, Q):
    return E.add(E.mul(c0, Q), E.mul(c1, phi(Q)) if c1 else None)


def random_point(E: Curve, rng: random.Random):
    while True:
        x = rng.randrange(E.p)
        rhs = (x * x * x + E.a * x + E.b) % E.p
        if rhs == 0:
            return (x, 0)
        ys = prime_nth_roots(rhs, 2, E.p)
        if ys:
            return (x, ys[rng.randrange(len(ys))])


def check_on_points(E: Curve, phi, r: int, h: int, mem: Candidate, clr: Candidate, eff: int,
                    *, npoints: int, nother: int, small_primes, seed: int) -> dict:
    """Both tests against the definition, on random and constructed points.

    Truth: Q in G iff [r]Q = O.  Clearing: beta(Q) = [c/h]([h]Q) with c the
    action of beta on G; since [h]Q is always in G and c/h is a unit mod r,
    this says beta(Q) is in G and is O exactly when Q has no G-component.
    The integer effective cofactor gets the same check.
    """
    rng = random.Random(seed)
    N = h * r
    assert clr.eigenvalue % r and eff % r, "a clearing map must be nonzero on G"
    ratio = clr.eigenvalue * pow(h, -1, r) % r
    eratio = eff * pow(h, -1, r) % r
    stats: dict[str, dict] = {}

    def record(kind, Q, full):
        s = stats.setdefault(kind, {"points": 0, "members": 0, "membership_errors": 0,
                                    "clearing_errors": 0, "effective_cofactor_errors": 0})
        s["points"] += 1
        truth = E.mul(r, Q) is None
        s["members"] += int(truth)
        if (apply_element(E, phi, mem.c0, mem.c1, Q) is None) != truth:
            s["membership_errors"] += 1
        if full:
            hQ = E.mul(h, Q)
            # [h]Q lies in G for every Q, so R = [c/h]([h]Q) with c/h != 0 mod r
            # says at once that R is in G and that R = O iff [h]Q = O.
            R = apply_element(E, phi, clr.c0, clr.c1, Q)
            s["clearing_errors"] += int(R != E.mul(ratio, hQ))
            Re = E.mul(eff, Q)
            s["effective_cofactor_errors"] += int(Re != E.mul(eratio, hQ))

    for _ in range(npoints):
        record("random", random_point(E, rng), True)
    for _ in range(nother):
        record("member [h]R", E.mul(h, random_point(E, rng)), True)
    for _ in range(nother):
        record("cofactor-only [r]R", E.mul(r, random_point(E, rng)), True)
    for _ in range(nother):
        A = E.mul(h, random_point(E, rng))
        B = E.mul(r, random_point(E, rng))
        record("mixed [h]R + [r]S", E.add(A, B), True)
    for ell in small_primes:
        v, m = 0, N
        while m % ell == 0:
            v, m = v + 1, m // ell
        found = 0
        for _ in range(64):
            T = E.mul(m, random_point(E, rng))            # the ell-Sylow component
            while T is not None and E.mul(ell, T) is not None:
                T = E.mul(ell, T)                           # down to order ell
            if T is not None:
                record(f"order {ell}", T, True)
                found += 1
                if found == 3:
                    break
    record("identity", None, True)
    total = {k: sum(s[k] for s in stats.values())
             for k in ("points", "members", "membership_errors", "clearing_errors", "effective_cofactor_errors")}
    return {"by_kind": stats, "total": total}


def torsion_count_check(E: Curve, D: int, pim1, ell: int) -> dict:
    """#E(F_q)[ell] from the ell-division polynomial vs [O : ell*O + (pi - 1)O]."""
    import flint  # type: ignore
    p = E.p
    ctx = flint.fmpz_mod_poly_ctx(p)
    if ell == 2:
        roots = ctx([E.b % p, E.a % p, 0, 1]).roots()
        count = 1 + len(roots)
    else:
        f = EX.division_polynomials_flint(p, E.a, E.b, ell)[ell]
        count = 1
        for x, _ in ctx(f).roots():
            x = int(x)
            rhs = (x ** 3 + E.a * x + E.b) % p
            if rhs == 0 or pow(rhs, (p - 1) // 2, p) == 1:
                count += 1 if rhs == 0 else 2
    pred = element_index(D, [(ell, 0), pim1])
    return {"ell": ell, "counted": count, "predicted": pred, "agree": count == pred}


