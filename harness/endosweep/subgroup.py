def _arkworks(name: str, path: str = ARKWORKS_JSON) -> dict:
    with open(path) as fh:
        d = json.load(fh)
    c = next(c for c in d["curves"] if c["name"] == name)
    return {"p": int(c["field"]["p"], 16), "a": int(c["params"]["a"]["raw"], 16),
            "b": int(c["params"]["b"]["raw"], 16), "n": int(c["order"], 16), "h": int(c["cofactor"], 16)}


def j0_unit(E: Curve, r: int, beta: int, P) -> Alpha:
    """phi(x, y) = (beta x, y) as an element of Z[omega] (omega = zeta_6): phi = omega - 1."""
    lam = next(l for l in ((-1 + s) * pow(2, -1, r) % r for s in _sqrts(-3, r))
               if E.mul(l, P) == (beta * P[0] % E.p, P[1]))
    return Alpha(-1, 1, lam, CV.chain_ops((), "optimised"), "zeta_3: (x, y) -> (beta x, y)")


def _sqrts(a: int, n: int) -> list[int]:
    from sympy.ntheory import sqrt_mod
    s = sqrt_mod(a % n, n)
    return [s, (-s) % n]


def chain_alpha(E: Curve, r: int, h: int, D: int, element, order, label: str):
    root = QO.omega_eigenvalues(D, r)[0]
    res = EX.build_chain_endomorphism(E.p, E.a, E.b, r, h, D, tuple(element), steps=list(order),
                                      conjugates=False, omega_root=root)
    if not res.found:
        raise RuntimeError(f"{label}: chain not built: {res.note}")
    s, b = res.matched_element
    if abs(b) != 1:
        raise RuntimeError("alpha must be s +- omega for Z[alpha] = O")
    ops = CV.chain_ops(tuple(order), "optimised")
    return Alpha(s, b, res.eigenvalue, ops, label), chain_map(E, res), res


def bls12_381_control(npoints: int, nother: int, seed: int) -> dict:
    c = _arkworks("bls12_381")
    E = Curve(c["p"], c["a"], c["b"])
    P = EX.point_of_order(E, c["n"], c["h"], 3)
    alpha = j0_unit(E, c["n"], BLS12_381_BETA, P)
    phi = unit_map_j0(E, BLS12_381_BETA)
    out = analyse("BLS12-381 G1", E, c["n"], c["h"], -3, alpha, phi, npoints=npoints, nother=nother, seed=seed)
    M = module_structure(-3, c["p"], c["n"], c["h"], alpha)
    out["control"] = control_summary(M, alpha, out, BLS12_381_U)
    return out


def control_summary(M: ModuleStructure, alpha: Alpha, out: dict, u: int) -> dict:
    """Compare what the module derivation found with the known BLS12 identities.

    Known (arkworks bls12_381 g1.rs at the pinned commit, quoting ePrint
    2021/1130 Section 6 and ePrint 2019/403 Section 5): G1 membership is
    "endomorphism_p(P) == -[X^2]P" and cofactor clearing multiplies by 1 - X.
    """
    r, D = M.r, M.D
    J_w = [alpha.to_omega(*v) for v in M.J_basis]
    rr_w = [alpha.to_omega(*v) for v in M.rr_basis]
    beta = alpha.to_omega(u * u, 1)                      # u^2 + phi
    mem = out["membership"]["chosen"]
    short = out["membership"]["shortest_valid"]
    sw = alpha.to_omega(int(short["c0"]), int(short["c1"]))
    return {
        "phi_eigenvalue_is_minus_u2": alpha.lam == (-u * u) % r,
        "r_equals_u4_minus_u2_plus_1": r == u ** 4 - u ** 2 + 1,
        "h_equals_(u-1)^2/3": M.h == (u - 1) ** 2 // 3,
        "u2_plus_phi_in_rr": element_index(D, rr_w + [beta]) == r,
        "norm_of_u2_plus_phi_equals_r": QO.norm(D, *beta) == r,
        "kernel_of_u2_plus_phi_on_E(F_p)": str(kernel_order(D, beta, M.pim1)),
        "cheapest_valid_membership_element": [mem["c0"], mem["c1"]],
        "cheapest_is_+-(u2_plus_phi)": (int(mem["c0"]), int(mem["c1"])) in ((u * u, 1), (-u * u, -1)),
        "shortest_by_height_valid_element": [short["c0"], short["c1"]],
        "shortest_is_a_unit_multiple_of_u2_plus_phi": QO.norm(D, *sw) == r and any(
            QO.multiply(D, beta, w) in (sw, (-sw[0], -sw[1])) for w in QO.units(D)),
        "1_minus_u_in_J": element_index(D, J_w + [(1 - u, 0)]) == M.h,
        "1_minus_u_not_in_rr": (1 - u) % r != 0,
        "effective_cofactor_equals_|1-u|": M.effective_cofactor == abs(1 - u),
        "cofactor_group": f"Z/{M.cofactor_invariants[0]} x Z/{M.cofactor_invariants[1]}",
    }


def residue_test_bandersnatch(E: Curve, r: int, h: int, D: int, pim1, nonmembers: int, seed: int) -> dict:
    """Q in G iff Q in 2E(F_p) when E(F_p)[2^oo] = Z/2 x Z/2: two Legendre symbols."""
    import flint  # type: ignore
    p = E.p
    two = element_index(D, [(2, 0), pim1])
    four = element_index(D, [(4, 0), pim1])
    out = {"#E(F_p)[2] predicted": two, "#E(F_p)[4] predicted": four}
    roots = sorted(int(x) for x, _ in flint.fmpz_mod_poly_ctx(p)([E.b % p, E.a % p, 0, 1]).roots())
    out["rational_2_torsion_roots"] = len(roots)
    if not (h == 4 and two == 4 and len(roots) == 3):
        out["applicable"] = False
        return out
    out["applicable"] = True
    e1, e2 = roots[0], roots[1]

    def qr(z):
        return z % p != 0 and pow(z, (p - 1) // 2, p) == 1

    def residue_member(Q):
        if Q is None:
            return True
        if Q[1] == 0:
            return False
        return qr(Q[0] - e1) and qr(Q[0] - e2)

    rng = random.Random(seed)
    errs = pts = mem = 0
    for i in range(nonmembers):
        R = random_point(E, rng)
        for Q in (R, E.mul(h, R), E.mul(r, R), E.add(E.mul(h, R), E.mul(r, random_point(E, rng)))):
            truth = E.mul(r, Q) is None
            pts += 1
            mem += int(truth)
            errs += int(residue_member(Q) != truth)
    out.update({"points": pts, "members": mem, "errors": errs, "ops": {
        "two_legendre_symbols": {k: 2 * v for k, v in legendre_ops(p).items()}}})
    return out


def run(*, npoints: int = 1000, nother: int = 200, seed: int = 20261008, inputs: str = INPUTS_JSON,
        progress=print) -> dict:
    results = {}
    progress("BLS12-381 G1 (positive control)")
    results["BLS12-381 G1"] = bls12_381_control(npoints=max(npoints // 4, 50), nother=max(nother // 4, 20), seed=seed)

    progress("CP6-782 G1: building 4 + omega as 7.3.5")
    c = _arkworks("cp6_782")
    E = Curve(c["p"], c["a"], c["b"])
    alpha, phi, res = chain_alpha(E, c["n"], c["h"], -339, (4, 1), (7, 3, 5), "4 + omega as 7.3.5 (chain)")
    results["CP6-782 G1"] = analyse("CP6-782 G1", E, c["n"], c["h"], -339, alpha, phi,
                                    npoints=npoints, nother=nother, seed=seed)

    progress("Bandersnatch: building sqrt(-2) as one 2-isogeny")
    c = _arkworks("ed_on_bls12_381_bandersnatch")
    E = Curve(c["p"], c["a"], c["b"])
    alpha, phi, res = chain_alpha(E, c["n"], c["h"], -8, (0, 1), (2,), "sqrt(-2) as one 2-isogeny (chain)")
    out = analyse("Bandersnatch (short Weierstrass model)", E, c["n"], c["h"], -8, alpha, phi,
                  npoints=max(npoints // 4, 50), nother=max(nother // 4, 20), seed=seed)
    M = module_structure(-8, E.p, c["n"], c["h"], alpha)
    out["residue_test"] = residue_test_bandersnatch(E, c["n"], c["h"], -8, M.pim1, 50, seed)
    results["Bandersnatch"] = out

    with open(inputs) as fh:
        inp = json.load(fh)
    m = inp["curves"]["mnt1"]
    progress("mnt1: building omega as one 5-isogeny")
    E = Curve(int(m["p"], 16), int(m["a"], 16) % int(m["p"], 16), int(m["b"], 16))
    n, h = int(m["n"], 16), int(m["h"], 16)
    alpha, phi, res = chain_alpha(E, n, h, -19, (0, 1), (5,), "omega as one 5-isogeny (chain)")
    results["mnt1"] = analyse("mnt1", E, n, h, -19, alpha, phi, npoints=max(npoints // 4, 50),
                              nother=max(nother // 4, 20), seed=seed)
    return {"results": results, "chain_curve_cofactors": inp["chain_curve_cofactors"],
            "inputs_sources": inp["sources"], "npoints": npoints, "nother": nother, "seed": seed}


