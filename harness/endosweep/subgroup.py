def trial_primes(h: int, bound: int = 1 << 16) -> list[int]:
    out, m, d = [], h, 2
    while d < bound and d * d <= m:
        if m % d == 0:
            out.append(d)
            while m % d == 0:
                m //= d
        d += 1
    if 1 < m < bound:
        out.append(m)
    return out


def analyse(name: str, E: Curve, r: int, h: int, D: int, alpha: Alpha, phi, *,
            npoints: int, nother: int, seed: int, box: int = 4) -> dict:
    t0 = time.time()
    M = module_structure(D, E.p, r, h, alpha)
    ar = CV.arithmetic(E.p, E.a)
    mem_all = short_elements(M, alpha, "membership", box=box)
    clr_all = short_elements(M, alpha, "clearing", box=box)
    if not mem_all or not clr_all:
        raise RuntimeError("no valid element in the search box")

    def costed(c: Candidate) -> dict:
        ops = msm_ops(ar, c.c0, c.c1, alpha.cost)
        return {"c0": str(c.c0), "c1": str(c.c1), "height_bits": c.height_bits, "norm": str(c.norm),
                "kernel_order_on_E(F_q)": str(c.kernel), "eigenvalue_on_G": hex(c.eigenvalue),
                "gcd_shortcut_holds": c.gcd_shortcut, "ops": ops}

    mem = min(mem_all[:12], key=lambda c: msm_ops(ar, c.c0, c.c1, alpha.cost)["M_eq"])
    clr = min(clr_all[:12], key=lambda c: msm_ops(ar, c.c0, c.c1, alpha.cost)["M_eq"])
    small = trial_primes(h)
    pts = check_on_points(E, phi, r, h, mem, clr, M.effective_cofactor, npoints=npoints, nother=nother,
                          small_primes=small, seed=seed)
    tors = [torsion_count_check(E, D, M.pim1, ell) for ell in small if ell <= 64]
    base_r = scalar_ops(ar, r)
    base_h = scalar_ops(ar, h)
    eff_ops = scalar_ops(ar, M.effective_cofactor)
    mem_ops = msm_ops(ar, mem.c0, mem.c1, alpha.cost)
    clr_ops = msm_ops(ar, clr.c0, clr.c1, alpha.cost)
    half_r, half_h = log2(r) / 2, log2(h) / 2
    return {
        "curve": name, "p_bits": E.p.bit_length(), "r": hex(r), "r_bits": r.bit_length(), "h": hex(h),
        "h_bits": h.bit_length(), "D": D, "conductor_f": hex(M.f), "trace": hex(M.t),
        "arithmetic": ar.note, "alpha": {"label": alpha.label, "s": alpha.s, "b": alpha.b,
                                         "eigenvalue_on_G": hex(alpha.lam), "cost": alpha.cost},
        "frobenius_in_O": [str(M.pi[0]), str(M.pi[1])],
        "cofactor_group_invariants": [str(x) for x in M.cofactor_invariants],
        "effective_cofactor": hex(M.effective_cofactor),
        "effective_cofactor_bits": M.effective_cofactor.bit_length(),
        "small_primes_of_h": small,
        "torsion_checks": tors,
        "rr_basis_bits": [max(abs(x) for x in v).bit_length() for v in M.rr_basis],
        "J_basis_bits": [max(abs(x) for x in v).bit_length() for v in M.J_basis],
        "membership": {"chosen": costed(mem), "valid_in_box": len(mem_all),
                       "half_bits": round(half_r, 2), "excess_bits": round(mem.height_bits - half_r, 2),
                       "shortest_valid": costed(mem_all[0])},
        "clearing": {"chosen": costed(clr), "valid_in_box": len(clr_all),
                     "half_bits": round(half_h, 2), "excess_bits": round(clr.height_bits - half_h, 2),
                     "shortest_valid": costed(clr_all[0]),
                     "relation_to_h": f"beta(Q) = [{hex(clr.eigenvalue * pow(h, -1, r) % r)}]([h]Q)"},
        "costs_M_eq": {
            "[r]Q": base_r, "beta_membership": mem_ops,
            "[h]Q": base_h, "[effective cofactor]Q": eff_ops, "beta_clearing": clr_ops,
            "ratio_membership": round(base_r["M_eq"] / mem_ops["M_eq"], 3),
            "ratio_clearing_vs_h": round(base_h["M_eq"] / clr_ops["M_eq"], 3),
            "ratio_clearing_vs_effective": round(eff_ops["M_eq"] / clr_ops["M_eq"], 3),
        },
        "points": pts,
        "elapsed_s": round(time.time() - t0, 1),
    }


