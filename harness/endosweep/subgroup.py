"""Subgroup membership and cofactor clearing from the O-module structure of E(F_q).

Setting.  E/F_q ordinary, #E(F_q) = h*r with r prime, r not dividing h, G the
subgroup of order r.  The handed-in theorem is Lenstra's ("Complex
multiplication structure of elliptic curves", J. Number Theory 56 (1996)):
if End(E) = O then E(F_q) is isomorphic to O/(pi - 1)O as an O-module, pi
the Frobenius.  It is used here as a hypothesis and checked on points (every
prediction below is tested against [r]Q and [h]Q, and the size of
E(F_q)[ell] it predicts for each small ell | h is compared with an exact
count of rational ell-torsion points from the ell-division polynomial).

What follows from it, with I = (pi - 1)O = rr * J, rr the prime of norm r
that contains pi - 1 and J the cofactor part (rr + J = O since r does not
divide h):

* for any beta in O, multiplication by beta on O/I has kernel of order
  [O : beta*O + I] (Dedekind domain: |ker| = |O/I| / |image| and the image
  is (beta*O + I)/I).  ``element_index`` computes that index exactly as the
  gcd of the 2x2 minors of {beta, beta*omega, pi-1, (pi-1)*omega};
* **membership.**  If beta is in rr and [O : beta*O + I] = r then ker(beta)
  on E(F_q) is exactly G (it contains G and has r elements), so Q in G iff
  beta(Q) = O.  The only ideal between I and O of index r is rr (an ideal of
  norm r dividing rr*J with r not dividing N(J)), so the index condition is
  both necessary and sufficient; ``gcd(N(beta)/r, h) = 1`` is a sufficient
  shortcut for it, not a necessary one;
* **cofactor clearing.**  If [O : beta*O + I] = h then beta*O + I = J (again
  the only ideal of that index between I and O), so beta(E(F_q)) =
  J/I, which is the r-torsion G: beta maps E(F_q) ONTO G and its fibres are
  cosets of ker(beta).  On G it acts as the scalar c = beta mod rr, so
  beta(Q) = [c/h mod r]([h]Q) for every Q in E(F_q);
* the least positive rational integer in J is the exponent of the cofactor
  group O/J, i.e. the smallest integer "effective cofactor".

Short elements are found by LLL (``lattice.lll``) on the Z-bases of rr (the
GLV relation lattice {(c0, c1) : c0 + c1*lambda = 0 mod r}) and of J (from
(pi - 1) * conj(rr) / r), in coordinates c0 + c1*alpha with alpha the cheap
endomorphism actually evaluated (a unit, or a chain built by ``explicit``).
Costs are the cross-curve sweep's formula counts (``curvesweep``: the curve's
own doubling, add-2007-bl/madd-2007-bl, interleaved width-w NAF, the
optimised chain evaluator) applied to the exact digits of the fixed scalars:
**modelled**, not timed.

    python -m harness.endosweep.subgroup --out-dir research/endosweep_subgroup_20261008
"""
