def scalar_ops(ar: CV.Arith, k: int, widths=(2, 3, 4, 5, 6, 7)) -> dict:
    """Best width-w NAF [k]Q, M_eq = M + S, over widths and affine/Jacobian tables."""
    k = abs(k)
    best = None
    for table in ("affine", "jacobian"):
        for w in widths:
            if k == 0:
                continue
            M, S = CV.baseline_ops(ar, k, w, table)
            if best is None or M + S < best["M_eq"]:
                best = {"M": M, "S": S, "M_eq": M + S, "w": w, "table": table, "bits": k.bit_length()}
    return best or {"M": 0, "S": 0, "M_eq": 0, "w": None, "table": None, "bits": 0}


def msm_ops(ar: CV.Arith, c0: int, c1: int, chain: dict, widths=(2, 3, 4, 5, 6, 7)) -> dict:
    """[c0]Q + [c1]alpha(Q): interleaved width-w NAF with two tables plus one alpha evaluation."""
    if c1 == 0:
        return scalar_ops(ar, c0, widths)
    if c0 == 0:
        s = scalar_ops(ar, c1, widths)
        return {**s, "M": s["M"] + chain["M"], "S": s["S"] + chain["S"],
                "M_eq": s["M_eq"] + chain["M_eq"]}
    best = None
    for table in ("affine", "jacobian"):
        for w in widths:
            M, S = CV.glv_ops(ar, c0, c1, w, table, chain)
            if best is None or M + S < best["M_eq"]:
                best = {"M": M, "S": S, "M_eq": M + S, "w": w, "table": table,
                        "bits": max(abs(c0), abs(c1)).bit_length()}
    return best


def legendre_ops(p: int) -> dict:
    """A Legendre symbol by Fermat exponentiation to (p-1)/2 (square-and-multiply)."""
    e = (p - 1) // 2
    S, M = e.bit_length() - 1, bin(e).count("1") - 1
    return {"M": M, "S": S, "M_eq": M + S}


