def element_index(D: int, gens) -> int:
    """[O : sum g*O] for elements g = (a, b) = a + b*omega (0 if not full rank).

    The ideal generated by the g is the Z-span of {g, g*omega}; its index in
    Z^2 is the gcd of all 2x2 minors of those vectors.
    """
    vecs = []
    for g in gens:
        vecs.append(tuple(g))
        vecs.append(QO.multiply(D, tuple(g), (0, 1)))
    det = 0
    for i in range(len(vecs)):
        for j in range(i + 1, len(vecs)):
            det = gcd(det, vecs[i][0] * vecs[j][1] - vecs[i][1] * vecs[j][0])
    return det


def kernel_order(D: int, beta, pim1) -> int:
    """|ker beta| on E(F_q) = O/(pi - 1), by Lenstra's module structure."""
    return element_index(D, [beta, pim1])


def frobenius_element(D: int, q: int, t: int, f: int, lam_omega: int, r: int) -> tuple[int, int]:
    """pi = (t - f*tau)/2 +- f*omega, the sign that acts as 1 on G (where omega acts as lam_omega)."""
    tau = D % 2
    out = []
    for s in (f, -f):
        if (t - s * tau) % 2:
            continue
        a, b = (t - s * tau) // 2, s
        assert QO.norm(D, a, b) == q and QO.trace(D, a, b) == t
        if (a - 1 + b * lam_omega) % r == 0:
            out.append((a, b))
    if len(out) != 1:
        raise ValueError(f"Frobenius sign not pinned by the action on G ({len(out)} candidates)")
    return out[0]


def smith_invariants(basis) -> tuple[int, int]:
    """(d1, d2), d1 | d2, with Z^2 / span(basis) = Z/d1 x Z/d2."""
    (a, b), (c, d) = basis
    d1 = gcd(gcd(a, b), gcd(c, d))
    det = abs(a * d - b * c)
    return d1, det // d1


@dataclass
class Alpha:
    """The evaluated endomorphism alpha = s + b*omega (b = +-1), acting on G as lam."""
    s: int
    b: int
    lam: int
    cost: dict                       # {"M", "S", "M_eq"} of one evaluation
    label: str

    def to_omega(self, c0: int, c1: int) -> tuple[int, int]:
        return c0 + c1 * self.s, c1 * self.b

    def from_omega(self, a: int, b: int) -> tuple[int, int]:
        if b % self.b:
            raise ValueError("not in Z[alpha]")
        c1 = b // self.b
        return a - c1 * self.s, c1


@dataclass
class ModuleStructure:
    D: int
    q: int
    r: int
    h: int
    t: int
    f: int
    lam_omega: int
    pi: tuple[int, int]
    rr_basis: list[list[int]]          # LLL-reduced, alpha coordinates
    J_basis: list[list[int]]           # LLL-reduced, alpha coordinates
    cofactor_invariants: tuple[int, int]
    effective_cofactor: int            # least positive integer in J
    checks: dict = field(default_factory=dict)

    @property
    def pim1(self) -> tuple[int, int]:
        return self.pi[0] - 1, self.pi[1]


def module_structure(D: int, q: int, r: int, h: int, alpha: Alpha) -> ModuleStructure:
    t = q + 1 - h * r
    Dfrob = t * t - 4 * q
    if Dfrob % D:
        raise ValueError("t^2 - 4q is not a multiple of D")
    f2 = Dfrob // D
    f = isqrt(f2)
    if f * f != f2:
        raise ValueError("t^2 - 4q is not D times a square")
    if h % r == 0:
        raise ValueError("r divides h: the r-part is not O/rr")
    lam_omega = (alpha.lam - alpha.s) * alpha.b % r          # b = +-1
    tau, nw = QO.omega_trace_norm(D)
    assert (lam_omega * lam_omega - tau * lam_omega + nw) % r == 0, "lambda is not an eigenvalue of omega"
    pi = frobenius_element(D, q, t, f, lam_omega, r)
    pim1 = (pi[0] - 1, pi[1])
    # rr = r*O + (omega - lam_omega)*O; J = (pi - 1) * conj(rr) / r
    rr_w = [(r, 0), ((-lam_omega) % r, 1)]
    assert element_index(D, rr_w) == r
    J_w = []
    for g in rr_w:
        x = QO.multiply(D, pim1, QO.conjugate(D, *g))
        assert x[0] % r == 0 and x[1] % r == 0
        J_w.append((x[0] // r, x[1] // r))
    assert element_index(D, J_w) == h, "J does not have index h"
    assert element_index(D, J_w + [pim1]) == h, "pi - 1 is not in J"
    rr_a = LA.lll([list(alpha.from_omega(*g)) for g in rr_w])
    J_a = LA.lll([list(alpha.from_omega(*g)) for g in J_w])
    rr_a.sort(key=LA.l2_norm_sq)
    J_a.sort(key=LA.l2_norm_sq)
    inv = smith_invariants(J_w)
    # least positive integer in J: the generator of J cap Z = the exponent of O/J
    (a1, b1), (a2, b2) = J_w
    eff = abs(a1 * b2 - a2 * b1) // gcd(b1, b2)
    assert inv[1] == eff
    return ModuleStructure(D, q, r, h, t, f, lam_omega, pi, rr_a, J_a, inv, eff)


@dataclass
class Candidate:
    c0: int
    c1: int
    kernel: int                         # |ker| on E(F_q), Lenstra
    norm: int
    height_bits: int
    eigenvalue: int                     # action on G
    gcd_shortcut: bool                  # gcd(N/r, h) = 1 (membership) / N in the clearing sense


def short_elements(M: ModuleStructure, alpha: Alpha, which: str, *, box: int = 4) -> list[Candidate]:
    """Every c1*b1 + c2*b2 (|c_i| <= box) of the reduced basis that is a valid test.

    ``which = "membership"``: in rr with |ker| = r.  ``which = "clearing"``:
    |ker| = h, i.e. beta*O + (pi - 1) = J, so beta maps E(F_q) onto G.
    Sorted by height (max |c0|, |c1|) in alpha coordinates.
    """
    basis = M.rr_basis if which == "membership" else M.J_basis
    want = M.r if which == "membership" else M.h
    seen, out = set(), []
    for i in range(-box, box + 1):
        for j in range(-box, box + 1):
            c0 = i * basis[0][0] + j * basis[1][0]
            c1 = i * basis[0][1] + j * basis[1][1]
            if (c0, c1) == (0, 0) or (-c0, -c1) in seen:
                continue
            seen.add((c0, c1))
            w = alpha.to_omega(c0, c1)
            k = kernel_order(M.D, w, M.pim1)
            if k != want:
                continue
            N = QO.norm(M.D, *w)
            if which == "membership":
                sc = N % M.r == 0 and gcd(N // M.r, M.h) == 1
            else:
                sc = gcd(N, M.r) == 1
            out.append(Candidate(c0, c1, k, N, max(abs(c0), abs(c1)).bit_length(),
                                 (c0 + c1 * alpha.lam) % M.r, sc))
    out.sort(key=lambda c: (max(abs(c.c0), abs(c.c1)), abs(c.c0) + abs(c.c1)))
    return out


