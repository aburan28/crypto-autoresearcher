def eigenvalue_of(E: Curve, phi, P, n: int, candidates: list[int]) -> int | None:
    """Which candidate scalar c satisfies phi(P) = c*P?  (P of prime order n.)"""
    img = phi(P)
    for c in candidates:
        if E.mul(c % n, P) == img:
            return c % n
    return None


def _orbit_candidates(D: int, el: QO.RingElement, lam_w: int, n: int) -> dict[int, tuple[int, int]]:
    cands = {}
    for base in ((el.a, el.b), QO.conjugate(D, el.a, el.b)):
        for u in QO.units(D):
            a_, b_ = QO.multiply(D, base, u)
            cands[QO.eigenvalue(D, a_, b_, lam_w, n)] = (a_, b_)
    return cands


def verify_j0_pump(bits: int = 26, seed: int = 3, pump_power: int | None = None) -> dict:
    E, N, n, t = j0_curve_with_7_torsion(bits, seed)
    p = E.p
    F = E.F
    rec = {"p": p, "b": E.b, "order": N, "n": n, "trace": t, "checks": []}
    cof = N // n
    P = None
    s = seed
    while P is None or E.mul(n, P) is not None:
        s += 1
        P = E.mul(cof, E.point(s))
    # 1. zeta_3: (x, y) -> (beta x, y)
    beta = next(int(r) for r in nthroot_mod(1, 3, p, all_roots=True) if int(r) != 1)
    zeta = lambda Q: None if Q is None else (F.mul(beta, Q[0]), Q[1])  # noqa: E731
    lam_w_roots = QO.omega_eigenvalues(-3, n)          # eigenvalues of omega = zeta_6
    zeta3_roots = [(r - 1) % n for r in lam_w_roots]   # zeta_3 = omega - 1
    lam_z = eigenvalue_of(E, zeta, P, n, zeta3_roots)
    rec["checks"].append({"zeta_3 eigenvalue predicted": lam_z is not None, "lambda_zeta3": lam_z})
    assert lam_z is not None
    lam_w = (lam_z + 1) % n
    # 2. degree-7 endomorphism 2 + omega from the rational 7-torsion
    K = None
    s = 0
    while K is None:
        s += 1
        K = E.mul(N // 7, E.point(100 + s))
    assert E.mul(7, K) is None
    velu = VeluMap(E, K, 7)
    E2 = velu.codomain
    assert E2.j() == E.j() == 0, "codomain of the 7-kernel is not j=0"
    iso = isomorphism_to(E2, E)
    assert iso is not None, "codomain is the twist, not the curve itself"
    alpha = Composite([velu, iso])
    cands = _orbit_candidates(-3, QO.RingElement(-3, 2, 1), lam_w, n)
    lam_a = eigenvalue_of(E, alpha, P, n, list(cands))
    rec["checks"].append({"degree-7 endomorphism eigenvalue matches a+b*lambda_omega": lam_a is not None,
                          "element": cands.get(lam_a), "lambda_alpha": lam_a})
    assert lam_a is not None
    a_, b_ = cands[lam_a]
    # 3. pump: alpha^j with height about n^(1/4)
    bits_n = n.bit_length() - 1
    if pump_power is None:
        pump_power = max(1, round(bits_n / 4 / 1.4))
    j = pump_power
    aj, bj = QO.power(-3, (a_, b_), j)
    pump = Composite([alpha] * j)
    lam_pump_pred = QO.eigenvalue(-3, aj, bj, lam_w, n)
    F.reset()
    img = pump(P)
    pump_ops = F.snapshot()
    ok = E.mul(lam_pump_pred, P) == img
    rec["checks"].append({"alpha^j eigenvalue = predicted": ok, "j": j, "height": QO.height(aj, bj),
                          "predicted_height_bits": QO.height(aj, bj).bit_length(), "n_bits": bits_n,
                          "affine_ops_pump": pump_ops})
    assert ok
    # 5. 4-dim decomposition {1, zeta, alpha^j, zeta*alpha^j}
    gens = [1, lam_z, lam_pump_pred, lam_z * lam_pump_pred % n]
    red = LA.reduce(gens, n)
    cb = LA.coefficient_bits(red, samples=16, seed=seed)
    rng = random.Random(seed + 7)
    worst = 0
    images = [P, zeta(P), img, zeta(img)]
    for _ in range(8):
        k = rng.randrange(1, n)
        ks = red.decompose(k)
        worst = max(worst, max(abs(v) for v in ks))
        lhs = E.mul(k, P)
        rhs = None
        for ki, Qi in zip(ks, images):
            rhs = E.add(rhs, E.mul(ki, Qi))
        assert lhs == rhs, "4-dim decomposition with explicit maps failed"
    rec["checks"].append({"4-dim decomposition reconstructs k*P (8 random k)": True,
                          "max_coeff_bits": worst.bit_length(), "babai_bound_bits": cb["bound_bits"],
                          "balanced_bits": cb["balanced_bits"], "basis_inf_norm_bits": cb["basis_inf_norm_bits"]})
    # 6. op counts: plain double-and-add of a full scalar vs the pump
    F.reset()
    E.mul(rng.randrange(1, n), P)
    rec["affine_ops_double_and_add_full_scalar"] = F.snapshot()
    rec["affine_ops_pump"] = pump_ops
    return rec


def verify_cm23_cycle(bits: int = 26, seed: int = 5) -> dict:
    E, N, n, t, js = cm23_curve(bits, seed)
    p = E.p
    rec = {"p": p, "a": E.a, "b": E.b, "order": N, "n": n, "trace": t, "j_cycle": js, "checks": []}
    cof = N // n
    s = seed
    P = None
    while P is None or E.mul(n, P) is not None:
        s += 1
        P = E.mul(cof, E.point(s))
    jset = set(js)
    paths = []

    def walk(cur: Curve, maps, prev_j, depth):
        if depth == 3:
            if cur.j() == E.j():
                paths.append(list(maps))
            return
        for T2 in _two_torsion_points(cur):
            v = VeluMap(cur, T2, 2)
            cj = v.codomain.j()
            if cj not in jset or cj == prev_j or cj == cur.j():
                continue
            walk(v.codomain, maps + [v], cur.j(), depth + 1)

    walk(E, [], None, 0)
    assert paths, "no closed 3-walk found: class polynomial or cycle logic wrong"
    found = None
    beta = QO.smallest_principal_power(-23, 2)        # 1 + omega, norm 8, class order 3
    assert beta is not None and beta.norm == 8
    lam_w_roots = QO.omega_eigenvalues(-23, n)
    for path in paths:
        last = path[-1].codomain
        iso = isomorphism_to(last, E)
        if iso is None:
            continue
        phi = Composite(path + [iso])
        for lam_w in lam_w_roots:
            cands = _orbit_candidates(-23, beta, lam_w, n)
            lam = eigenvalue_of(E, phi, P, n, list(cands))
            if lam is not None:
                found = (path, lam, cands[lam], lam_w)
                break
        if found:
            break
    rec["checks"].append({"2-isogeny 3-cycle is an endomorphism with eigenvalue of 1+omega (or conjugate/unit)":
                          found is not None,
                          "element": found[2] if found else None, "lambda": found[1] if found else None,
                          "paths_found": len(paths)})
    assert found is not None
    path, lam, (a_, b_), lam_w = found
    j = 3
    aj, bj = QO.power(-23, (a_, b_), j)
    phi = Composite(path + [isomorphism_to(path[-1].codomain, E)])
    pump = Composite([phi] * j)
    pred = QO.eigenvalue(-23, aj, bj, lam_w, n)
    ok = E.mul(pred, P) == pump(P)
    rec["checks"].append({"cycle^3 eigenvalue = predicted": ok, "height_of_cycle^3": QO.height(aj, bj),
                          "degree": 8 ** j})
    assert ok
    red = LA.reduce([1, lam], n)
    cb = LA.coefficient_bits(red, samples=16, seed=seed)
    rec["checks"].append({"GLV-2 with the degree-8 cycle endomorphism": True,
                          "coeff_bits_bound": cb["bound_bits"], "balanced_bits": cb["balanced_bits"]})
    return rec


def main(argv=None) -> int:
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--bits", type=int, default=26)
    ap.add_argument("--out", default=None)
    args = ap.parse_args(argv)
    out = {"j0_pump": verify_j0_pump(args.bits), "cm23_cycle": verify_cm23_cycle(args.bits)}
    txt = json.dumps(out, indent=1, default=str)
    if args.out:
        with open(args.out, "w") as f:
            f.write(txt)
    print(txt)
    return 0


