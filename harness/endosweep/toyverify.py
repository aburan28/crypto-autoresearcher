def _two_torsion_points(E: Curve):
    from sympy import Poly, symbols
    x = symbols("x")
    roots = Poly(x ** 3 + E.a * x + E.b, x, modulus=E.p).ground_roots()
    return [(int(r) % E.p, 0) for r in roots]


def j0_curve_with_7_torsion(bits: int, seed: int = 1):
    """A curve y^2 = x^3 + b over F_p, p = 1 mod 3, with #E = 7 * c * n, n prime.

    The six twists of j = 0 have traces +-A, +-(A+3B)/2, +-(A-3B)/2 where
    4p = A^2 + 3B^2; we pick p, then the twist, by testing group orders.
    """
    rng = random.Random(seed)
    while True:
        p = nextprime(rng.randrange(1 << (bits - 1), 1 << bits))
        if p % 3 != 1:
            continue
        el = QO.cornacchia_element(-3, p)
        if el is None:
            continue
        A, B = 2 * el.a + el.b, el.b             # 4p = A^2 + 3B^2
        traces = set()
        for s1 in (1, -1):
            traces.add(s1 * A)
            if (A + 3 * B) % 2 == 0:
                traces.add(s1 * (A + 3 * B) // 2)
            if (A - 3 * B) % 2 == 0:
                traces.add(s1 * (A - 3 * B) // 2)
        cands = [(t, p + 1 - t) for t in traces if (p + 1 - t) % 7 == 0]
        good = []
        for t, N in cands:
            m = N // 7
            while m % 2 == 0:
                m //= 2
            while m % 3 == 0:
                m //= 3
            if isprime(m) and m > 4 * (p ** 0.5) and m > 1000:
                good.append((t, N, m))
        if not good:
            continue
        for b in range(1, 200):
            E = Curve(p, 0, b)
            P = E.point(seed)
            for t, N, n in good:
                if E.mul(N, P) is None and E.mul(N // n, P) is not None:
                    return E, N, n, t


HILBERT_CLASS_POLY_M23 = [1, 3491750, -5151296875, 12771880859375]   # H_{-23}(x), degree 3


def cm23_curve(bits: int, seed: int = 1):
    """A curve with CM by the maximal order of Q(sqrt(-23)) (h = 3) over F_p.

    Roots of the Hilbert class polynomial H_{-23} mod p give the three
    j-invariants of the 2-isogeny 3-cycle; 4p = A^2 + 23 B^2 gives the trace.
    The class polynomial is verified, not trusted: the trace found by testing
    the group order must satisfy t^2 - 4p = -23 f^2.
    """
    from sympy import Poly, symbols
    x = symbols("x")
    rng = random.Random(seed)
    while True:
        p = nextprime(rng.randrange(1 << (bits - 1), 1 << bits))
        el = QO.cornacchia_element(-23, p)
        if el is None:
            continue
        A = 2 * el.a + el.b
        roots = Poly(sum(c * x ** (3 - i) for i, c in enumerate(HILBERT_CLASS_POLY_M23)), x,
                     modulus=p).ground_roots()
        js = [int(r) % p for r in roots]
        if len(js) != 3:
            continue
        for t in (A, -A):
            N = p + 1 - t
            m = N
            for q in (2, 2, 2, 3):
                if m % q == 0:
                    m //= q
            if not (isprime(m) and m > 4 * p ** 0.5 and m > 1000):
                continue
            n = m
            j0 = js[0]
            k = j0 * pow((1728 - j0) % p, -1, p) % p
            a0, b0 = 3 * k % p, 2 * k % p
            for tw in range(1, 50):
                E = Curve(p, a0 * tw ** 2 % p, b0 * tw ** 3 % p)
                P = E.point(seed)
                if E.mul(N, P) is None and E.mul(N // n, P) is not None:
                    assert (t * t - 4 * p) % 23 == 0
                    f2 = (4 * p - t * t) // 23
                    f = int(round(f2 ** 0.5))
                    assert f * f == f2, "trace does not match CM by -23: class polynomial wrong?"
                    return E, N, n, t, js


