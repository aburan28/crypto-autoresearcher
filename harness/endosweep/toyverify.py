"""Toy-scale EXPLICIT verification of what the sweeper models.

The sweeper reasons about eigenvalues, heights and lattices.  This module
builds the actual rational maps on small curves and checks, by evaluating
them on points, that

1. the unit automorphism zeta_3 on a j = 0 curve acts on the prime-order
   subgroup as one of the two roots the sweeper predicts;
2. a degree-7 endomorphism 2 + omega of Z[zeta_6], built by Velu's formulas
   from the rational 7-torsion and an isomorphism back to the curve, is an
   endomorphism with the predicted eigenvalue a + b*lambda_omega;
3. iterating it j times (an isogeny-cycle "pump") gives the eigenvalue
   lambda^j and the height the sweeper computes with ``quadorder.power``;
4. on a curve with CM by the class-number-3 order Z[(1+sqrt(-23))/2], the
   closed walk of three 2-isogenies is an endomorphism of degree 8 whose
   eigenvalue matches 1 + omega (the generator of the first principal power
   of a prime above 2) -- i.e. ``smallest_principal_power`` describes a
   real map;
5. the 4-dimensional decomposition {1, u, alpha, u*alpha} reconstructs k*P
   from explicit endomorphism images for random k, with every coefficient
   within the lattice's Babai bound;
6. affine operation counts of a plain double-and-add versus the pump are
   recorded (toy affine formulas; the cost model in ``costmodel.py`` uses
   projective counts and is NOT calibrated from these numbers).

Everything is deterministic (fixed seeds) and prints a JSON-able record.
"""
from __future__ import annotations

import json
import random
from dataclasses import dataclass

from sympy import isprime, nextprime
from sympy.ntheory import sqrt_mod
from sympy.ntheory.residue_ntheory import nthroot_mod

from . import lattice as LA
from . import quadorder as QO


# ---------------------------------------------------------------------------
# counted affine arithmetic
# ---------------------------------------------------------------------------

@dataclass
class Counter:
    p: int
    M: int = 0
    S: int = 0
    I: int = 0

    def mul(self, a, b):
        self.M += 1
        return a * b % self.p

    def sqr(self, a):
        self.S += 1
        return a * a % self.p

    def inv(self, a):
        self.I += 1
        return pow(a % self.p, -1, self.p)

    def snapshot(self):
        return {"M": self.M, "S": self.S, "I": self.I}

    def reset(self):
        self.M = self.S = self.I = 0


class Curve:
    """y^2 = x^3 + a x + b over F_p, affine, with counted field operations."""

    def __init__(self, p: int, a: int, b: int, F: Counter | None = None):
        self.p, self.a, self.b = p, a % p, b % p
        self.F = F or Counter(p)
        if (4 * self.a ** 3 + 27 * self.b ** 2) % p == 0:
            raise ValueError("singular")

    def on_curve(self, P):
        if P is None:
            return True
        x, y = P
        return (y * y - x * x * x - self.a * x - self.b) % self.p == 0

    def j(self):
        p, a, b = self.p, self.a, self.b
        num = 1728 * 4 * a ** 3
        den = (4 * a ** 3 + 27 * b ** 2) % p
        return num * pow(den, -1, p) % p

    def neg(self, P):
        return None if P is None else (P[0], (-P[1]) % self.p)

    def add(self, P, Q):
        F, p = self.F, self.p
        if P is None:
            return Q
        if Q is None:
            return P
        x1, y1 = P
        x2, y2 = Q
        if x1 == x2:
            if (y1 + y2) % p == 0:
                return None
            lam = F.mul((3 * F.sqr(x1) + self.a) % p, F.inv(2 * y1))
        else:
            lam = F.mul((y2 - y1) % p, F.inv(x2 - x1))
        x3 = (F.sqr(lam) - x1 - x2) % p
        y3 = (F.mul(lam, (x1 - x3) % p) - y1) % p
        return (x3, y3)

    def mul(self, k, P):
        if k < 0:
            return self.mul(-k, self.neg(P))
        R, Q = None, P
        while k:
            if k & 1:
                R = self.add(R, Q)
            Q = self.add(Q, Q)
            k >>= 1
        return R

    def lift_x(self, x):
        rhs = (x * x * x + self.a * x + self.b) % self.p
        y = sqrt_mod(rhs, self.p)
        return None if y is None else (x, int(y))

    def point(self, seed: int):
        rng = random.Random(seed)
        while True:
            P = self.lift_x(rng.randrange(1, self.p))
            if P is not None:
                return P


# ---------------------------------------------------------------------------
# Velu for odd prime kernels and for 2-torsion kernels (counted)
# ---------------------------------------------------------------------------

class VeluMap:
    """E -> E' with kernel generated by K (order ell).  Evaluates with counting."""

    def __init__(self, E: Curve, K, ell: int):
        self.E, self.ell = E, ell
        p, a, b = E.p, E.a, E.b
        self.terms = []     # (xq, vq, uq)
        v = w = 0
        if ell == 2:
            xq, yq = K
            assert yq == 0
            gx = (3 * xq * xq + a) % p
            vq, uq = gx, 0
            self.terms.append((xq, vq, uq))
            v, w = vq, (uq + xq * vq) % p
        else:
            Q = K
            for _ in range((ell - 1) // 2):
                xq, yq = Q
                gx = (3 * xq * xq + a) % p
                gy = (-2 * yq) % p
                vq = 2 * gx % p
                uq = gy * gy % p
                self.terms.append((xq, vq, uq))
                v = (v + vq) % p
                w = (w + uq + xq * vq) % p
                Q = E.add(Q, K)
        self.codomain = Curve(p, (a - 5 * v) % p, (b - 7 * w) % p, E.F)

    def __call__(self, P):
        if P is None:
            return None
        F, p = self.E.F, self.E.p
        x, y = P
        X, Y = x, y
        for (xq, vq, uq) in self.terms:
            if (x - xq) % p == 0:
                return None
            d = F.inv(x - xq)
            d2 = F.sqr(d)
            X = (X + F.mul(vq, d) + F.mul(uq, d2)) % p
            yd2 = F.mul(y, d2)
            Y = (Y - 2 * F.mul(uq, F.mul(yd2, d)) - F.mul(vq, yd2)) % p
        return (X, Y)


class Isomorphism:
    """(x, y) -> (u^2 x, u^3 y) from y^2 = x^3 + a x + b to y^2 = x^3 + a u^4 x + b u^6."""

    def __init__(self, E: Curve, u: int):
        self.E, self.u = E, u % E.p
        p = E.p
        self.u2, self.u3 = self.u * self.u % p, self.u ** 3 % p
        self.codomain = Curve(p, E.a * self.u ** 4 % p, E.b * self.u ** 6 % p, E.F)

    def __call__(self, P):
        if P is None:
            return None
        return (self.E.F.mul(self.u2, P[0]), self.E.F.mul(self.u3, P[1]))


def isomorphism_to(E1: Curve, E2: Curve):
    """An F_p-isomorphism E1 -> E2 (same j), or None if they are twists."""
    p = E1.p
    if E1.a == 0 and E2.a == 0:
        ratio = E2.b * pow(E1.b, -1, p) % p
        for u in nthroot_mod(ratio, 6, p, all_roots=True) or []:
            iso = Isomorphism(E1, int(u))
            if (iso.codomain.a, iso.codomain.b) == (E2.a, E2.b):
                return iso
        return None
    if E1.a and E2.a and E1.b and E2.b:
        r = E2.b * pow(E1.b, -1, p) * E1.a * pow(E2.a, -1, p) % p
        u = sqrt_mod(r, p)
        if u is None:
            return None
        for cand in (int(u), (-int(u)) % p):
            iso = Isomorphism(E1, cand)
            if (iso.codomain.a, iso.codomain.b) == (E2.a, E2.b):
                return iso
    return None


class Composite:
    def __init__(self, maps):
        self.maps = maps

    def __call__(self, P):
        for m in self.maps:
            P = m(P)
        return P


