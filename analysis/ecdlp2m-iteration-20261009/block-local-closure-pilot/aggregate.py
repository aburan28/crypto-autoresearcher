#!/usr/bin/env python3
"""aggregate.py -- PILOT #3 (block-local closure). Rebuilds aggregate.md from
results/*.jsonl. Clopper-Pearson 95% intervals by exact binomial bisection
(stdlib only). EXPLORATORY; not program evidence."""
import glob
import json
import statistics as st
from collections import defaultdict
from math import comb
from pathlib import Path

HERE = Path(__file__).resolve().parent


def binom_cdf(k, n, p):
    return sum(comb(n, i) * p ** i * (1 - p) ** (n - i) for i in range(k + 1))


def clopper_pearson(x, n, alpha=0.05):
    if n == 0:
        return (float("nan"), float("nan"))
    lo, hi = 0.0, 1.0
    if x > 0:
        a, b = 0.0, 1.0
        for _ in range(60):
            mid = (a + b) / 2
            if 1 - binom_cdf(x - 1, n, mid) < alpha / 2:
                a = mid
            else:
                b = mid
        lo = a
    if x < n:
        a, b = 0.0, 1.0
        for _ in range(60):
            mid = (a + b) / 2
            if binom_cdf(x, n, mid) < alpha / 2:
                b = mid
            else:
                a = mid
        hi = b
    return lo, hi


def fmt_ci(x, n):
    lo, hi = clopper_pearson(x, n)
    return f"{x}/{n} [{lo:.2f}, {hi:.2f}]" if n else "—"


def main():
    rows = []
    for f in sorted(glob.glob(str(HERE / "results" / "*.jsonl"))):
        rows += [json.loads(l) for l in open(f)]
    cells = {}
    for r in rows:
        cells.setdefault((r["m"], r["n"]), (r["k"], r["N"], r["nblocks"]))
    order = ["full", "L1", "L2", "L3", "adj0", "adj1", "L1adj0", "L2adj1"]
    out = ["# Block-local degree-4 closure: aggregate (exploratory, not program evidence)", "",
           "Regenerated by `python3 aggregate.py` from `results/*.jsonl`. One row per (cell, variant).",
           "Columns: ncols (all variants of a cell share it per instance; shown once), column reduction vs `full`,",
           "UNSAT refuted x/y with Clopper-Pearson 95% CI, SAT false refutations x/y with CP 95% CI,",
           "codim = ncols - rank on SAT instances vs the number of Boolean solutions (`nsol`), median wall / peak RSS",
           "of the worker process (one process per job, host shared with two other pilots: upper bounds).",
           "`L2` at m = 3 is identical to `full` (two blocks) and was not run separately.", ""]
    out.append("| cell | k, N, blocks | variant | ncols (reduction) | UNSAT refuted [CP95] | SAT false refut. [CP95] | SAT codim = nsol | median wall UNSAT / SAT | median RSS MB | median rows UNSAT / SAT | products dropped (median, UNSAT) | incomplete |")
    out.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for (m, n), (k, N, nb) in sorted(cells.items()):
        byv = defaultdict(list)
        for r in rows:
            if (r["m"], r["n"]) == (m, n):
                byv[r["variant"]].append(r)
        fullcols = None
        fr = [r for r in byv.get("full", []) if r.get("status") == "completed"]
        if fr:
            fullcols = fr[0]["ncols"]
        for v in order:
            if v not in byv:
                continue
            rs = byv[v]
            done = [r for r in rs if r.get("status") == "completed"]
            inc = len(rs) - len(done)
            U = [r for r in done if r["label"] == "UNSAT"]
            S = [r for r in done if r["label"] == "SAT"]
            cols = done[0]["ncols"] if done else None
            red = f"{cols} ({100.0 * (1 - cols / fullcols):.0f}% fewer)" if cols and fullcols and v != "full" else (str(cols) if cols else "—")
            cod = f"{sum(1 for r in S if r['codim'] == r['nsol'])}/{len(S)}" if S else "—"
            med = lambda L, key: (f"{st.median(r[key] for r in L):.1f}" if L else "—")
            medi = lambda L, key: (f"{int(st.median(r[key] for r in L))}" if L else "—")
            out.append(f"| m={m} n={n} | {k}, {N}, {nb} | {v} | {red} | {fmt_ci(sum(r['contains_one'] for r in U), len(U))} | "
                       f"{fmt_ci(sum(r['contains_one'] for r in S), len(S))} | {cod} | {med(U, 'wall_s')} s / {med(S, 'wall_s')} s | "
                       f"{med(done, 'peak_rss_mb')} | {medi(U, 'rows')} / {medi(S, 'rows')} | {medi(U, 'products_dropped')} | {inc} |")
    # soundness summary
    sat = [r for r in rows if r["label"] == "SAT" and r.get("status") == "completed"]
    out += ["", f"Soundness: SAT instances completed = {len(sat)}, with contains_one = {sum(r['contains_one'] for r in sat)}, "
            f"basis rows not vanishing at a known solution = {sum(sum(r.get('eval_rows_not_vanishing', [])) for r in sat)} "
            f"(witness evaluations = {sum(len(r.get('eval_rows_not_vanishing', [])) for r in sat)})."]
    pooled_u = [r for r in rows if r["label"] == "UNSAT" and r.get("status") == "completed"]
    out.append("")
    out.append("Pooled over cells (m = 3 and 4), per variant: UNSAT refuted / SAT false refutations.")
    for v in order:
        U = [r for r in pooled_u if r["variant"] == v]
        S = [r for r in sat if r["variant"] == v]
        if U or S:
            out.append(f"- {v}: UNSAT {fmt_ci(sum(r['contains_one'] for r in U), len(U))}; SAT false {fmt_ci(sum(r['contains_one'] for r in S), len(S))}")
    # instances where a local variant failed
    out.append("")
    fails = [(r["id"], r["variant"]) for r in pooled_u if not r["contains_one"]]
    out.append("UNSAT instances NOT refuted by some variant: " + (", ".join(f"{i} ({v})" for i, v in fails) if fails else "none"))
    (HERE / "aggregate.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
