#!/usr/bin/env python3
"""export.py -- PILOT #2 (m45closure). Reads results/*.jsonl and instances/*.json,
writes data.csv (one row per instance x closure) and aggregate.md (per cell)."""
import csv
import glob
import json
import math
import os
import statistics
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))


def binom_cdf(k, n, p):
    return sum(math.comb(n, i) * p ** i * (1 - p) ** (n - i) for i in range(k + 1))


def cp95(x, n):
    """Clopper-Pearson 95% interval for x successes of n, by bisection."""
    if n == 0:
        return (float("nan"), float("nan"))
    lo = 0.0 if x == 0 else _bisect(lambda p: 1 - binom_cdf(x - 1, n, p) - 0.025)
    hi = 1.0 if x == n else _bisect(lambda p: binom_cdf(x, n, p) - 0.025)
    return lo, hi


def _bisect(f, a=0.0, b=1.0):
    fa = f(a)
    for _ in range(60):
        m = (a + b) / 2
        fm = f(m)
        if (fm > 0) == (fa > 0):
            a, fa = m, fm
        else:
            b = m
    return (a + b) / 2


def main():
    rows = []
    for f in sorted(glob.glob(os.path.join(HERE, "results", "*.jsonl"))):
        cell = os.path.basename(f)[:-6]
        for line in open(f):
            r = json.loads(line)
            r["cell"] = cell
            rows.append(r)
    fields = ["cell", "m", "n", "k", "N", "id", "family", "label", "nsol", "kind", "D", "status", "contains_one",
              "rank", "ncols", "codim", "rows", "n_iterations", "wall_s", "peak_rss_mb", "elimination_faults",
              "ech_evalcheck_mismatch", "eval_rows_not_vanishing_sum", "dropped_terms_above_D", "mem_cap_gb",
              "timeout_s", "nworkers", "elimination", "m4ri_library"]
    with open(os.path.join(HERE, "data.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields, extrasaction="ignore")
        w.writeheader()
        for r in rows:
            r.setdefault("m", 3)
            r["codim"] = (r["ncols"] - r["rank"]) if r.get("status") == "completed" and r.get("ncols") else ""
            r["n_iterations"] = len(r["iterations"]) if isinstance(r.get("iterations"), list) else ""
            ev = r.get("eval_rows_not_vanishing")
            r["eval_rows_not_vanishing_sum"] = sum(ev) if isinstance(ev, list) else ""
            r["wall_s"] = round(r["wall_s"], 2) if isinstance(r.get("wall_s"), (int, float)) else r.get("outer_wall_s")
            r["peak_rss_mb"] = round(r["peak_rss_mb"], 1) if isinstance(r.get("peak_rss_mb"), (int, float)) else ""
            r["elimination"] = r.get("elimination", "myclosure" if str(r.get("kind", "")).startswith("my") else "")
            w.writerow(r)
    # ---- aggregate ----
    out = []
    out.append("# aggregate.md -- PILOT #2 (m45closure), regenerated by `python3 export.py`\n")
    out.append("Exploratory, hypothesis-generating; not program evidence. One row per (cell, family, closure).\n")
    out.append("UNSAT refuted = instances labelled UNSAT by both enumerators on which the closure contains 1 "
               "(Clopper-Pearson 95% in brackets). SAT refuted must be 0. NULL = support-matched null, NULL2 = dense "
               "matched null (label 'unenumerated' where 2^N enumeration was infeasible: such rows are listed as `?`).\n")
    cells = sorted({r["cell"] for r in rows})
    for cell in cells:
        crow = [r for r in rows if r["cell"] == cell]
        inst_file = os.path.join(HERE, "instances", f"{cell}.json")
        if cell.startswith("repro-"):
            inst_file = os.path.join(HERE, "instances", cell[len("repro-m3-"):] + ".json")
        hdr = ""
        if os.path.exists(inst_file):
            c = json.load(open(inst_file))
            ins = [x for x in c["instances"] if not x["dup_target"]]
            nU = sum(1 for x in ins if x["nsol"] == 0); nS = len(ins) - nU
            m = c.get("m", 3)
            hdr = (f"m={m} n={c['n']} k={c['k']} N={ins[0]['N']} neq={ins[0].get('neq', '')} curve b={c['b']} q={c['q']} "
                   f"| labelled distinct targets: {len(ins)} ({nU} UNSAT, {nS} SAT); enumerator disagreements: "
                   f"{sum(not x['enum_agree'] for x in ins)}; eval failures: {sum(not x['eval_ok'] for x in ins)}")
            pcs = [v for x in ins for v in x.get("point_check", [])]
            if pcs:
                hdr += f"; point-level check of solutions: {sum(pcs)}/{len(pcs)}"
        out.append(f"\n## {cell}\n\n{hdr}\n")
        out.append("| family | closure | columns | UNSAT refuted [CP95] | SAT refuted | unlabelled refuted | censored | n | median wall s | max wall s | median RSS MB | max RSS MB | elim faults | evalcheck mism. | witness rows not vanishing |")
        out.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
        agg = defaultdict(list)
        for r in crow:
            agg[(r["family"], r["kind"], r["D"])].append(r)
        for key in sorted(agg, key=lambda t: (t[0], t[2], t[1])):
            rs = agg[key]
            comp = [r for r in rs if r.get("status") == "completed"]
            cens = len(rs) - len(comp)
            U = [r for r in comp if r["nsol"] == 0 and r.get("label", "enumerated") == "enumerated"]
            S = [r for r in comp if r["nsol"] > 0]
            Q = [r for r in comp if r.get("label") == "unenumerated"]
            uref = sum(bool(r["contains_one"]) for r in U); sref = sum(bool(r["contains_one"]) for r in S)
            qref = sum(bool(r["contains_one"]) for r in Q)
            lo, hi = cp95(uref, len(U))
            cp = f"[{lo:.2f},{hi:.2f}]" if U else ""
            walls = [r["wall_s"] for r in comp if isinstance(r.get("wall_s"), (int, float))]
            rss = [r["peak_rss_mb"] for r in comp if isinstance(r.get("peak_rss_mb"), (int, float))]
            cols = sorted({r.get("ncols") for r in comp if r.get("ncols")})
            faults = sum(r.get("elimination_faults", 0) or 0 for r in comp)
            mism = sum(r.get("ech_evalcheck_mismatch", 0) or 0 for r in comp)
            bad = sum(sum(r["eval_rows_not_vanishing"]) for r in comp if isinstance(r.get("eval_rows_not_vanishing"), list))
            out.append(f"| {key[0]} | {key[1]}{key[2]} | {','.join(map(str, cols))} | {uref}/{len(U)} {cp} | {sref}/{len(S)} | "
                       f"{(str(qref) + '/' + str(len(Q))) if Q else '-'} | {cens} | {len(rs)} | "
                       f"{statistics.median(walls):.1f} | {max(walls):.1f} | {statistics.median(rss):.0f} | {max(rss):.0f} | "
                       f"{faults} | {mism} | {bad} |" if walls else
                       f"| {key[0]} | {key[1]}{key[2]} | - | 0/0 | 0/0 | - | {cens} | {len(rs)} | - | - | - | - | - | - | - |")
        # minimal refuting degree per UNSAT S3 instance over the W closures run
        byid = defaultdict(dict)
        for r in crow:
            if r["family"] == "S3" and r["nsol"] == 0 and r["kind"] == "W" and r.get("status") == "completed":
                byid[r["id"]][r["D"]] = bool(r["contains_one"])
        dist = defaultdict(int)
        for iid, dd in byid.items():
            ref = [D for D, one in dd.items() if one]
            if ref:
                dist[f"{min(ref)}"] += 1
            else:
                dist[f">{max(dd)}"] += 1
        if dist:
            out.append(f"\nMinimal refuting degree over the W_D run (UNSAT S3 instances, by M4RI closure): "
                       + ", ".join(f"D={k}: {v}" for k, v in sorted(dist.items())) + ".")
        # codim vs nsol on SAT instances (W closures, completed, not containing one)
        cod = [(r["ncols"] - r["rank"], r["nsol"], r["kind"], r["D"]) for r in crow
               if r["family"] == "S3" and r["nsol"] > 0 and r.get("status") == "completed" and r["kind"] in ("W", "myW")]
        if cod:
            byD = defaultdict(lambda: [0, 0])
            for c, s, kd, D in cod:
                byD[f"{kd}{D}"][0] += (c == s); byD[f"{kd}{D}"][1] += 1
            out.append("codim(W_D) == #solutions on SAT S3 instances: " + ", ".join(f"{k}: {v[0]}/{v[1]}" for k, v in sorted(byD.items())) + ".")
    open(os.path.join(HERE, "aggregate.md"), "w").write("\n".join(out) + "\n")
    print(f"{len(rows)} rows -> data.csv, aggregate.md")


if __name__ == "__main__":
    main()
