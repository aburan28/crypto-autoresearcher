#!/usr/bin/env python3
"""aggregate.py -- regenerates aggregate.md from results/*.jsonl (LEADS PILOT #4; exploratory)."""
import json, glob, hashlib
from pathlib import Path
from math import comb
HERE = Path(__file__).resolve().parent
def med(v): v = sorted(v); return v[len(v) // 2] if v else None
def cp(k, n):  # exact Clopper-Pearson 95%
    from math import lgamma, exp, log
    def bt(x, a, b):  # regularized incomplete beta via continued fraction (Numerical Recipes)
        if x <= 0: return 0.0
        if x >= 1: return 1.0
        lb = lgamma(a + b) - lgamma(a) - lgamma(b) + a * log(x) + b * log(1 - x)
        def cf(x, a, b):
            qab, qap, qam = a + b, a + 1, a - 1; c, d = 1.0, 1 - qab * x / qap
            d = 1 / (d if abs(d) > 1e-30 else 1e-30); h = d
            for m in range(1, 300):
                m2 = 2 * m; aa = m * (b - m) * x / ((qam + m2) * (a + m2))
                d = 1 + aa * d; d = 1 / (d if abs(d) > 1e-30 else 1e-30); c = 1 + aa / c if abs(1 + aa / c) > 1e-30 else 1e-30; h *= d * c
                aa = -(a + m) * (qab + m) * x / ((a + m2) * (qap + m2))
                d = 1 + aa * d; d = 1 / (d if abs(d) > 1e-30 else 1e-30); c = 1 + aa / c if abs(1 + aa / c) > 1e-30 else 1e-30; h *= d * c
            return h
        return exp(lb) * cf(x, a, b) / a if x < (a + 1) / (a + b + 2) else 1 - exp(lb) * cf(1 - x, b, a) / b
    def inv(p, a, b):
        lo, hi = 0.0, 1.0
        for _ in range(100):
            mid = (lo + hi) / 2
            if bt(mid, a, b) < p: lo = mid
            else: hi = mid
        return (lo + hi) / 2
    l = 0.0 if k == 0 else inv(0.025, k, n - k + 1)
    u = 1.0 if k == n else inv(0.975, k + 1, n - k)
    return f"[{l:.2f}, {u:.2f}]"
out = ["# LEADS PILOT #4 aggregate (generated by aggregate.py; do not edit)", ""]
out += ["## Column caps (kind `cap`)", "", "| m | n | k | variant | columns | UNSAT refuted [CP95] | SAT refuted | median wall s | median peak RSS MB | witness faults | not completed |", "|---|---|---|---|---|---|---|---|---|---|---|"]
for f in sorted(glob.glob(str(HERE / "results/cap-*.jsonl"))):
    rows = [json.loads(l) for l in open(f)]
    for v in dict.fromkeys(r["variant"] for r in rows):
        R = [r for r in rows if r["variant"] == v]; C = [r for r in R if "one" in r and r.get("rc", 0) == 0]
        U = [r for r in C if r["label"] == "UNSAT"]; S = [r for r in C if r["label"] == "SAT"]; r0 = R[0]
        ku = sum(r["one"] for r in U)
        out.append(f"| {r0['m']} | {r0['n']} | {r0['k']} | {v} | {C[0]['ncols'] if C else '-'} | {ku}/{len(U)} {cp(ku, len(U)) if U else ''} | {sum(r['one'] for r in S)}/{len(S)} | {med([r['outer_wall_s'] for r in C]):.1f} | {med([r.get('peak_rss_mb', 0) for r in C]):.0f} | {sum(sum(r.get('eval_rows_not_vanishing', [])) for r in C)} | {len(R) - len(C)} |")
out += ["", "## Target-independent precomputation (kind `pre`)", "",
        "scratch = one closure from the generators, stopping when 1 enters. two-phase = the z-free generators (all blocks but the last) closed to fixpoint once (phase 1), then the last block's generators inserted and the closure continued (phase 2, per target). Medians.", "",
        "| cell | label | n inst | cols | scratch refutes | scratch products | scratch s | phase-1 rank | phase-1 products | phase-1 s | phase-2 refutes | phase-2 products | phase-2 s | witness faults |", "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
for f in sorted(glob.glob(str(HERE / "results/pre-*.jsonl"))):
    rows = [json.loads(l) for l in open(f) if "scratch" in l]
    for lab in ("UNSAT", "SAT"):
        R = [r for r in rows if r["label"] == lab and r.get("scratch", {}).get("rc", 1) == 0]
        if not R: continue
        a = [r["scratch"] for r in R]; b = [r["two_phase"] for r in R]
        out.append(f"| {Path(f).stem[4:]} {R[0]['variant']} | {lab} | {len(R)} | {b[0]['ncols']} | {sum(x['one'] for x in a)}/{len(a)} | {med([x['prod'] for x in a])} | {med([x['sec1'] for x in a]):.3f} | {med([x['rank1'] for x in b])} | {med([x['prod1'] for x in b])} | {med([x['sec1'] for x in b]):.2f} | {sum(x['one'] for x in b)}/{len(b)} | {med([x['prod'] - x['prod1'] for x in b])} | {med([x['sec2'] for x in b]):.3f} | {sum(sum(x.get('eval_rows_not_vanishing', [])) for x in b)} |")
out += ["", "## Windowed closure (kind `win`): 2-block windows, messages = closure ∩ span(monomials on the shared block)", "",
        "| cell | label | n inst | refuted [CP95] | sweeps (each) | largest window cols | censored/errors | message witness faults | median wall s |", "|---|---|---|---|---|---|---|---|---|"]
for f in sorted(glob.glob(str(HERE / "results/win-*.jsonl"))):
    rows = [json.loads(l) for l in open(f)]
    for lab in ("UNSAT", "SAT"):
        R = [r for r in rows if r["label"] == lab]
        if not R: continue
        C = [r for r in R if "one" in r and not r.get("error")]; k_ = sum(bool(r["one"]) for r in C)
        out.append(f"| {Path(f).stem[4:]} | {lab} | {len(R)} | {k_}/{len(C)} {cp(k_, len(C)) if C else ''} | {[r.get('sweeps') for r in C]} | {max((r.get('max_window_cols') or 0) for r in C) if C else '-'} | {len(R) - len(C)} | {sum(r.get('message_witness_nonvanishing', 0) for r in C)} | {med([r['outer_wall_s'] for r in R]):.1f} |")
out += ["", "## Inputs", ""]
for p in sorted((HERE / "results").glob("*.jsonl")) + sorted((HERE / "instances").glob("*.json")):
    out.append(f"- `{p.relative_to(HERE)}` sha256 `{hashlib.sha256(p.read_bytes()).hexdigest()[:16]}`")
(HERE / "aggregate.md").write_text("\n".join(out) + "\n")
print("\n".join(out[:60]))
