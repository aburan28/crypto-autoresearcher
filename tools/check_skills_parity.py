#!/usr/bin/env python3
"""Fail when a repository's two agent skill surfaces drift.

The lab contract (`docs/lab-contract.md`, section 3) requires that every skill
name resolves on both surfaces — `.agents/skills/<name>` and
`.claude/skills/<name>` — and that each name has exactly one real body. The
other surface is a relative symlink (crypto, cryptanalysis), a pointer adapter
(crypto-autoresearcher), or a generated mirror that names its generator.

    python3 tools/check_skills_parity.py
    python3 tools/check_skills_parity.py --root /path/to/repo

Exit 0 when the surfaces agree, 1 otherwise.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

GENERATED = "Generated by"


def surfaces(base: Path) -> dict[str, Path]:
    found: dict[str, Path] = {}
    if not base.is_dir():
        return found
    for entry in sorted(base.iterdir()):
        if entry.name.startswith("."):
            continue
        skill = entry / "SKILL.md"
        if skill.exists():
            found[entry.name] = entry
    return found


def generated_mirror(entry: Path) -> bool:
    try:
        head = (entry / "SKILL.md").read_text(errors="replace")[:800]
    except OSError:
        return False
    return GENERATED in head


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=None)
    args = parser.parse_args(argv)
    root = (args.root or Path(__file__).resolve().parents[1]).resolve()

    agents = surfaces(root / ".agents" / "skills")
    claude = surfaces(root / ".claude" / "skills")
    errors: list[str] = []

    for name in sorted(set(agents) - set(claude)):
        errors.append(f"{name}: missing .claude/skills/{name}")
    for name in sorted(set(claude) - set(agents)):
        errors.append(f"{name}: missing .agents/skills/{name}")

    for name in sorted(set(agents) & set(claude)):
        a_entry, c_entry = agents[name], claude[name]
        for label, entry in (("agents", a_entry), ("claude", c_entry)):
            if entry.is_symlink():
                try:
                    (entry / "SKILL.md").resolve(strict=True)
                except FileNotFoundError:
                    errors.append(f"{name}: {label} symlink target is missing")
        if a_entry.is_symlink() or c_entry.is_symlink():
            continue
        try:
            identical = (a_entry / "SKILL.md").read_bytes() == (
                c_entry / "SKILL.md"
            ).read_bytes()
        except OSError:
            identical = False
        if identical and not (generated_mirror(a_entry) or generated_mirror(c_entry)):
            errors.append(
                f"{name}: identical real SKILL.md on both surfaces; "
                "make one a relative symlink"
            )

    if errors:
        for line in errors:
            print(f"skills-parity: {line}", file=sys.stderr)
        print(f"skills-parity: {len(errors)} problem(s)", file=sys.stderr)
        return 1
    print(f"skills-parity: OK ({len(agents)} skill(s) on both surfaces)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
