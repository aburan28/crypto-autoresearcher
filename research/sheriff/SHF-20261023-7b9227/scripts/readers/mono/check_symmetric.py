"""Symmetric-base checks (clause (2) of KN-FIND-bdcd60) and group-model computations.

G1 curve-free permutation-group model G_m = ((Z/2)^{m-1}/diag) x| S_{m-1} on 2^{m-2} points,
   m = 3..7: order, transitivity, regular normal 2-subgroup, primitivity, number of nontrivial
   block systems and block sizes, structure, transitive-group id (degree <= 8), and the
   joint cycle-type distribution (on the roots, on the m-1 coordinates) for m = 4, 5.
G2 symbolic m = 3: F in F_p[e1,e2][T] has non-square discriminant => S_2.
G3 Chebotarev census on F_p-points of the symmetric base (random monic g of degree m-1,
   F(T) computed from the roots of g in F_{p^k} by my own resultant code), m = 4, 5,
   joint cycle types (g, F) compared with G1's distribution by chi-square; and the same
   data tested against wrong-group alternatives (control B).
Usage: sage -python check_symmetric.py OUTDIR
"""
import sys, json, time, itertools, collections, os
from sage.all import *
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from mono_lib import (Cover, S3_expr, symbolic_S, symmetric_base_group, agl32,
                      joint_cycle_distribution, v_only_distribution)

set_random_seed(20261023)
OUT = sys.argv[1]
os.makedirs(OUT, exist_ok=True)
log = open(os.path.join(OUT, 'symmetric.log'), 'w')


def say(*a):
    s = ' '.join(str(x) for x in a)
    print(s); log.write(s + '\n'); log.flush()


summary = {'group_model': {}, 'm3_symbolic': {}, 'census': {}, 'alternatives': {}}

# ------------------------------------------------------------------ G1 group model
say('== G1 permutation-group model of the symmetric-base group, m = 3..7')
joint_dist = {}
for m in range(3, 8):
    t0 = time.time()
    G, nV, perms = symmetric_base_group(m)
    # restriction to the V points (my own generator order: translations first)
    gens_V = [Permutation([list(g)[i] for i in range(nV)]) for g in perms]
    GV = PermutationGroup(gens_V, domain=list(range(1, nV + 1)))
    rec = {'order': int(GV.order()), 'claimed_order': (2 ** (m - 2) * factorial(m - 1)) if m >= 4 else 2,
           'degree': nV, 'transitive': bool(GV.is_transitive()),
           'primitive': bool(GV.is_primitive()) if nV > 1 else None}
    rec['order_matches_claim'] = (rec['order'] == rec['claimed_order'])
    gG = libgap(GV)
    if nV > 1:
        blocks = libgap.AllBlocks(gG)  # representatives (block containing 1) of nontrivial systems
        rec['nontrivial_block_systems'] = int(len(blocks))
        rec['block_sizes'] = sorted(int(len(B)) for B in blocks)
    # translations subgroup: generated by the first m-2 generators (regular normal 2-subgroup)
    Tgens = gens_V[:m - 2]
    TG = PermutationGroup(Tgens, domain=list(range(1, nV + 1)))
    rec['translation_subgroup'] = {'order': int(TG.order()), 'elementary_abelian': bool(TG.is_abelian() and all(g.order() <= 2 for g in TG.gens())),
                                   'regular': bool(TG.is_transitive() and TG.order() == nV),
                                   'normal_in_G': bool(TG.is_normal(GV))}
    rec['structure'] = str(gG.StructureDescription())
    if nV <= 8 and nV > 1:
        try:
            rec['transitive_id'] = int(libgap.TransitiveIdentification(gG))
        except Exception as ex:
            rec['transitive_id'] = 'n/a (%s)' % str(ex)[:60]
    if m == 4:
        rec['isomorphic_to_S4'] = bool(GV.is_isomorphic(SymmetricGroup(4)))
        rec['equals_Sym4_as_permutation_group'] = bool(GV.order() == 24 and nV == 4)
    if m in (4, 5):
        jd = joint_cycle_distribution(G, nV)
        joint_dist[m] = jd
        rec['joint_cycle_type_distribution'] = {'%s|%s' % (k[0], k[1]): v for k, v in sorted(jd.items())}
        rec['root_cycle_type_distribution'] = {str(k): v for k, v in sorted(v_only_distribution(G, nV).items())}
    rec['seconds'] = round(time.time() - t0, 1)
    summary['group_model']['m=%d' % m] = rec
    say('  m=%d' % m, {k: v for k, v in rec.items() if k not in ('joint_cycle_type_distribution',)})

# ------------------------------------------------------------------ G2 symbolic m=3 on the symmetric base
say('== G2 m=3 symmetric base: disc of F in F_p[e1,e2] is a non-square')
for p in (7, 11, 13, 101, 10007):
    F = GF(p)
    R = PolynomialRing(F, ['a', 'b', 'e1', 'e2', 'T'])
    a, b, e1, e2, T = R.gens()
    # S_3 in terms of e1 = x1+x2, e2 = x1 x2
    Fsym = (e1 ** 2 - 4 * e2) * T ** 2 - 2 * (e1 * (e2 + a) + 2 * b) * T + ((e2 - a) ** 2 - 4 * b * e1)
    # consistency with S_3(x1,x2,T)
    R2 = PolynomialRing(F, ['a', 'b', 'x1', 'x2', 'T'])
    a2, b2, x1, x2, T2 = R2.gens()
    consistent = (Fsym(a2, b2, x1 + x2, x1 * x2, T2) == S3_expr(a2, b2, x1, x2, T2))
    D = Fsym.discriminant(T)
    # D is a non-square in F_p(a,b,e1,e2) iff some irreducible factor has odd multiplicity
    fac = D.factor()
    nonsquare = any(e % 2 == 1 for g, e in fac)
    summary['m3_symbolic'][str(p)] = {'consistent_with_S3': bool(consistent), 'disc_nonsquare_generic_ab': bool(nonsquare),
                                      'disc_factor_pattern': [(str(g)[:60], int(e)) for g, e in fac]}
    say('  p=%d' % p, summary['m3_symbolic'][str(p)])
# per specific curve (a, b fixed) the discriminant 16 f(x1) f(x2) is a non-square in F_p(e1,e2):
for (p, a, b) in [(7, 1, 0), (11, 0, 1), (101, 2, 3), (13, 2, 5)]:
    F = GF(p)
    R = PolynomialRing(F, ['e1', 'e2', 'T'])
    e1, e2, T = R.gens()
    Fsym = (e1 ** 2 - 4 * e2) * T ** 2 - 2 * (e1 * (e2 + F(a)) + 2 * F(b)) * T + ((e2 - F(a)) ** 2 - 4 * F(b) * e1)
    D = Fsym.discriminant(T)
    nonsquare = any(e % 2 == 1 for g, e in D.factor())
    facF = Fsym.factor()
    summary['m3_symbolic']['curve %d,%d,%d' % (p, a, b)] = {'disc_nonsquare': bool(nonsquare), 'F_irreducible_over_Fp(e)': bool(len(facF) == 1 and facF[0][1] == 1)}
    say('  curve', (p, a, b), summary['m3_symbolic']['curve %d,%d,%d' % (p, a, b)])


# ------------------------------------------------------------------ G3 census on symmetric-base F_p-points
def fibre_poly_ext(p, a, b, m, xs, K, S4sym):
    """F(T) = S_m(xs, T) with xs in K = F_{p^k}; returns polynomial over K[T]."""
    PT = PolynomialRing(K, 'T'); T = PT.gen()
    PTX = PolynomialRing(PT, 'X'); X = PTX.gen()
    aK, bK = K(a), K(b)
    if m == 4:
        A = PTX(S3_expr(aK, bK, xs[0], xs[1], X))
        B = PTX(S3_expr(aK, bK, xs[2], T, X))
        return A.resultant(B), PT
    if m == 5:
        A = PTX(S3_expr(aK, bK, xs[0], xs[1], X))
        B4 = S4sym(xs[2], xs[3], T, X, 0)
        return A.resultant(PTX(B4)), PT
    raise ValueError


def cycle_type_of(poly):
    return tuple(sorted([int(g.degree()) for g, e in poly.factor() for _ in range(e)]))


def chi_square(obs, expected_probs, N):
    """obs: Counter over keys; expected_probs: dict key->prob (sum 1). Returns (stat, dof, impossible_observed)."""
    keys = set(obs) | set(expected_probs)
    stat = 0.0
    impossible = {}
    for k in keys:
        o = obs.get(k, 0)
        pk = expected_probs.get(k, 0.0)
        if pk == 0.0:
            if o > 0:
                impossible[str(k)] = o
            continue
        e = pk * N
        stat += (o - e) ** 2 / e
    dof = len([k for k in expected_probs if expected_probs[k] > 0]) - 1
    return stat, dof, impossible


say('== G3 Chebotarev census on symmetric-base F_p-points, m = 4, 5')
CURVES = [(101, 2, 3), (101, 0, 1), (1009, 5, 7), (1009, 1, 0), (10007, 2, 3), (13, 2, 5)]
for (p, a, b) in CURVES:
    F = GF(p)
    E = EllipticCurve(F, [a, b])
    R4, S4sym = symbolic_S(4, F(a), F(b), F)
    key = '%d,%d,%d' % (p, a, b)
    summary['census'][key] = {'supersingular': bool(E.is_supersingular()), 'j': str(E.j_invariant())}
    for m in (4, 5):
        n = m - 1
        N = {4: 3000, 5: 1500}[m] if p < 5000 else {4: 1200, 5: 500}[m]
        if p == 13:
            N = {4: 3000, 5: 2000}[m]
        Kcache = {}
        PX = PolynomialRing(F, 'x'); x = PX.gen()
        joint = collections.Counter(); status = collections.Counter()
        t0 = time.time()
        for _ in range(N):
            g = x ** n + sum(F.random_element() * x ** i for i in range(n))
            if not g.is_squarefree():
                status['g_not_squarefree'] += 1; continue
            degs = [int(h.degree()) for h, e in g.factor()]
            k = lcm(degs)
            if k not in Kcache:
                Kcache[k] = GF(p ** k, 'w') if k > 1 else F
            K = Kcache[k]
            roots = [r for r, e in g.change_ring(K).roots()]
            assert len(roots) == n
            if any((r ** 3 + K(a) * r + K(b)) == 0 for r in roots):
                status['f_zero'] += 1; continue
            Fp, PT = fibre_poly_ext(p, a, b, m, roots, K, S4sym)
            # F must have F_p coefficients
            try:
                Fq = PolynomialRing(F, 'T')([F(c) for c in Fp.list()])
            except (TypeError, ValueError):
                status['NOT_RATIONAL'] += 1; continue
            if Fq.degree() != 2 ** (m - 2):
                status['degree_drop'] += 1; continue
            if gcd(Fq, Fq.derivative()).degree() != 0:
                status['not_squarefree'] += 1; continue
            status['ok'] += 1
            joint[(cycle_type_of(Fq), tuple(sorted(degs)))] += 1
        nok = status['ok']
        jd = joint_dist[m]; order = sum(jd.values())
        probs = {k: v / order for k, v in jd.items()}
        stat, dof, impossible = chi_square(joint, probs, nok)
        # marginal on roots
        obsV = collections.Counter(); probV = collections.defaultdict(float)
        for (cv, cs), v in joint.items():
            obsV[cv] += v
        for (cv, cs), v in probs.items():
            probV[cv] += v
        statV, dofV, impV = chi_square(obsV, dict(probV), nok)
        id_ct = tuple([1] * 2 ** (m - 2))
        rec = {'N': N, 'status': dict(status), 'joint_observed': {'%s|%s' % k: v for k, v in sorted(joint.items())},
               'chi2_joint': round(float(stat), 2), 'dof_joint': dof, 'impossible_joint_types_observed': impossible,
               'chi2_roots_marginal': round(float(statV), 2), 'dof_roots': dofV, 'impossible_root_types_observed': impV,
               'identity_fraction': float(obsV[id_ct] / nok) if nok else None, 'identity_expected': float(1 / order),
               'seconds': round(time.time() - t0, 1)}
        summary['census'][key]['m=%d' % m] = rec
        say('  curve', key, 'm=%d' % m, 'ok=%d' % nok, 'chi2_joint=%.1f/dof %d' % (stat, dof),
            'chi2_roots=%.1f/dof %d' % (statV, dofV), 'impossible=%s %s' % (impossible, impV),
            'id_frac=%.4f exp %.4f' % (rec['identity_fraction'] or 0, 1 / order), '%.0fs' % rec['seconds'])

# ------------------------------------------------------------------ control B: wrong-group alternatives
say('== Control B: the same census data against wrong groups (must be rejected)')


def dist_of_group(G):
    cnt = collections.Counter()
    for g in G:
        cnt[tuple(sorted(g.cycle_type()))] += 1
    return cnt


alts = {}
# degree 4 (m=4): alternatives to S_4: V_4 regular, C_4, D_4, A_4
alts[4] = {'V4_regular': PermutationGroup([[(1, 2), (3, 4)], [(1, 3), (2, 4)]]),
           'C4': CyclicPermutationGroup(4), 'D4': DihedralGroup(4), 'A4': AlternatingGroup(4)}
# degree 8 (m=5): alternatives to the claimed order-192 group
gap_wr = libgap.WreathProduct(libgap.SymmetricGroup(2), libgap.SymmetricGroup(4))
S2wrS4 = PermutationGroup(gap_group=gap_wr)
gap_wr2 = libgap.WreathProduct(libgap.SymmetricGroup(4), libgap.SymmetricGroup(2))
S4wrS2 = PermutationGroup(gap_group=gap_wr2)
# AGL(3,2) built by hand in mono_lib.agl32
alts[8] = {'C8_regular': CyclicPermutationGroup(8), 'S2wrS4_384': S2wrS4, 'S4wrS2_1152': S4wrS2,
           'AGL(3,2)_1344': agl32(), 'A8': AlternatingGroup(8), 'S8': SymmetricGroup(8)}
# the other transitive groups of degree 8 and order 192, for distinguishability by cycle type
try:
    for i in range(1, 51):
        Tg = PermutationGroup(gap_group=libgap.TransitiveGroup(8, i))
        if Tg.order() == 192:
            alts[8]['TransitiveGroup(8,%d)_192' % i] = Tg
except Exception as ex:
    say('  transitive groups library unavailable:', str(ex)[:80])

for (p, a, b) in CURVES:
    key = '%d,%d,%d' % (p, a, b)
    for m in (4, 5):
        rec = summary['census'][key]['m=%d' % m]
        nok = rec['status'].get('ok', 0)
        obsV = collections.Counter()
        for kk, v in rec['joint_observed'].items():
            cv = eval(kk.split('|')[0])
            obsV[cv] += v
        res = {}
        for name, Gx in alts[2 ** (m - 2)].items():
            d = dist_of_group(Gx); o = sum(d.values())
            probs = {k: v / o for k, v in d.items()}
            stat, dof, imp = chi_square(obsV, probs, nok)
            res[name] = {'order': int(o), 'chi2': round(float(stat), 1), 'dof': dof, 'impossible_observed': imp,
                         'cycle_types_of_group': {str(k): v for k, v in sorted(d.items())}}
        summary['alternatives'].setdefault(key, {})['m=%d' % m] = res
        say('  ', key, 'm=%d' % m, {n_: (r['chi2'], r['dof'], bool(r['impossible_observed'])) for n_, r in res.items()})

with open(os.path.join(OUT, 'symmetric_summary.json'), 'w') as fh:
    json.dump(summary, fh, indent=1, default=str)
say('wrote', os.path.join(OUT, 'symmetric_summary.json'))
