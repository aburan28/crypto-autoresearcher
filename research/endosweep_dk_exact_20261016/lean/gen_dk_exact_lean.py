#!/usr/bin/env python3
"""Generate formal/CryptoResearch/Endosweep/DkExact.lean from this directory's results.

Reads (repository-relative, from REPO, default ".")
  research/endosweep_dk_exact_20261016/dk_exact.json
  research/endosweep_dk_exact_20261016/factorizations.jsonl
Writes
  formal/CryptoResearch/Endosweep/DkExact.lean

Every number is re-derived and re-checked here first (the same propositions the
Lean file states), so a stale or inconsistent input fails here rather than in
Lean.  The definitions and proofs are fixed text in this script; only the data
blocks are generated.  The file imports NistCertificates (for `FactoredCert`,
`noDivBelow`) and through it Discriminant; core Lean only, no Mathlib.

    python3 research/endosweep_dk_exact_20261016/lean/gen_dk_exact_lean.py .

An optional second argument writes elsewhere (the tests regenerate into a
temporary file and compare).
"""
import json
import re
import sys
from math import isqrt, prod
from pathlib import Path

REPO = Path(sys.argv[1] if len(sys.argv) > 1 else ".")
DIR = REPO / "research/endosweep_dk_exact_20261016"
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else REPO / "formal/CryptoResearch/Endosweep/DkExact.lean"
TRIAL = 10 ** 8   # as NistCertificates: odd-exponent primes below this are proved prime in Lean


def lean_name(curve: str) -> str:
    name = re.sub(r"[^A-Za-z0-9]", "_", curve)
    assert re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", name), curve
    return name


def min_deg(D: int) -> int:
    return (abs(D) + D % 2) // 4


def certs():
    doc = json.loads((DIR / "dk_exact.json").read_text())
    facs = {}
    for line in (DIR / "factorizations.jsonl").read_text().splitlines():
        r = json.loads(line)
        facs[r["curve"]] = (int(r["N"]), [(int(p), x) for p, x in r["factors"]])
    out = []
    for r in doc["curves"]:
        p, n, h, t = int(r["p"]), int(r["n"]), int(r["h"]), int(r["t"])
        DK, f, deg, s = int(r["D_K"]), int(r["conductor_f"]), int(r["min_nonscalar_degree"]), int(r["squarefree_part"])
        N, fac = facs[r["curve"]]
        assert fac == [(int(a), x) for a, x in r["factorization"]]
        assert p + 1 - t == h * n
        assert N == 4 * p - t * t == prod(a ** x for a, x in fac)
        assert t * t - 4 * p == DK * f * f
        assert DK < 0 and DK % 4 in (0, 1) and deg == min_deg(DK)
        odd = [a for a, x in fac if x % 2]
        assert odd == sorted(odd) and len(set(odd)) == len(odd) and prod(odd) == s
        if (-s) % 4 == 1:
            assert DK == -s
        else:
            assert DK == -4 * s and (-s) % 4 in (2, 3)
        small = [(a, isqrt(a) + 1) for a in odd if a < TRIAL]
        large = [a for a in odd if a >= TRIAL]
        for a, rr in small:
            assert 2 <= a < rr * rr and all(a % d for d in range(2, rr))
        L = abs(DK).bit_length() - 1
        assert 2 ** L <= abs(DK) < 2 ** (L + 1) and 2 ** max(L - 2, 0) <= deg
        out.append(dict(curve=r["curve"], name=lean_name(r["curve"]), p=p, t=t, h=h, n=n, DK=DK, f=f, deg=deg,
                        s=s, fac=fac, small=small, large=large, L=L))
    return out


HEADER = """/-
Exact CM discriminants of the curves whose `4q − t²` the factoring driver
completed (research/endosweep_dk_exact_20261016).

Source:  research/endosweep_dk_exact_20261016/README.md ("Results" and "Lean
         verification"); data in dk_exact.json and factorizations.jsonl there.
Target:  formal/targets/endosweep-dk-exact-discriminants.yaml

GENERATED by research/endosweep_dk_exact_20261016/lean/gen_dk_exact_lean.py
(the script re-checks every proposition in Python and refuses to write on any
mismatch).  Do not edit by hand.

WHAT IS CERTIFIED (unconditionally, by kernel arithmetic), per curve, with
`q = p` the field prime and `h`, `n` the published cofactor and subgroup order:
  * `q + 1 − t = h·n` (the trace `t` is the one the group order gives);
  * `t² − 4q = D_K·f²`;
  * `4q − t² = ∏ pᵢ^eᵢ`, the factorisation certificate, multiplied back;
  * the odd-exponent primes of the certificate are `oddPrimes`, their product
    is the squarefree part `s`, and `D_K = −s` with `D_K ≡ 1 (mod 4)` or
    `D_K = −4s` with `−s ≡ 2, 3 (mod 4)` (exactly `nist.exact_discriminant`);
  * `D_K < 0` and `D_K ≡ 0, 1 (mod 4)` (`IsDisc`);
  * `min_nonscalar_degree(D_K) = (|D_K| + (D_K mod 2))/4` is the recorded value,
    `2^L ≤ |D_K| < 2^(L+1)` and `2^(L−2) ≤ min_nonscalar_degree(D_K)`;
  * every odd-exponent factor below 10^8 is prime (trial division in Lean).
CONDITIONAL on the primality of the odd-exponent factors above 10^8 (listed
per curve in `largePrimes`; proved by PARI `isprime`, NOT by Lean): `D_K` is
a fundamental discriminant.

NOT CERTIFIED: primality of any factor above 10^8 (an explicit hypothesis, as
in NistCertificates); primality of `p` and `n`; any elliptic-curve fact (that
`t` is the trace of Frobenius of the named curve, that End(E) lies in the
order of discriminant `D_K`, that degree equals norm); uniqueness of the
fundamental discriminant in a square class.
-/
import CryptoResearch.Endosweep.NistCertificates

namespace CryptoResearch.Endosweep.DkExact

open CryptoResearch.Endosweep.Discriminant
open CryptoResearch.Endosweep.NistCertificates

/-- One curve: NistCertificates' `FactoredCert` (`q`, `t`, `D_K`, `f`, degree,
factorisation, small/large odd-exponent primes) plus the published cofactor
`h`, subgroup order `n`, the squarefree part `s` of `4q − t²` and
`L = ⌊log2 |D_K|⌋`. -/
structure DkCert extends FactoredCert where
  h : Int
  n : Int
  s : Nat
  L : Nat

/-- The closed arithmetic checked for one curve. -/
abbrev DkCert.Holds (c : DkCert) : Prop :=
  c.q + 1 - c.t = c.h * c.n ∧
  c.toFactoredCert.Holds ∧
  c.oddPrimes.prod = c.s ∧
  (c.DK % 4 = 0 ∨ c.DK % 4 = 1) ∧
  2 ^ c.L ≤ c.DK.natAbs ∧ c.DK.natAbs < 2 ^ (c.L + 1) ∧ (2 : Int) ^ (c.L - 2) ≤ c.deg

/-- What is stated for one curve. -/
def DkCert.Statement (c : DkCert) : Prop :=
  c.q + 1 - c.t = c.h * c.n ∧
  c.t ^ 2 - 4 * c.q = c.DK * c.f ^ 2 ∧
  4 * c.q - c.t ^ 2 = ((c.factors.map (fun pe => pe.1 ^ pe.2)).prod : Nat) ∧
  (c.factors.filter (fun pe => pe.2 % 2 == 1)).map (·.1) = c.oddPrimes ∧
  c.oddPrimes.prod = c.s ∧
  ((c.DK = -(c.s : Int) ∧ c.DK % 4 = 1) ∨
    (c.DK = -4 * (c.s : Int) ∧ ((-(c.s : Int)) % 4 = 2 ∨ (-(c.s : Int)) % 4 = 3))) ∧
  IsDisc c.DK ∧
  minNonscalarDegree c.DK = c.deg ∧
  2 ^ c.L ≤ c.DK.natAbs ∧ c.DK.natAbs < 2 ^ (c.L + 1) ∧ (2 : Int) ^ (c.L - 2) ≤ c.deg ∧
  ((∀ p ∈ c.largePrimes, IsPrimeNat p) → IsFundamental c.DK)

/-- The closed check gives the statement; only the fundamentality step uses the
primality hypothesis on `largePrimes`. -/
theorem DkCert.statement_of_holds (c : DkCert) (h : c.Holds) : c.Statement := by
  obtain ⟨hhn, ⟨h1, h2, hodd, hnd, hD, hdisc, hdeg, hsmall⟩, hs, _, hL1, hL2, hL3⟩ := h
  refine ⟨hhn, h1, h2, hodd, hs, by rw [← hs]; exact hD, hdisc, hdeg, hL1, hL2, hL3,
    fun hlarge => isFundamental_of_primes c.oddPrimes hnd ?_ c.DK hD⟩
  intro p hp
  simp only [FactoredCert.oddPrimes, List.mem_append, List.mem_map] at hp
  rcases hp with ⟨pr, hpr, rfl⟩ | hp
  · obtain ⟨a, b, c'⟩ := hsmall pr hpr
    exact isPrimeNat_of_noDivBelow a b c'
  · exact hlarge p hp

"""


def fac_lean(fac):
    return "[" + ", ".join(f"({p}, {x})" for p, x in fac) + "]"


def pr_lean(xs):
    return "[" + ", ".join(f"({p}, {r})" for p, r in xs) + "]"


def nl(xs):
    return "[" + ", ".join(str(x) for x in xs) + "]"


def main():
    cs = certs()
    L = [HEADER]
    for c in cs:
        L.append(f"/-- {c['curve']}: `D_K = {'−s' if c['DK'] == -c['s'] else '−4s'}`"
                 f"{' = ' + str(c['DK']) if abs(c['DK']) < 10 ** 6 else ''}, `f` of {len(str(c['f']))} digits, "
                 f"`⌊log2 |D_K|⌋ = {c['L']}`. -/")
        L.append(f"def {c['name']} : DkCert where")
        L.append(f"  q := {c['p']}")
        L.append(f"  t := {c['t']}")
        L.append(f"  h := {c['h']}")
        L.append(f"  n := {c['n']}")
        L.append(f"  DK := {c['DK']}")
        L.append(f"  f := {c['f']}")
        L.append(f"  deg := {c['deg']}")
        L.append(f"  factors := {fac_lean(c['fac'])}")
        L.append(f"  smallPrimes := {pr_lean(c['small'])}")
        L.append(f"  largePrimes := {nl(c['large'])}")
        L.append(f"  s := {c['s']}")
        L.append(f"  L := {c['L']}")
        L.append("")
        L.append(f"/-- {c['curve']}: the closed arithmetic, checked by the kernel. -/")
        L.append(f"theorem {c['name']}_holds : {c['name']}.Holds := by decide +kernel")
        L.append("")
        L.append(f"/-- {c['curve']}: `q + 1 − t = h·n`, `t² − 4q = D_K·f²`, the factorisation, the squarefree")
        L.append("part and the construction of `D_K` from it, `D_K ≡ 0, 1 (mod 4)`, the degree bound, and,")
        L.append("IF the listed factors above 10^8 are prime (PARI `isprime`; not proved here), `D_K` is fundamental. -/")
        L.append(f"theorem {c['name']}_certificate : {c['name']}.Statement :=")
        L.append(f"  DkCert.statement_of_holds _ {c['name']}_holds")
        L.append("")
    names = [c["name"] for c in cs]
    L.append(f"/-- The {len(cs)} curves of research/endosweep_dk_exact_20261016/dk_exact.json. -/")
    L.append("def dkCerts : List DkCert :=")
    L.append("  [" + ",\n   ".join(names) + "]")
    L.append("")
    m3 = [c["name"] for c in cs if c["DK"] == -3]
    big = [c for c in cs if c["DK"] != -3]
    lo = min(c["L"] for c in big)
    L.append(f"""/-- **Exact CM discriminants** (README "Results").  For every curve in
`dkCerts`, `DkCert.Statement` holds: `q + 1 − t = h·n`; `t² − 4q = D_K·f²`;
`4q − t²` is the product of the certificate's prime powers; the odd-exponent
primes multiply to the squarefree part `s`, and `D_K = −s` (`D_K ≡ 1 mod 4`) or
`D_K = −4s` (`−s ≡ 2, 3 mod 4`); `D_K` is a discriminant; the recorded degree is
`min_nonscalar_degree(D_K)`, with `2^L ≤ |D_K| < 2^(L+1)` and degree `≥ 2^(L−2)`;
and IF the listed factors above 10^8 are prime (PARI `isprime`, not proved
here), `D_K` is fundamental.  Moreover `D_K = −3` (degree 1, the order-6
automorphism) on {', '.join(m3)} (the pairing-friendly curves with `j = 0`),
and on the other {len(big)} curves `|D_K| ≥ 2^{lo}` and every non-scalar element
of the order of discriminant `D_K` has norm `≥ 2^{lo - 2}`
(`Discriminant.minNonscalarDegree_isLeast`). -/
theorem exact_discriminants :
    dkCerts.length = {len(cs)} ∧
    (∀ c ∈ dkCerts, c.Statement) ∧
    ({' ∧ '.join(f'{x}.DK = -3' for x in m3)}) ∧
    (∀ c ∈ dkCerts, c.DK ≠ -3 → 2 ^ {lo} ≤ c.DK.natAbs ∧ (2 : Int) ^ {lo - 2} ≤ c.deg) := by
  refine ⟨rfl, ?_, by decide +kernel, by decide +kernel⟩
  intro c hc
  simp only [dkCerts, List.mem_cons, List.not_mem_nil, or_false] at hc
  rcases hc with {' | '.join(['rfl'] * len(cs))}
""")
    for nme in names:
        L.append(f"  · exact {nme}_certificate")
    L.append("")
    L.append("end CryptoResearch.Endosweep.DkExact")
    text = "\n".join(L) + "\n"
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text)} bytes, {len(cs)} curves)")


if __name__ == "__main__":
    main()
