"""A frozen, reproducible corpus slice for evaluation.

The full repository stages ~8,400 documents. Running the question set against
all of them takes minutes and, worse, makes the labelled answers unstable:
whether ``KN-LIT-006`` is retrievable should not change because 300 unrelated
literature notes were added last week.

Globs alone do not buy that. ``ledger/evidence/EV-*.yaml`` and
``knowledge/findings/KN-FIND-*.md`` match more files every week this program
runs, and they did: between the commit that recorded the retrieval baseline
and five days later the slice grew from 430 documents to 625, evidence records
alone going 137 → 299. Recall fell, no retrieval code having changed. A
measured baseline that any unrelated commit can move is not measuring
retrieval.

So the slice is an explicit manifest of repository-relative paths
(``corpus_manifest.txt``), and ``EVAL_GLOBS`` is only the recipe used to
regenerate it. Growing the slice is a deliberate edit -- ``crypto-kb
eval-manifest --write`` -- after which the labelled answers are re-checked and
the baseline is re-measured with the run that justifies it.

A manifest path that no longer exists is an error rather than a silent
shrink: a deleted record invalidates every label that names it, and that is
worth a loud failure.
"""

from __future__ import annotations

from pathlib import Path

from crypto_kb.ingest.repo_corpus import RULES, StagingRule, stage_repository

#: The frozen slice. Regenerate deliberately with `crypto-kb eval-manifest --write`.
MANIFEST_PATH = Path(__file__).with_name("corpus_manifest.txt")

#: Globs that define the evaluation slice, by staging-rule name. These select
#: the *candidates*; the manifest is what is actually staged.
EVAL_GLOBS: dict[str, str] = {
    # The founding ECDLP literature: Semaev, Gaudry, Diem, index calculus.
    "literature": "knowledge/literature/KN-LIT-0[0-9][0-9].md",
    "techniques": "knowledge/techniques/KN-TECH-0[0-9][0-9].md",
    "findings": "knowledge/findings/KN-FIND-*.md",
    "open-problems": "knowledge/open-problems/KN-OPEN-*.md",
    "evidence": "ledger/evidence/EV-*.yaml",
    "hypotheses": "ledger/H-*.yaml",
    "questions": "ledger/RQ-*.yaml",
    "docs": "docs/*.md",
}


def eval_rules() -> tuple[StagingRule, ...]:
    """The staging rules restricted to the evaluation slice."""
    by_name = {rule.name: rule for rule in RULES}
    narrowed: list[StagingRule] = []
    for name, glob in EVAL_GLOBS.items():
        rule = by_name.get(name)
        if rule is None:  # pragma: no cover - guards a rename in repo_corpus
            raise KeyError(f"no staging rule named {name!r}")
        narrowed.append(
            StagingRule(
                name=rule.name,
                glob=glob,
                destination=rule.destination,
                source_type=rule.source_type,
                id_prefix=rule.id_prefix,
                build=rule.build,
            )
        )
    return tuple(narrowed)


def discover_eval_paths(repo_root: Path) -> list[str]:
    """Every candidate path the globs match today, sorted.

    This is what ``--write`` freezes. It is deliberately *not* what
    ``build_eval_corpus`` stages.
    """
    found: set[str] = set()
    for glob in EVAL_GLOBS.values():
        for path in repo_root.glob(glob):
            if path.is_file():
                found.add(path.relative_to(repo_root).as_posix())
    return sorted(found)


def load_manifest(path: Path | None = None) -> list[str]:
    """The frozen slice, comments and blank lines stripped."""
    path = path or MANIFEST_PATH
    if not path.exists():  # pragma: no cover - ships with the package
        raise FileNotFoundError(
            f"evaluation manifest missing at {path}; regenerate with "
            "`crypto-kb eval-manifest --write`"
        )
    lines = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if line and not line.startswith("#"):
            lines.append(line)
    return lines


def write_manifest(repo_root: Path, path: Path | None = None) -> list[str]:
    """Freeze today's candidates as the evaluation slice."""
    path = path or MANIFEST_PATH
    paths = discover_eval_paths(repo_root)
    header = [
        "# The frozen evaluation corpus slice: one repository-relative path per line.",
        "#",
        "# Generated by `crypto-kb eval-manifest --write` from EVAL_GLOBS in",
        "# crypto_kb/eval/corpus.py. Do not regenerate to make a failing baseline",
        "# pass -- a baseline measured on a different corpus is a different",
        "# measurement. Regenerate when the slice should genuinely grow, then",
        "# re-check the labels in tests/retrieval_eval/questions.jsonl and",
        "# re-measure BASELINE in tests/retrieval_eval/test_eval_harness.py.",
        f"# {len(paths)} documents.",
        "",
    ]
    path.write_text("\n".join([*header, *paths]) + "\n", encoding="utf-8")
    return paths


def build_eval_corpus(repo_root: Path, store, manifest_path: Path | None = None) -> list:
    """Stage the frozen evaluation slice into ``store``."""
    manifest = load_manifest(manifest_path)
    missing = [p for p in manifest if not (repo_root / p).is_file()]
    if missing:
        raise FileNotFoundError(
            f"{len(missing)} manifest paths no longer exist (first: {missing[0]}). "
            "Every question label that names one is now unmeasurable. Re-check the "
            "labels, then regenerate with `crypto-kb eval-manifest --write`."
        )
    return stage_repository(repo_root, store, rules=eval_rules(), include=manifest)
