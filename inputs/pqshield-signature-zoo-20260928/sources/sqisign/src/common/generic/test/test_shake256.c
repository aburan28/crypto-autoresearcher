#define MAX_OUT_LEN 250

// Squeezing in awkwardly sized pieces must give the same stream as one big squeeze; 7 bytes divides neither the rate
// nor any output length used here.
#define CHUNK 7

static int
check(const char *what, const shake256_kat_t *kat, const uint8_t *got)
{
    if (memcmp(got, kat->out, kat->out_len) == 0)
        return 1;

    printf("  FAIL %s/%s\n", kat->name, what);
    return 0;
}

// One-shot shake256() against the vector.
static int
test_shake256_one_shot(const shake256_kat_t *kat)
{
    uint8_t got[MAX_OUT_LEN];

    shake256(got, kat->out_len, kat->msg, kat->msg_len);

    return check("one-shot", kat, got);
}

// Incremental absorb/finalize/squeeze against the vector.
static int
test_shake256_incremental(const shake256_kat_t *kat)
{
    uint8_t got[MAX_OUT_LEN];
    shake256incctx ctx;

    shake256_inc_init(&ctx);
    shake256_inc_absorb(&ctx, kat->msg, kat->msg_len);
    shake256_inc_finalize(&ctx);
    shake256_inc_squeeze(got, kat->out_len, &ctx);

    return check("incremental", kat, got);
}

// Squeezing the same output in CHUNK-sized pieces, which is the streaming property prng_random_bytes() relies on:
// n bytes then m bytes must equal one squeeze of n + m.
static int
test_shake256_chunked_squeeze(const shake256_kat_t *kat)
{
    // Zero-initialized only for cppcheck: it assumes out_len could be 0, leaving the loop below with nothing to write.
    // No vector in the table asks for zero bytes.
    uint8_t got[MAX_OUT_LEN] = { 0 };
    shake256incctx ctx;

    shake256_inc_init(&ctx);
    shake256_inc_absorb(&ctx, kat->msg, kat->msg_len);
    shake256_inc_finalize(&ctx);
    for (size_t done = 0; done < kat->out_len;) {
        size_t take = kat->out_len - done < CHUNK ? kat->out_len - done : CHUNK;
        shake256_inc_squeeze(got + done, take, &ctx);
        done += take;
    }

    return check("chunked-squeeze", kat, got);
}

// Absorbing the 51-byte message as 48 bytes then 3 bytes, which is the exact sequence prng_domain_seed() performs when
// it absorbs the root seed followed by the domain separator.
static int
test_shake256_split_absorb(const shake256_kat_t *kat)
{
    uint8_t got[MAX_OUT_LEN];
    shake256incctx ctx;

    shake256_inc_init(&ctx);
    shake256_inc_absorb(&ctx, kat->msg, PRNG_SEED_BYTES);
    shake256_inc_absorb(&ctx, kat->msg + PRNG_SEED_BYTES, PRNG_DOMAIN_SEP_BYTES);
    shake256_inc_finalize(&ctx);
    shake256_inc_squeeze(got, kat->out_len, &ctx);

    return check("split-absorb-48+3", kat, got);
}

int
main(void)
{
    int res = 1;

    printf("Running SHAKE-256 known-answer tests\n");

    for (size_t i = 0; i < sizeof(shake256_kats) / sizeof(*shake256_kats); i++) {
        const shake256_kat_t *kat = &shake256_kats[i];

        if (kat->out_len > MAX_OUT_LEN) {
            printf("  FAIL %s: output longer than MAX_OUT_LEN\n", kat->name);
            res = 0;
            continue;
        }

        res &= test_shake256_one_shot(kat);
        res &= test_shake256_incremental(kat);
        res &= test_shake256_chunked_squeeze(kat);
        if (kat->msg_len == PRNG_SEED_BYTES + PRNG_DOMAIN_SEP_BYTES)
            res &= test_shake256_split_absorb(kat);
    }

    if (!res) {
        printf("SHAKE-256 known-answer tests failed\n");
        return 1;
    }

    printf("SHAKE-256 known-answer tests passed\n");

    return 0;
}
