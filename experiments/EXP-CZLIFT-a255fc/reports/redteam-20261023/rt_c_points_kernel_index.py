"""Red-team check C (TASK-20261023-326d39, joints R1 and PTM-1): the actual points, their reduction
kernels and the image subgroup.

Own code only (no producer import). Steps:
 1. Enumerate every point of naive height H(X) = max(|a|, d^2) <= HMAX on each ladder curve, from
    c^2 = 4a^3 + b2 a^2 d^2 + 2 b4 a d^4 + b6 d^6 (X = a/d^2, Y = 2y + a1 x + a3 = c/d^3), with a
    float64 prefilter and an exact integer square test. Cross-check the grid counts against the
    runs' recorded counts for every grid H <= HMAX.
 2. Reduce into the short model y^2 = x^3 - 27 c4 x - 54 c6 (x = 36X + 3 b2, y = 108 Y) mod p and
    cross-check `distinct` against every recorded coverage cell with H <= HMAX.
 3. Image subgroup G_p generated by the reductions of all enumerated points; index k_p = N_p/|G_p|;
    whether coverage saturates at 1/k_p; primes with k_p >= 3 (no lift of most residues at any
    height for the subgroup generated by points of height <= HMAX).
 4. For selected frozen cells with collisions: every colliding pair P != Q, the kernel point
    K = P - Q over Q (exact Fractions); checks p^2 | den X(K), records H(X(K)) against p^2, and the
    number of distinct +-K explaining the collisions (clumping).
Usage: rt_c_points_kernel_index.py [HMAX]   (default 30000)
"""
from __future__ import annotations

import json
import math
import os
import sys
import time
from fractions import Fraction

import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", ".."))
OUTDIR = os.path.dirname(os.path.abspath(__file__))
RUNS = ["RUN-CZLIFT-74f172", "RUN-CZLIFT-490b33"]
GRID = [10, 30, 100, 300, 1000, 3000, 10_000, 30_000, 100_000, 300_000]
KERNEL_CELLS = [  # (curve, p, H) frozen cells with collisions, chosen across ranks
    ("389a1", 149, 30000), ("5077a1", 211, 30000), ("5077a1", 293, 30000),
    ("234446a1", 593, 30000), ("234446a1", 839, 30000), ("19047851a1", 419, 30000),
    ("5187563742a1", 1193, 30000), ("382623908456a1", 1193, 30000), ("382623908456a1", 2417, 30000),
    ("382623908456a1", 103, 300),
]


def binv(ai):
    a1, a2, a3, a4, a6 = ai
    b2 = a1 * a1 + 4 * a2
    b4 = 2 * a4 + a1 * a3
    b6 = a3 * a3 + 4 * a6
    c4 = b2 * b2 - 24 * b4
    c6 = -b2 ** 3 + 36 * b2 * b4 - 216 * b6
    return b2, b4, b6, c4, c6


SIEVE = (64, 63, 65, 11, 17, 19, 23, 29, 31, 37, 41)


def enumerate_points(ai, HMAX):
    """All affine points as (a, d, c), gcd(a, d) = 1, d >= 1, max(|a|, d^2) <= HMAX.

    Exact: a residue sieve over SIEVE (g must be a square mod every m) removes only non-squares,
    then an exact integer square test decides.
    """
    b2, b4, b6, _, _ = binv(ai)
    tabs = []
    for m in SIEVE:
        sq = np.zeros(m, dtype=bool)
        sq[(np.arange(m) ** 2) % m] = True
        tabs.append((m, sq))
    a_int = np.arange(-HMAX, HMAX + 1, dtype=np.int64)
    pts = []
    for d in range(1, math.isqrt(HMAX) + 1):
        keep = np.ones(a_int.shape, dtype=bool)
        for m, sq in tabs:
            am = a_int % m
            dm = d % m
            gm = (4 * am * am % m * am + (b2 % m) * am % m * am % m * (dm * dm % m)
                  + (2 * b4 % m) * am % m * pow(dm, 4, m) + (b6 % m) * pow(dm, 6, m)) % m
            keep &= sq[gm]
        aa = a_int[keep]
        aa = aa[np.gcd(np.abs(aa), d) == 1]
        for x in aa.tolist():
            G = 4 * x ** 3 + b2 * x * x * d * d + 2 * b4 * x * d ** 4 + b6 * d ** 6
            if G < 0:
                continue
            c = math.isqrt(G)
            if c * c == G:
                pts.append((x, d, c))
                if c:
                    pts.append((x, d, -c))
    return pts


def height(pt):
    return max(abs(pt[0]), pt[1] * pt[1])


# ---------- E(F_p) arithmetic on y^2 = x^3 + A x + B ----------
O = None


def ec_add(P, Q, A, p):
    if P is None:
        return Q
    if Q is None:
        return P
    x1, y1 = P
    x2, y2 = Q
    if x1 == x2:
        if (y1 + y2) % p == 0:
            return None
        lam = (3 * x1 * x1 + A) * pow(2 * y1, -1, p) % p
    else:
        lam = (y2 - y1) * pow(x2 - x1, -1, p) % p
    x3 = (lam * lam - x1 - x2) % p
    return (x3, (lam * (x1 - x3) - y1) % p)


def short_model(ai):
    b2, b4, b6, c4, c6 = binv(ai)
    return -27 * c4, -54 * c6, b2


def reduce_pt(pt, p, b2):
    a, d, c = pt
    if d % p == 0:
        return None
    di = pow(d, -1, p)
    X = a * di * di % p
    Y = c * di * di * di % p
    return ((36 * X + 3 * b2) % p, 108 * Y % p)


def curve_order(A, B, p):
    n = 1
    for x in range(p):
        g = (x * x * x + A * x + B) % p
        if g == 0:
            n += 1
        elif pow(g, (p - 1) // 2, p) == 1:
            n += 2
    return n


def generated_subgroup(gens, A, p):
    S = {O}
    for g in gens:
        if g in S:
            continue
        base = list(S)
        T = set(S)
        h = g
        while h not in S:
            for s in base:
                T.add(ec_add(s, h, A, p))
            h = ec_add(h, g, A, p)
        S = T
    return S


# ---------- exact group law over Q on the short model ----------
def to_short_Q(pt, b2):
    a, d, c = pt
    X = Fraction(a, d * d)
    Y = Fraction(c, d ** 3)
    return (36 * X + 3 * b2, 108 * Y)


def q_add(P, Q, A):
    if P is None:
        return Q
    if Q is None:
        return P
    x1, y1 = P
    x2, y2 = Q
    if x1 == x2:
        if y1 + y2 == 0:
            return None
        lam = (3 * x1 * x1 + A) / (2 * y1)
    else:
        lam = (y2 - y1) / (x2 - x1)
    x3 = lam * lam - x1 - x2
    return (x3, lam * (x1 - x3) - y1)


def X_of_short(xs, b2):
    return (xs - 3 * b2) / 36


def main():
    HMAX = int(sys.argv[1]) if len(sys.argv) > 1 else 30000
    raws = {r: json.load(open(os.path.join(ROOT, "experiments", "EXP-CZLIFT-a255fc", "runs", r, "raw-result.json")))
            for r in RUNS}
    curves = raws["RUN-CZLIFT-490b33"]["raw"]["curves"]
    out = {"HMAX": HMAX, "curves": {}, "kernel_cells": []}
    t0 = time.time()
    allpts = {}
    for cv in curves:
        lab, ai = cv["label"], cv["ainvs"]
        pts = enumerate_points(ai, HMAX)
        allpts[lab] = pts
        mine = {H: 1 + sum(1 for q in pts if height(q) <= H) for H in GRID if H <= HMAX}
        rec = {r: {int(k): v for k, v in raws[r]["raw"]["curves"][[c["label"] for c in raws[r]["raw"]["curves"]].index(lab)]["counts"].items()} for r in RUNS}
        count_ok = all(mine[H] == rec[r][H] for r in RUNS for H in mine)
        A, B, b2 = short_model(ai)
        per_p = {}
        distinct_mismatch = 0
        distinct_checked = 0
        for p in cv["primes"]:
            Np = curve_order(A, B, p)
            red = [reduce_pt(q, p, b2) for q in sorted(pts, key=height)]
            hs = sorted(height(q) for q in pts)
            # distinct check against recorded cells
            for r in RUNS:
                rcv = raws[r]["raw"]["curves"][[c["label"] for c in raws[r]["raw"]["curves"]].index(lab)]
                for c in rcv["coverage"]:
                    if c["p"] == p and c["H"] <= HMAX:
                        n = sum(1 for h in hs if h <= c["H"])
                        dset = set(red[:n])
                        dset.add(None)
                        distinct_checked += 1
                        if len(dset) != c["distinct"] or c["N_p"] != Np:
                            distinct_mismatch += 1
            G = generated_subgroup([x for x in red if x is not None], A, p)
            k = Np // len(G) if Np % len(G) == 0 else None
            # coverage of E(F_p) at the largest recorded height in the replication run
            rcv = raws["RUN-CZLIFT-490b33"]["raw"]["curves"][[c["label"] for c in curves].index(lab)]
            top = max((c for c in rcv["coverage"] if c["p"] == p), key=lambda c: c["H"])
            per_p[p] = {"N_p": Np, "image_order": len(G), "index_k_p": k,
                        "coverage_at_3e5": round(top["coverage"], 4), "ceiling_1_over_k": round(1 / k, 4) if k else None,
                        "h_half_recorded": rcv["h_half"].get(str(p))}
        out["curves"][lab] = {"rank_recalled": cv["rank_recalled"], "n_points_le_HMAX": len(pts) + 1,
                              "counts_match_both_runs": count_ok, "distinct_cells_checked": distinct_checked,
                              "distinct_mismatches": distinct_mismatch, "per_prime": per_p}
        print(lab, "points", len(pts) + 1, "counts_ok", count_ok, "distinct mismatches", distinct_mismatch,
              "/", distinct_checked, "t=%.1f" % (time.time() - t0), flush=True)
    # kernel analysis
    for lab, p, H in KERNEL_CELLS:
        if H > HMAX:
            continue
        cv = curves[[c["label"] for c in curves].index(lab)]
        A, B, b2 = short_model(cv["ainvs"])
        pts = [q for q in allpts[lab] if height(q) <= H]
        groups = {}
        for q in pts:
            groups.setdefault(reduce_pt(q, p, b2), []).append(q)
        groups.setdefault(None, []).append("O")
        n = len(pts) + 1
        distinct = len(groups)
        kernel_x = {}
        pairs = 0
        ok_p2 = True
        for res, members in groups.items():
            if len(members) < 2:
                continue
            for i in range(len(members)):
                for j in range(i + 1, len(members)):
                    P = None if members[i] == "O" else to_short_Q(members[i], b2)
                    Q = None if members[j] == "O" else to_short_Q(members[j], b2)
                    negQ = None if Q is None else (Q[0], -Q[1])
                    K = q_add(P, negQ, A)
                    pairs += 1
                    if K is None:
                        ok_p2 = False
                        continue
                    X = X_of_short(K[0], b2)
                    if X.denominator % (p * p):
                        ok_p2 = False
                    kernel_x[X] = max(abs(X.numerator), X.denominator)
        hs = sorted(kernel_x.values())
        out["kernel_cells"].append({
            "curve": lab, "p": p, "H": H, "N": n, "distinct": distinct, "lost_residues": n - distinct,
            "colliding_pairs": pairs, "distinct_pm_kernel_points": len(kernel_x),
            "collisions_per_kernel_point": round(pairs / len(kernel_x), 2) if kernel_x else None,
            "all_kernel_points_have_p2_dividing_den": ok_p2,
            "p_squared": p * p, "min_kernel_naive_height": hs[0] if hs else None,
            "min_kernel_height_over_p2": round(hs[0] / (p * p), 3) if hs else None,
            "log10_kernel_heights_quartiles": [round(math.log10(hs[int(q * (len(hs) - 1))]), 2) for q in (0, .25, .5, .75, 1)] if hs else None,
        })
        print(out["kernel_cells"][-1], flush=True)
    path = os.path.join(OUTDIR, f"rt_c_points_kernel_index_output_H{HMAX}.json")
    json.dump(out, open(path, "w"), indent=1, default=str)
    print("wrote", path, "t=%.1f" % (time.time() - t0))


if __name__ == "__main__":
    main()
