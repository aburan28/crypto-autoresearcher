"""R1 discriminating control: rank-record curves with SMALL coefficients (red team, TASK-20261023-7b5dc6).

Elkies-Watkins, 'Elliptic curves of large rank and small conductor', ANTS VI (LNCS 3076, 2004),
arXiv:math/0403374, Table 2 (retrieved 2026-10-23), lists the lowest-conductor curves of rank r = 5..11,
where 'rank' is the rank of the subgroup generated by small integral points (their footnote 3), i.e. a
lower bound.  The first row for r = 7 is the run's overlap curve [0,0,0,-10012,346900].  The first rows
for r = 8..11 have coefficients orders of magnitude smaller than the 1977 records the run used, so they
hold rank (lower bound) above 7 while removing most of the coefficient-size confound.
Same counter and grid as rt_count.py.  Output rt_ew_output.json.
"""
import json, os, sys, time
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import rt_lib as L

GRID = [100, 1000, 10000, 30000, 100000, 300000]
EW = [
    ("EW-r7-N382623908456", [0, 0, 0, -10012, 346900], 7, 382623908456),
    ("EW-r8-N249649566346838", [1, -1, 0, -106384, 13075804], 8, 249649566346838),
    ("EW-r9-N32107342006814614", [1, -1, 0, -135004, 97151644], 9, 32107342006814614),
    ("EW-r10-N10189285026863130793", [0, 0, 1, -16312387, 25970162646], 10, 10189285026863130793),
    ("EW-r11-N18031737725935636520843", [0, 0, 1, -16359067, 26274178986], 11, 18031737725935636520843),
]
out = {"source": "arXiv:math/0403374 Table 2, first row per rank", "grid": GRID, "rows": []}
for lab, ai, r, N in EW:
    t0 = time.time()
    pts = L.enumerate_points(ai, 300000)
    cnt = L.counts_from_points(pts, GRID)
    out["rows"].append({"label": lab, "ainvs": ai, "rank_lower_bound_source": r, "conductor_source": N,
                        "abs_disc": abs(L.discriminant(ai)), "counts": cnt, "integral_x_points": sum(1 for a, d, c in pts if d == 1),
                        "seconds": round(time.time() - t0, 1)})
    print(lab, "r>=", r, "|disc|", abs(L.discriminant(ai)), cnt, round(time.time() - t0, 1), "s", flush=True)
json.dump(out, open(os.path.join(HERE, "rt_ew_output.json"), "w"), indent=1)
