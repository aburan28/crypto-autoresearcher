def parse_results_text(text):
    """Return the list of N1 values (= delta_E per maximal order type)."""
    tuples = TUPLE_RE.findall(text)
    entries = ENTRY_RE.findall(text)
    n1 = [int(t[0]) for t in tuples]
    return n1, len(entries), len(tuples)


def load_dataset(cache_dir):
    """Load every cached results<p>.sage.  Returns (records, file_hashes)."""
    records = {}
    file_hashes = []
    names = sorted(os.listdir(cache_dir))
    for name in names:
        m = re.fullmatch(r"results(\d+)\.sage", name)
        if not m:
            continue
        p = int(m.group(1))
        path = os.path.join(cache_dir, name)
        raw = open(path, "rb").read()
        sha = hashlib.sha256(raw).hexdigest()
        text = raw.decode("utf-8", errors="strict")
        n1, n_entries, n_tuples = parse_results_text(text)
        if n_tuples == 0:
            raise ValueError("no (N1,N2,N3) tuples parsed from %s" % name)
        if n_entries != n_tuples:
            raise ValueError(
                "entry/tuple count mismatch in %s: %d vs %d"
                % (name, n_entries, n_tuples))
        # class number of supersingular j-invariants over Fbar_p.
        # p = 2, 3 are the degenerate cases (one supersingular j-invariant
        # each) that the floor(p/12)+e formula does not cover.
        if p in (2, 3):
            h_formula = 1
        else:
            h_formula = p // 12 + SUPERSINGULAR_E[p % 12]
        n_singleton = sum(1 for v in n1 if v == 1)
        h_recon = n_singleton + 2 * (n_tuples - n_singleton)
        records[p] = {
            "p": p,
            "n_order_types": n_tuples,
            "n_delta_eq_1": n_singleton,
            "h_reconstructed": h_recon,
            "h_class_number_formula": h_formula,
            "normalisation_ok": bool(h_recon == h_formula),
            "delta_min": min(n1),
            "delta_max": max(n1),
            "n1": n1,
            "sha256": sha,
            "bytes": len(raw),
        }
        file_hashes.append({"p": p, "file": name, "bytes": len(raw),
                            "sha256": sha,
                            "url": ("https://raw.githubusercontent.com/"
                                    "christellevincent/WISDE/main/results/"
                                    + name)})
    return records, file_hashes


def curve_counts(rec, tmax):
    """N(T, p) for T = 1..tmax, in units of ISOMORPHISM CLASSES OF CURVES
    (j-invariants), and in units of maximal ORDER TYPES."""
    hist = [0] * (tmax + 2)
    over = 0
    for v in rec["n1"]:
        if v <= tmax:
            hist[v] += 1
        else:
            over += 1
    curves = [0] * (tmax + 1)
    types = [0] * (tmax + 1)
    ccur = 0
    ctyp = 0
    for T in range(1, tmax + 1):
        w = 1 if T == 1 else 2      # Galois orbit size for delta = T
        ccur += w * hist[T]
        ctyp += hist[T]
        curves[T] = ccur
        types[T] = ctyp
    return curves, types, over


