def tmax_theorem(p):
    """floor((p/2)^(1/3)) -- AOV Thm 4.2 bound, integer since delta is an
    integer degree.  Computed exactly with integers."""
    t = int(round((p / 2.0) ** (1.0 / 3.0)))
    while 2 * (t + 1) ** 3 <= p:
        t += 1
    while t > 0 and 2 * t ** 3 > p:
        t -= 1
    return t


def build_cells(records, p_min, decile_mode="per_p"):
    """Frozen W-MAIN / W-SENS cell construction.

    W-MAIN: all (T, p) cells with p >= 1000 and 1 < T <= (p/2)^(1/3),
            EXCLUDING cells with N(T,p) < 10 and EXCLUDING the largest T
            decile.
    W-SENS: identical with p >= 10000.

    `decile_mode`:
      "per_p"  -- keep T <= floor(0.9 * Tmax(p)).  This is the reading forced
                  by the contract's own stated rationale ("saturation toward
                  fraction 1 flattens the power law"): saturation to fraction
                  1 is a per-p phenomenon occurring at T -> Tmax(p).
      "pooled" -- drop the top decile of the pooled admitted T values.
                  Recorded as a sensitivity ONLY; never the primary.
    """
    raw = []
    for p in sorted(records):
        if p < p_min:
            continue
        rec = records[p]
        tmax = tmax_theorem(p)
        curves, types, _ = curve_counts(rec, tmax)
        for T in range(2, tmax + 1):
            raw.append({"p": p, "T": T, "Tmax": tmax,
                        "N_curves": curves[T], "N_types": types[T]})
    if decile_mode == "per_p":
        kept = [r for r in raw if r["T"] <= math.floor(0.9 * r["Tmax"])]
    elif decile_mode == "pooled":
        ts = sorted(r["T"] for r in raw)
        if not ts:
            return []
        cut = ts[max(0, int(math.ceil(0.9 * len(ts))) - 1)]
        kept = [r for r in raw if r["T"] <= cut]
    else:
        raise ValueError(decile_mode)
    return [r for r in kept if r["N_curves"] >= 10]


def fit_cells(cells, key="N_curves"):
    rows = [(math.log(r["T"]), math.log(r["p"]), math.log(r[key]))
            for r in cells]
    out = ols(rows)
    out["p_min"] = min(r["p"] for r in cells)
    out["p_max"] = max(r["p"] for r in cells)
    out["T_min"] = min(r["T"] for r in cells)
    out["T_max"] = max(r["T"] for r in cells)
    out["n_primes"] = len(set(r["p"] for r in cells))
    out["c"] = math.exp(out["log_c"])
    return out


