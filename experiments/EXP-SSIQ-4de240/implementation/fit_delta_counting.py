def ols(rows):
    """Ordinary least squares of y on [1, x1, x2].

    rows: list of (x1, x2, y).  Equal weights.  Returns dict with the
    coefficients, their standard errors, R^2, n, and residual sigma.
    Pure Python, deterministic, so re-running gives bit-identical output.
    """
    n = len(rows)
    if n < 4:
        raise ValueError("too few cells for a 3-parameter fit: %d" % n)
    # normal equations
    XtX = [[0.0] * 3 for _ in range(3)]
    Xty = [0.0, 0.0, 0.0]
    for x1, x2, y in rows:
        v = (1.0, x1, x2)
        for i in range(3):
            Xty[i] += v[i] * y
            for j in range(3):
                XtX[i][j] += v[i] * v[j]
    inv = _inv3(XtX)
    beta = [sum(inv[i][k] * Xty[k] for k in range(3)) for i in range(3)]
    rss = 0.0
    tss = 0.0
    ybar = sum(r[2] for r in rows) / n
    for x1, x2, y in rows:
        pred = beta[0] + beta[1] * x1 + beta[2] * x2
        rss += (y - pred) ** 2
        tss += (y - ybar) ** 2
    dof = n - 3
    sigma2 = rss / dof
    se = [math.sqrt(sigma2 * inv[i][i]) for i in range(3)]
    return {
        "n_cells": n,
        "log_c": beta[0], "alpha": beta[1], "beta_p": beta[2],
        "se_log_c": se[0], "se_alpha": se[1], "se_beta_p": se[2],
        "rss": rss, "sigma_resid": math.sqrt(sigma2),
        "r_squared": (1.0 - rss / tss) if tss > 0 else float("nan"),
        "dof": dof,
    }


def _inv3(m):
    a, b, c = m[0]
    d, e, f = m[1]
    g, h, i = m[2]
    det = a * (e * i - f * h) - b * (d * i - f * g) + c * (d * h - e * g)
    if det == 0.0:
        raise ValueError("singular design matrix")
    return [
        [(e * i - f * h) / det, (c * h - b * i) / det, (b * f - c * e) / det],
        [(f * g - d * i) / det, (a * i - c * g) / det, (c * d - a * f) / det],
        [(d * h - e * g) / det, (b * g - a * h) / det, (a * e - b * d) / det],
    ]


def primes_upto(n):
    s = bytearray([1]) * (n + 1)
    s[0:2] = b"\x00\x00"
    for i in range(2, int(n ** 0.5) + 1):
        if s[i]:
            s[i * i::i] = bytearray(len(range(i * i, n + 1, i)))
    return [i for i, v in enumerate(s) if v]


def class_number_disc(D):
    """h(D) for a negative discriminant D, by counting reduced binary forms
    (a,b,c), b^2-4ac = D, |b| <= a <= c, b >= 0 if |b| == a or a == c.
    Independent of the solver and of the dataset."""
    assert D < 0 and D % 4 in (0, 1)
    h = 0
    b = D % 2
    B = int(math.isqrt(-D // 3))
    while b <= B:
        m = (b * b - D) // 4
        a = max(b, 1)
        while a * a <= m:
            if m % a == 0:
                c = m // a
                if b == 0 or a == b or a == c:
                    h += 1
                else:
                    h += 2
            a += 1
        b += 2
    return h


def fp_rational_ss_count(p):
    """Number of supersingular j-invariants lying in F_p, for p > 3.

    Deuring/Waterhouse/Schoof: a supersingular E/Fbar_p has j(E) in F_p
    exactly when E descends to a curve over F_p of trace 0, and the number of
    F_p-isomorphism classes of elliptic curves over F_p with exactly p+1
    points is h(-4p), the class number of the imaginary quadratic ORDER of
    discriminant -4p (= Z[sqrt(-p)]).  Each such j-invariant carries exactly
    two F_p-forms (a curve and its quadratic twist, both of trace 0), so

        #{ supersingular j in F_p } = h(-4p) / 2.

    NOT PRE-REGISTERED as an exact identity: the frozen contract's
    C-ANCHOR-LOW states the anchor as "~ p^{1/2}".  This exact form is a
    stronger supplementary check; its statement was settled before it was run
    over the full dataset and it is reported separately from the
    pre-registered scaling check.
    """
    h = class_number_disc(-4 * p)
    assert h % 2 == 0, "h(-4p) odd for p=%d" % p
    return h // 2


