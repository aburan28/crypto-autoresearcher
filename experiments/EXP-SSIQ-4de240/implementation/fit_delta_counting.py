def decision(alpha_main, se_alpha_main, alpha_sens):
    """spec.preregistered_prediction.decision_rule_frozen_before_data,
    applied mechanically.  No interpretation."""
    supports = (abs(alpha_main - 1.5) <= 0.20
                and abs(alpha_main - 2.0) > 2.0 * se_alpha_main)
    refutes = (abs(alpha_main - 2.0) <= 0.20
               and abs(alpha_main - 1.5) > 2.0 * se_alpha_main)
    window_shift = abs(alpha_main - alpha_sens)
    window_sensitive = window_shift > 0.20
    if window_sensitive:
        branch = "INCONCLUSIVE"
        why = ("W-MAIN/W-SENS alpha differ by %.6f > 0.20; spec"
               ".fitting_windows.W-SENS downgrades the primary result to"
               " INCONCLUSIVE regardless of the side W-MAIN landed on"
               % window_shift)
    elif supports and not refutes:
        branch = "SUPPORTS-D1"
        why = ("alpha within 3/2 +- 0.20 and 2.0 excluded at 2 standard"
               " errors")
    elif refutes and not supports:
        branch = "REFUTES-D1-AT-SCALE"
        why = ("alpha within 2.0 +- 0.20 and 1.5 excluded at 2 standard"
               " errors")
    else:
        branch = "INCONCLUSIVE"
        why = ("neither branch condition met: |alpha-1.5|=%.6f,"
               " |alpha-2.0|=%.6f, 2*se=%.6f"
               % (abs(alpha_main - 1.5), abs(alpha_main - 2.0),
                  2.0 * se_alpha_main))
    return {
        "branch": branch,
        "reason": why,
        "supports_condition_met": bool(supports),
        "refutes_condition_met": bool(refutes),
        "window_sensitive": bool(window_sensitive),
        "window_shift_abs": window_shift,
    }


