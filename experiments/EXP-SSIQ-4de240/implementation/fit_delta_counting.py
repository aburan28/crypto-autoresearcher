def git_state():
    def g(*a):
        try:
            return subprocess.check_output(["git"] + list(a),
                                           stderr=subprocess.DEVNULL
                                           ).decode().strip()
        except Exception:
            return None
    return {"commit": g("rev-parse", "HEAD"),
            "branch": g("rev-parse", "--abbrev-ref", "HEAD"),
            "dirty": bool(g("status", "--porcelain"))}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--cache-dir", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--null-cap", type=int, default=4000)
    ap.add_argument("--emit-file-hashes", action="store_true")
    args = ap.parse_args()

    t0 = time.time()
    started = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    log = lambda s: (print(s, flush=True))

    log("[%s] %s / %s" % (started, EXPERIMENT_ID, RUN_ID))
    log("loading dataset from %s" % args.cache_dir)
    records, file_hashes = load_dataset(args.cache_dir)
    log("  primes loaded: %d   p range: %d .. %d"
        % (len(records), min(records), max(records)))

    # ---- normalisation check (spec inputs.dataset.normalisation_check_required)
    bad_norm = [p for p in records if not records[p]["normalisation_ok"]]
    log("  normalisation check (H_reconstructed == floor(p/12)+e): "
        "%d / %d primes agree" % (len(records) - len(bad_norm), len(records)))

    # ---- coverage description
    complete_block = [p for p in records if p <= 22000]
    all_small = primes_upto(22000)
    complete_full = (len(complete_block) == len(all_small))
    selected_block = sorted(p for p in records if p > 22000)

    # ---- C-ANCHOR-LOW ----------------------------------------------------
    log("C-ANCHOR-LOW: N(1,p) vs the F_p-rational supersingular locus")
    anchor_low_rows = []
    anchor_low_bad = []
    anchor_low_skipped = [p for p in sorted(records) if p <= 3]
    for p in sorted(records):
        if p <= 3:
            continue        # the class-number identity is stated for p > 3
        obs = records[p]["n_delta_eq_1"]
        exp = fp_rational_ss_count(p)
        anchor_low_rows.append({"p": p, "N_T1": obs, "h_fp_rational": exp,
                                "match": bool(obs == exp)})
        if obs != exp:
            anchor_low_bad.append({"p": p, "observed": obs, "expected": exp})
    # scaling exponent of N(1,p) against p (the spec's "~ p^{1/2}")
    sc_rows = [(math.log(r["p"]), 0.0, math.log(r["N_T1"]))
               for r in anchor_low_rows if r["N_T1"] > 0]
    n_sc = len(sc_rows)
    sx = sum(r[0] for r in sc_rows) / n_sc
    sy = sum(r[2] for r in sc_rows) / n_sc
    sxy = sum((r[0] - sx) * (r[2] - sy) for r in sc_rows)
    sxx = sum((r[0] - sx) ** 2 for r in sc_rows)
    anchor_low_slope = sxy / sxx
    resid = sum((r[2] - sy - anchor_low_slope * (r[0] - sx)) ** 2
                for r in sc_rows)
    anchor_low_slope_se = math.sqrt(resid / (n_sc - 2) / sxx)
    # The PRE-REGISTERED criterion is the "~ p^{1/2}" scaling; the exact
    # class-number identity is a stronger supplementary check.  Both are
