def null_surrogate_counts(records, seed, cap, log=lambda s: None):
    """C-NULL.  Random positive-definite ternary quadratic forms of
    discriminant p/4, with the identical estimator over the identical window.

    Construction.  AOV section 5.1: the arithmetic object is the rank-3
    quadratic module (R, Q') with Discr(Q') = det of the half-integral Gram
    matrix = p/4, and delta_E = N1 = the first successive minimum.  The
    structure-free surrogate of the same shape is a RANDOM ternary lattice of
    the same determinant, carrying the Euclidean form.  We use the standard
    Goldstein-Mayer family

        L_v = { x in Z^3 : <x, v> = 0 mod q },   v uniform with gcd(v, q) = 1,

    which has index q in Z^3, hence Gram determinant exactly q^2, and which
    equidistributes in the space of lattices of that covolume as q grows.
    q = round(sqrt(p)/2) so that q^2 ~= p/4; the achieved determinant ratio
    q^2/(p/4) is recorded per prime.  N1_null = min_{x in L_v, x != 0} |x|^2,
    an integer, exactly as delta_E is.

    NO ARITHMETIC OF SUPERSINGULAR CURVES ENTERS.  Only the rank, the
    determinant and the positive-definiteness are shared with the real data.
    """
    import numpy as np
    rng = np.random.default_rng(seed)
    out = {}
    det_ratios = []
    for p in sorted(records):
        rec = records[p]
        H = rec["h_class_number_formula"]
        q = int(round(math.sqrt(p) / 2.0))
        if q < 2:
            q = 2
        det_ratios.append((q * q) / (p / 4.0))
        M = min(H, cap)
        # Hermite bound for a rank-3 lattice of determinant q^2:
        # lambda_1^2 <= 2^(1/3) * (q^2)^(1/3)
        hermite = (2.0 ** (1.0 / 3.0)) * (float(q * q) ** (1.0 / 3.0))
        bound = int(math.floor(hermite)) + 1
        cand = _candidates(bound)
        # sample v with gcd(v, q) = 1 (so the index is exactly q)
        vs = []
        need = M
        while need > 0:
            trial = rng.integers(0, q, size=(need * 2 + 8, 3), dtype=np.int64)
            g = np.gcd(np.gcd(trial[:, 0], trial[:, 1]),
                       np.gcd(trial[:, 2], q))
            g = np.gcd(g, q)
            ok = trial[g == 1]
            if len(ok):
                vs.append(ok)
                need -= len(ok)
        V = np.concatenate(vs, axis=0)[:M]
        mins = _lattice_minima(cand, V, q, bound)
        counts = np.bincount(mins, minlength=bound + 2)
        cum = np.cumsum(counts)
        out[p] = {"q": q, "M": M, "H": H,
                  "cum_frac": (cum / float(M)).tolist(),
                  "det_ratio": (q * q) / (p / 4.0)}
    return out, det_ratios


_CAND_CACHE = {}


def _candidates(bound):
    """All x in Z^3, one per +/- pair, with 0 < |x|^2 <= bound, sorted by
    |x|^2 ascending.  Returns (X [k,3] int64, norms [k] int64)."""
    import numpy as np
    if bound in _CAND_CACHE:
        return _CAND_CACHE[bound]
    r = int(math.isqrt(bound))
    pts = []
    for x in range(-r, r + 1):
        for y in range(-r, r + 1):
            for z in range(-r, r + 1):
                n = x * x + y * y + z * z
                if 0 < n <= bound:
                    if (x > 0) or (x == 0 and y > 0) or (x == 0 and y == 0
                                                         and z > 0):
                        pts.append((n, x, y, z))
    pts.sort()
    X = np.array([[a, b, c] for _, a, b, c in pts], dtype=np.int64)
    norms = np.array([n for n, _, _, _ in pts], dtype=np.int64)
    _CAND_CACHE.clear()
    _CAND_CACHE[bound] = (X, norms)
    return X, norms


def _lattice_minima(cand, V, q, bound):
    """First minimum |x|^2 of each L_v, by scanning candidates in ascending
    norm order and taking the first with <x, v> = 0 mod q."""
    import numpy as np
    X, norms = cand
    M = V.shape[0]
    res = np.full(M, -1, dtype=np.int64)
    todo = np.arange(M)
    step = 256
    i = 0
    while i < len(X) and len(todo):
        j = min(i + step, len(X))
        prod = (X[i:j] @ V[todo].T) % q
        hit = (prod == 0)
        any_hit = hit.any(axis=0)
        if any_hit.any():
            first = hit.argmax(axis=0)
            idx = np.where(any_hit)[0]
            res[todo[idx]] = norms[i:j][first[idx]]
            todo = todo[~any_hit]
        i = j
        step = min(step * 2, 8192)
    if (res < 0).any():
        # cannot happen: the Hermite bound guarantees a vector within `bound`
        raise RuntimeError("lattice minimum exceeded the Hermite bound")
    return res


def build_null_cells(records, nullcounts, p_min):
    cells = []
    for p in sorted(records):
        if p < p_min:
            continue
        tmax = tmax_theorem(p)
        nc = nullcounts[p]
        H = nc["H"]
        cf = nc["cum_frac"]
        for T in range(2, tmax + 1):
            if T >= len(cf):
                frac = cf[-1]
            else:
                frac = cf[T]
            n = H * frac
            cells.append({"p": p, "T": T, "Tmax": tmax, "N_curves": n})
    kept = [r for r in cells if r["T"] <= math.floor(0.9 * r["Tmax"])]
    return [r for r in kept if r["N_curves"] >= 10]


