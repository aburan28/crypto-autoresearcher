"""
CTRL-NULL-RRG / HEUR-ISO-1 synthetic random-regular-graph null, per
specification.yaml. Pure combinatorial Monte Carlo -- NO elliptic-curve
arithmetic at all -- validating the MODEL'S OWN IMPLEMENTATION of the
hitting-time closed form P(r* > r) ~= (1 - s/n)^{B_r}, B_r = d(d-1)^{r-1},
independently of any curve-specific effect (specification.yaml
controls.CTRL-NULL-RRG.failure_meaning).

Graph model: a uniformly random d-regular graph on n labeled vertices,
generated by the standard configuration-model pairing (stub-matching with
rejection on self-loops/multi-edges), which is the direct combinatorial
object HEUR-ISO-1's formal_statement describes. A uniformly random subset S
of size s is marked special; hitting time r* is the BFS distance from a
uniformly random start vertex to the nearest vertex of S.
"""
from __future__ import annotations
import random
from collections import deque


def random_regular_graph(n: int, d: int, rng: random.Random, max_regen: int = 200):
    """Configuration-model random d-regular graph on n vertices (n*d even).
    Returns adjacency list. Retries on self-loop/multi-edge collision."""
    if (n * d) % 2 != 0:
        raise ValueError("n*d must be even for a d-regular graph to exist")
    for _ in range(max_regen):
        stubs = [v for v in range(n) for _ in range(d)]
        rng.shuffle(stubs)
        adj = [set() for _ in range(n)]
        ok = True
        for i in range(0, len(stubs), 2):
            u, v = stubs[i], stubs[i + 1]
            if u == v or v in adj[u]:
                ok = False
                break
            adj[u].add(v)
            adj[v].add(u)
        if ok:
            return [sorted(s) for s in adj]
    raise RuntimeError(f"failed to generate a simple {d}-regular graph on {n} vertices after {max_regen} tries")


def hitting_times(adj, special_set, rng: random.Random, num_starts: int):
    """BFS hitting time to `special_set` from `num_starts` uniformly random
    start vertices (with replacement). Returns list of r* values (int),
    using len(adj) as a sentinel for 'not reached within the graph's own
    diameter' (shouldn't happen on a connected graph, recorded if it does)."""
    n = len(adj)
    results = []
    for _ in range(num_starts):
        start = rng.randrange(n)
        if start in special_set:
            results.append(0)
            continue
        dist = [-1] * n
        dist[start] = 0
        q = deque([start])
        found = None
        while q:
            u = q.popleft()
            for v in adj[u]:
                if dist[v] == -1:
                    dist[v] = dist[u] + 1
                    if v in special_set:
                        found = dist[v]
                        q.clear()
                        break
                    q.append(v)
            if found is not None:
                break
        results.append(found if found is not None else n)  # sentinel: unreached
    return results


def predicted_survival(r: int, d: int, n: int, s: int) -> float:
    B_r = d * (d - 1) ** (r - 1) if r >= 1 else 1
    base = max(0.0, 1.0 - s / n)
    return base ** B_r


def ks_distance(empirical_r_values, d: int, n: int, s: int, r_max: int) -> float:
    """KS distance between empirical CDF of r* and the model's predicted
    CDF (1 - predicted_survival(r))."""
    total = len(empirical_r_values)
    max_dist = 0.0
    for r in range(0, r_max + 1):
        emp_cdf = sum(1 for v in empirical_r_values if v <= r) / total
        pred_cdf = 1.0 - predicted_survival(r, d, n, s)
        max_dist = max(max_dist, abs(emp_cdf - pred_cdf))
    return max_dist


def run_rrg_null(n: int, s: int, d: int, num_starts: int, rng: random.Random, r_max: int = None):
    adj = random_regular_graph(n, d, rng)
    special_set = set(rng.sample(range(n), s))
    r_values = hitting_times(adj, special_set, rng, num_starts)
    if r_max is None:
        r_max = max(r_values) if r_values else 1
    ks = ks_distance(r_values, d, n, s, r_max)
    return {
        "n": n, "s": s, "d": d, "num_starts": num_starts,
        "r_values_summary": {
            "min": min(r_values), "max": max(r_values),
            "mean": sum(r_values) / len(r_values),
        },
        "ks_distance": ks,
        "r_max_used": r_max,
    }
