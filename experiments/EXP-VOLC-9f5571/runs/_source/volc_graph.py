# --------------------------------------------------------------------------
# ell = 2 Velu formulas -- NOT in harness.isogeny_class.velu_odd, which
# REFUSES even ell (CORR-20260807-3ee25d). Kernel is generated by a single
# rational 2-torsion point Q = (x0, 0); there is no +/- pairing (Q = -Q), so
# the sum in Velu's formula is over the single point Q, with u_Q = 0 because
# y_Q = 0.
# --------------------------------------------------------------------------


def velu2(E: EllipticCurve, x0: int) -> tuple[int, int]:
    """Kernel {O, Q} with Q = (x0, 0) NOT paired with a distinct -Q (Q = -Q,
    since it is 2-torsion), so unlike the odd-ell case the per-point term is
    NOT doubled: v_Q = g_x(Q) = 3x0^2 + a (single point, weight 1), u_Q = 0
    since y_Q = 0. This is the correction to an earlier draft of this function
    that doubled v_Q as if Q were paired with a distinct point (which produced
    a wrong-trace target curve on the very first test -- caught by testing
    against SR1 before any run was written, not discovered later)."""
    p, a, b = E.p, E.a, E.b
    x0 %= p
    v = (3 * x0 * x0 + a) % p                # v_Q = g_x(Q), weight 1 (no pairing)
    w = (x0 * v) % p                          # w_Q = u_Q + x0*v_Q = x0*v_Q (u_Q=0)
    return (a - 5 * v) % p, (b - 7 * w) % p


def velu2_image(E: EllipticCurve, x0: int, P: Point) -> Point:
    if P is None:
        return None
    p, a = E.p, E.a
    x0 %= p
    x, y = P
    if (x - x0) % p == 0:
        return None
    v = (3 * x0 * x0 + a) % p
    d = pow((x - x0) % p, -1, p)
    X = (x + v * d) % p
    Y = (y - v * y * d * d) % p
    return (X, Y)


def two_torsion_roots(E: EllipticCurve) -> list[int]:
    """x-coordinates of rational 2-torsion points -- used ONLY to build Velu
    kernels, never reported or used as a level variable (prohibition honored
    by construction: this list is consumed by `velu2`/`velu2_image` and by
    nothing that assigns a level)."""
    p, a, b = E.p, E.a, E.b
    return [x for x in range(p) if (x * x % p * x + a * x + b) % p == 0]


# --------------------------------------------------------------------------
# odd ell (3, 107): reuse harness.isogeny_class.velu_odd, but we need EVERY
# rational order-ell subgroup, not just one generator (find_kernel_generator
# returns a single point). Exhaustive scan over liftable x, toy scale only.
# --------------------------------------------------------------------------


def ell_subgroup_generators(E: EllipticCurve, order: int, ell: int) -> list[Point]:
    """One representative point per rational order-ell subgroup of E(F_p)."""
    if order % ell:
        return []
    cof = order // ell
    seen: set[Point] = set()
    gens: list[Point] = []
    for x in range(E.p):
        P = E.lift_x(x)
        if P is None:
            continue
        R = E.mul(cof, P)
        if R is None or R in seen:
            continue
        if E.mul(ell, R) is not None:
            continue  # R does not have order exactly ell (should not happen: ell prime)
        gens.append(R)
        Q = R
        for _ in range(ell - 1):
            seen.add(Q)
            Q = E.add(Q, R)
    return gens


# --------------------------------------------------------------------------
# isomorphism test: (a1,b1) ~ (a2,b2) iff exists u in F_p^* with
# a2 = u^4 a1, b2 = u^6 b1 (contract level_construction). Handles j=0
# (a=0, sextic twist) and j=1728 (b=0, quartic twist) specially.
# --------------------------------------------------------------------------


def _nth_roots(val: int, n: int, p: int) -> list[int]:
    val %= p
    try:
        r = nthroot_mod(val, n, p, all_roots=True)
    except Exception:
        return []
    if r is None:
        return []
    if isinstance(r, list):
        return r
    return [r]


def isomorphic(p: int, a1: int, b1: int, a2: int, b2: int) -> bool:
    a1, b1, a2, b2 = a1 % p, b1 % p, a2 % p, b2 % p
    if (a1 == 0) != (a2 == 0):
        return False
    if (b1 == 0) != (b2 == 0):
        return False
    if a1 == 0 and b1 == 0:
        raise ValueError("singular curve passed to isomorphic()")
    if a1 == 0:                              # j = 0, sextic twist on b
        ratio = b2 * pow(b1, -1, p) % p
        return bool(_nth_roots(ratio, 6, p))
    if b1 == 0:                              # j = 1728, quartic twist on a
        ratio = a2 * pow(a1, -1, p) % p
        return bool(_nth_roots(ratio, 4, p))
    ratio4 = a2 * pow(a1, -1, p) % p
    ratio6 = b2 * pow(b1, -1, p) % p
    cands = _nth_roots(ratio4, 4, p)
    return any(pow(u, 6, p) == ratio6 for u in cands)


# --------------------------------------------------------------------------
# graph construction
# --------------------------------------------------------------------------


@dataclass
class VolcanoGraph:
    p: int
    ell: int
    labels: list[str]
    adj: dict            # label -> sorted list of neighbor labels (undirected, deduped)
    edges_directed: list  # raw (source_label, target_label, kernel_repr) found from Velu
    unmatched: list       # Velu images that matched no vertex in the class -- FATAL if nonempty
    degree: dict          # label -> int


def build_ell2_graph(p: int, records: list[CurveRecord]) -> VolcanoGraph:
    by_ab = {(r.a, r.b): r for r in records}
    adj: dict[str, set[str]] = {r.label: set() for r in records}
    directed = []
    unmatched = []
    for r in records:
        E = r.curve()
        for x0 in two_torsion_roots(E):
            ta, tb = velu2(E, x0)
            match = by_ab.get((ta % p, tb % p))
            if match is None:
                # fall back to isomorphism search (should not be needed for
                # ell=2 since velu2's output IS a specific model, but kept for
                # honesty rather than silently trusting exact-tuple lookup)
                for cand in records:
                    if isomorphic(p, ta, tb, cand.a, cand.b):
                        match = cand
                        break
            if match is None:
                unmatched.append({"source": r.label, "kernel_x0": x0,
                                  "target_ab": [ta, tb]})
                continue
            adj[r.label].add(match.label)
            adj[match.label].add(r.label)
            directed.append((r.label, match.label, x0))
    degree = {k: len(v) for k, v in adj.items()}
    return VolcanoGraph(p=p, ell=2, labels=[r.label for r in records],
                        adj={k: sorted(v) for k, v in adj.items()},
                        edges_directed=directed, unmatched=unmatched,
                        degree=degree)


def build_odd_ell_graph(p: int, ell: int, records: list[CurveRecord]) -> VolcanoGraph:
    by_ab = {(r.a, r.b): r for r in records}
    adj: dict[str, set[str]] = {r.label: set() for r in records}
    directed = []
    unmatched = []
    for r in records:
        E = r.curve()
        gens = ell_subgroup_generators(E, r.order, ell)
        for g in gens:
            ta, tb, _kx = velu_odd(E, g, ell)
            match = by_ab.get((ta % p, tb % p))
            if match is None:
                for cand in records:
                    if isomorphic(p, ta, tb, cand.a, cand.b):
                        match = cand
                        break
            if match is None:
                unmatched.append({"source": r.label, "kernel_gen": list(g),
                                  "target_ab": [ta, tb]})
                continue
            adj[r.label].add(match.label)
            adj[match.label].add(r.label)
            directed.append((r.label, match.label, list(g)))
    degree = {k: len(v) for k, v in adj.items()}
    return VolcanoGraph(p=p, ell=ell, labels=[r.label for r in records],
                        adj={k: sorted(v) for k, v in adj.items()},
                        edges_directed=directed, unmatched=unmatched,
                        degree=degree)


# --------------------------------------------------------------------------
# level assignment: leaf-prune to the 2-core (crater), then BFS distance.
# Purely graph-theoretic; no CM/conductor arithmetic used.
# --------------------------------------------------------------------------


def assign_levels(vg: VolcanoGraph) -> tuple[dict, set]:
    remaining = set(vg.labels)
    work = {k: set(v) for k, v in vg.adj.items()}
    while True:
        leaves = [v for v in remaining if len(work[v] & remaining) <= 1]
        if not leaves or len(leaves) == len(remaining):
            break
        for v in leaves:
            remaining.discard(v)
    core = set(remaining)
    dist: dict[str, int | None] = {v: None for v in vg.labels}
    dq: deque = deque()
    for v in core:
        dist[v] = 0
        dq.append(v)
    while dq:
        u = dq.popleft()
        for w in vg.adj[u]:
            if dist[w] is None:
                dist[w] = dist[u] + 1
                dq.append(w)
    return dist, core


def level_counts(dist: dict) -> dict:
    out: dict[int, int] = {}
    for v in dist.values():
        if v is None:
            out["UNREACHED"] = out.get("UNREACHED", 0) + 1
        else:
            out[v] = out.get(v, 0) + 1
    return out
