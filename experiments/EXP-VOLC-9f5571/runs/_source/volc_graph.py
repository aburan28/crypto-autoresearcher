"""EXP-VOLC-9f5571 (GOAL-ENDO-001, BATCH-d7e255) -- NEW module, NEW driver.

Explicit Velu ell-isogeny volcano graph builder for general odd ell (3, 107)
and a dedicated ell=2 formula (needed for the SR1 gate; `harness.isogeny_class
.velu_odd` refuses ell=2 by design -- CORR-20260807-3ee25d defect D1). This
module does not edit and does not reimplement `harness/exp_icinv.py`
(source_constraints, invalidation_rules). It imports read-only from
`harness.isogeny_class`, `harness.toycurve` and `harness.exp_icinv_fullgroup`.

Level is assigned PURELY GRAPH-THEORETICALLY, with no arithmetic shortcut:
1. build the explicit isogeny graph (vertices = curves in the class up to
   F_p-isomorphism, edges = Velu ell-isogenies, resolved to a target vertex by
   the isomorphism test (a,b) ~ (u^4 a, u^6 b));
2. iteratively prune degree-<=1 leaves until only the 2-core (the crater
   cycle) remains -- this is standard leaf-pruning to find a graph's core and
   needs no CM-theoretic input;
3. level(v) = BFS distance from the crater core, over the full graph.

Two_torsion_x_count / ell_subgroup_count(.,2) are NEVER used as the level
variable (level_proxy_prohibited); 2-torsion root-finding is used ONLY to
locate ell=2 kernel points for the Velu construction itself, which is what the
contract's level_construction paragraph specifies.
"""
