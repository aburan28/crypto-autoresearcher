"""Method A: the Frobenius-stable subspace lattice of F_{q^n}, from integer data only.

F_{q^n} is free of rank one over R = F_q[T]/(T^n - 1) with T acting as the q-power
Frobenius sigma (normal basis theorem), so sigma-stable F_q-subspaces correspond
exactly to ideals of R, i.e. to monic divisors of T^n - 1 over F_q.  The ideal
generated by g has F_q-dimension n - deg g.

Nothing here factors a polynomial.  For gcd(n, q) = 1 the irreducible factors of
T^n - 1 over F_q are in bijection with the q-cyclotomic cosets mod n, with degree
equal to the coset size; when p | n, write n = p^e * n' and every factor of
T^{n'} - 1 is repeated p^e times.  So the whole lattice is integer arithmetic.
"""
from math import gcd


def cyclotomic_cosets(q, n):
    """q-cyclotomic cosets mod n (requires gcd(q, n) == 1). Returns sorted tuples."""
    assert gcd(q, n) == 1, "cyclotomic cosets need gcd(q, n) == 1"
    seen, cosets = set(), []
    for a in range(n):
        if a in seen:
            continue
        c, x = [], a
        while x not in c:
            c.append(x)
            seen.add(x)
            x = (x * q) % n
        cosets.append(tuple(sorted(c)))
    return sorted(cosets)


def factor_degrees(q, n):
    """Multiset of degrees of the irreducible factors of T^n - 1 over F_q.

    Returns (degrees, repetition) where the true multiset is `degrees` each
    repeated `repetition` = p^e times, p = char F_q, p^e || n.
    """
    p = _char(q)
    e, n_prime = 0, n
    while n_prime % p == 0:
        n_prime //= p
        e += 1
    degs = [len(c) for c in cyclotomic_cosets(q, n_prime)]
    return degs, p ** e


def _char(q):
    for p in range(2, q + 1):
        if q % p == 0:
            while q % p == 0:
                q //= p
            assert q == 1, "q must be a prime power"
            return p
    raise ValueError("q must be >= 2")


def attainable_dimensions(q, n):
    """Exact set of F_q-dimensions of sigma-stable subspaces of F_{q^n}."""
    degs, rep = factor_degrees(q, n)
    reachable = {0}
    for d in degs:
        # each irreducible factor may be taken with multiplicity 0..rep
        reachable = {s + k * d for s in reachable for k in range(rep + 1)}
    assert max(reachable) == n, f"dimension spectrum must top out at n: {max(reachable)} != {n}"
    return sorted(reachable)


def num_stable_subspaces(q, n):
    """Exact number of sigma-stable subspaces = number of monic divisors of T^n - 1."""
    degs, rep = factor_degrees(q, n)
    return (rep + 1) ** len(degs)


def min_faithful_dimension(q, n):
    """Smallest dim of a stable V on which sigma does NOT act trivially.

    sigma acts trivially exactly on the (T-1)-primary part; the smallest stable
    subspace containing a vector with nontrivial orbit is the one cut by the
    smallest irreducible factor of T^n - 1 other than (T - 1).
    """
    degs, _ = factor_degrees(q, n)
    others = sorted(d for d in degs if d != 1) or []
    # degree-1 factors other than (T-1) exist only when n has other roots of unity
    # in F_q; handle by counting: if more than one degree-1 factor, min is 1.
    ones = [d for d in degs if d == 1]
    if len(ones) > 1:
        return 1
    return others[0] if others else None
