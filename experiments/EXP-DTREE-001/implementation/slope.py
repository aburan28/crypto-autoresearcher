"""RUN-DTREE-002: exact-enumeration slope measurement (C1), CTRL-ENUMERATION-
AUDIT, and the pre-registered tail checks -- run against the frozen grid
produced by instances.py/RUN-DTREE-001.

If the frozen grid has fewer than 6 non-saturated cells (design_infeasible,
per the "freeze" stage stop rule), the confirmatory slope fit, the audit, and
the tail checks are all reported as not_applicable with the reason, and
nothing is improvised in their place. A small, clearly separated diagnostic
(one illustrative point per tiny curve at B'=8, OUTSIDE the frozen grid) is
additionally computed for transparency only -- it is never used in the
confirmatory fit or compared against gamma=2/gamma=3.
"""
from __future__ import annotations

import math
import random

import numpy as np
from scipy import stats as scipy_stats

from harness.semaev import build_factor_base
from harness.toycurve import EllipticCurve, ECDLPInstance
import curvegroup as cg

Z_95 = 1.959963984540054


def _fb_for_tiny(rec: dict, size: int) -> list[int]:
    inst = ECDLPInstance(p=rec["p"], a=rec["a"], b=rec["b"],
                          P=tuple(rec["P"]), Q=tuple(rec["Q"]),
                          n=rec["n"], k=rec["k"], field_bits=rec["field_bits"],
                          seed=rec["seed"])
    return build_factor_base(inst, size)


def subgroup_points(E: EllipticCurve, P, N: int) -> set:
    """The exact N-element cyclic subgroup <P> = {c*P : c in [0, N)}.

    Needed because harness.semaev.build_factor_base samples x-coordinates
    from the WHOLE curve E(F_p), which is only <P> itself when the curve's
    cofactor is 1. These toy curves are generated by generate_instance's
    "first curve meeting a low bar" search and frequently have cofactor > 1
    (recorded as an anomaly in implementation.md), so a signed sum of
    factor-base points can land outside <P> even though the target R = a*P +
    b*Q is, by construction, always inside it. P_dec must be computed as a
    fraction of THIS N-element universe, not of the (possibly much larger)
    full curve group -- otherwise the count is not even bounded by N.
    """
    pts = set()
    cur = None
    for _ in range(N):
        pts.add(cur)
        cur = E.add(cur, P)
    return pts


def exact_p_dec(rec: dict, b_prime: int) -> dict:
    E = EllipticCurve(rec["p"], rec["a"], rec["b"])
    V = _fb_for_tiny(rec, b_prime)
    N = rec["n"]
    universe = subgroup_points(E, tuple(rec["P"]), N)
    combo_multiplicity: dict = {}       # multiplicity WITHIN the subgroup only
    achieved_in_subgroup = set()
    achieved_outside_subgroup = 0
    import itertools
    for v1, v2, v3 in itertools.combinations(V, 3):
        for p1 in cg.signed_variants(E, v1):
            for p2 in cg.signed_variants(E, v2):
                s12 = E.add(p1, p2)
                for p3 in cg.signed_variants(E, v3):
                    s = E.add(s12, p3)
                    if s in universe:
                        achieved_in_subgroup.add(s)
                        combo_multiplicity[s] = combo_multiplicity.get(s, 0) + 1
                    else:
                        achieved_outside_subgroup += 1
    count = len(achieved_in_subgroup)
    return {
        "b_prime": b_prime, "n": N, "count_decomposable": count,
        "p_dec": count / N,
        "max_multiplicity": max(combo_multiplicity.values()) if combo_multiplicity else 0,
        "multiplicity_histogram": _hist(combo_multiplicity),
        "signed_sums_landing_outside_subgroup": achieved_outside_subgroup,
        "factor_base": V,
    }


def _hist(mult: dict) -> dict:
    h: dict = {}
    for v in mult.values():
        h[v] = h.get(v, 0) + 1
    return {str(k): v for k, v in sorted(h.items())}


def audit_cell(rec: dict, b_prime: int) -> dict:
    """CTRL-ENUMERATION-AUDIT: an INDEPENDENT code path (the Semaev S4
    algebraic identity, evaluated target-first over the group's x-coordinate
    universe) recomputes the same cell as exact_p_dec (which sums points
    directly, combination-first) and the counts must agree exactly.

    exact_p_dec counts ACHIEVED POINTS (out of N group elements); the S4
    identity can only see X-COORDINATES (it is agnostic to which of +-R is
    meant). The two are reconciled via a checked algebraic identity, not
    assumed: decomposability is invariant under negating every summand's
    sign, so nontrivial achieved points pair up {R,-R} sharing one
    x-coordinate, while the identity O is self-paired and has no
    x-coordinate. See _audit_agrees.
    """
    E = EllipticCurve(rec["p"], rec["a"], rec["b"])
    V = _fb_for_tiny(rec, b_prime)
    N = rec["n"]
    primary = exact_p_dec(rec, b_prime)

    universe_x_nonnull = set()
    cur = None
    for _ in range(N):
        if cur is not None:
            universe_x_nonnull.add(cur[0])
        cur = E.add(cur, tuple(rec["P"]))
    universe_x_nonnull = sorted(universe_x_nonnull)

    reachable_x = cg.enumerate_decomposable_arity3_via_semaev(
        rec["a"], rec["b"], rec["p"], V, universe_x_nonnull)
    o_achieved = _is_identity_achieved(E, V)

    return {
        "b_prime": b_prime,
        "primary_count_decomposable": primary["count_decomposable"],
        "audit_reachable_x_count": len(reachable_x),
        "identity_O_achieved_primary": o_achieved,
        "agrees": _audit_agrees(primary, reachable_x, o_achieved),
    }


def _is_identity_achieved(E: EllipticCurve, V: list[int]) -> bool:
    import itertools
    for v1, v2, v3 in itertools.combinations(V, 3):
        for p1 in cg.signed_variants(E, v1):
            for p2 in cg.signed_variants(E, v2):
                s12 = E.add(p1, p2)
                for p3 in cg.signed_variants(E, v3):
                    if E.add(s12, p3) is None:
                        return True
    return False


def _audit_agrees(primary, reachable_x, o_achieved) -> bool:
    """Exact agreement check: point-count = 2*|reachable_x| + (1 if O achieved else 0).

    Justification (audit parity): decomposability is invariant under R -> -R
    (negating every summand's sign choice), so nontrivial achieved points
    pair up {R,-R}, each pair sharing one x-coordinate; O is self-paired and
    has no x-coordinate. This is an algebraic identity checked here, not
    assumed -- if it fails, both code paths are compared and the discrepancy
    is reported rather than silently reconciled.
    """
    expected = 2 * len(reachable_x) + (1 if o_achieved else 0)
    return expected == primary["count_decomposable"]


def poisson_multiplicity_check(cell: dict, rng: np.random.Generator, n_trials_sim: int = 2000) -> dict:
    """Multiplicity tail check: compare the observed max tuple-sum
    multiplicity to a simulated Poisson(lambda)-max prediction, lambda =
    C(b_prime,3)/n (mean multiplicity if sums landed uniformly at random)."""
    from math import comb
    lam = comb(cell["b_prime"], 3) * 8 / cell["n"] if cell["n"] > 0 else 0.0
    # 8x: each combination contributes up to 8 signed sums (see enumerate_decomposable_arity3)
    n = cell["n"]
    if lam <= 0 or n <= 0:
        return {"lambda_per_element": lam, "observed_max_multiplicity": cell["max_multiplicity"],
                "simulated_pctile_99": None, "flag": None}
    sim = rng.poisson(lam, size=(n_trials_sim, n)).max(axis=1)
    pctl99 = float(np.percentile(sim, 99))
    return {
        "lambda_per_element": lam,
        "observed_max_multiplicity": cell["max_multiplicity"],
        "simulated_pctile_99": pctl99,
        "flag_exceeds_99th": cell["max_multiplicity"] > pctl99,
    }


def birthday_prediction(b_prime: int, n: int) -> float:
    from math import comb
    lam = comb(b_prime, 3) / n if n > 0 else 0.0
    return n * (1 - math.exp(-lam))


def fit_slope(cells: list[dict]) -> dict:
    """Least-squares log-slope of exact P_dec versus B' over pooled cells."""
    log_b = np.array([math.log(c["b_prime"]) for c in cells])
    log_p = np.array([math.log(c["p_dec"]) for c in cells])
    res = scipy_stats.linregress(log_b, log_p)
    slope, intercept, rvalue, pvalue, stderr = res
    n = len(cells)
    dof = max(n - 2, 1)
    tcrit = float(scipy_stats.t.ppf(0.975, dof)) if n > 2 else float("inf")
    half_width = float(tcrit * stderr) if n > 2 else float("inf")
    ci_lo, ci_hi = float(slope) - half_width, float(slope) + half_width
    return {
        "n_cells": n, "slope_gamma": float(slope), "intercept": float(intercept),
        "r_value": float(rvalue), "p_value": float(pvalue), "stderr": float(stderr),
        "dof": dof, "ci_95": [ci_lo, ci_hi],
        "ci_contains_gamma_2_heur001": bool(ci_lo <= 2.0 <= ci_hi),
        "ci_contains_gamma_3_birthday": bool(ci_lo <= 3.0 <= ci_hi),
    }


def run_slope_measurement(frozen: dict, audit_seed: int = 20260807) -> dict:
    tiny = frozen["tiny_instances"]
    grid = frozen["slope_grid"]
    design_infeasible = grid["design_infeasible"]

    result = {
        "design_infeasible": design_infeasible,
        "total_qualifying_cells": grid["total_qualifying_cells"],
        "min_cells_required": grid["rule"]["min_cells_required_across_all_tiny_curves"],
        "lambda_tables": {bits: tiny[bits]["lambda_table"] for bits in tiny},
        "confirmatory_slope_fit": None,
        "ctrl_enumeration_audit": None,
        "tail_checks": None,
        "diagnostic_illustrative_points": {},
    }

    rng = np.random.default_rng(audit_seed)
    pyrandom = random.Random(audit_seed)

    if not design_infeasible:
        cells = []
        per_curve_cells = {}
        for bits, rec in tiny.items():
            qualifying = rec["qualifying_b_prime"]
            curve_cells = [exact_p_dec(rec, bp) for bp in qualifying]
            per_curve_cells[bits] = curve_cells
            cells.extend(curve_cells)
        result["confirmatory_slope_fit"] = fit_slope(cells)
        result["cells_by_curve"] = per_curve_cells

        audits = {}
        for bits, rec in tiny.items():
            qualifying = rec["qualifying_b_prime"]
            if not qualifying:
                audits[bits] = {"applicable": False, "reason": "no qualifying cells on this curve"}
                continue
            chosen = pyrandom.choice(qualifying)
            audits[bits] = {"applicable": True, "chosen_b_prime": chosen,
                             **audit_cell(rec, chosen)}
        result["ctrl_enumeration_audit"] = audits

        tail = {}
        for bits, rec in tiny.items():
            curve_cells = per_curve_cells[bits]
            if not curve_cells:
                tail[bits] = {"applicable": False, "reason": "no qualifying cells on this curve"}
                continue
            largest = max(curve_cells, key=lambda c: c["b_prime"])
            pred = birthday_prediction(largest["b_prime"], rec["n"])
            deviation = abs(largest["count_decomposable"] - pred) / pred if pred > 0 else None
            zero_cells = [c["b_prime"] for c in curve_cells if c["count_decomposable"] == 0]
            tail[bits] = {
                "applicable": True,
                "extreme_cell_agreement": {
                    "largest_b_prime": largest["b_prime"],
                    "observed_count": largest["count_decomposable"],
                    "birthday_predicted_count": pred,
                    "relative_deviation": deviation,
                    "flag_exceeds_10pct": (deviation is not None and deviation > 0.10),
                },
                "multiplicity_tail": poisson_multiplicity_check(largest, rng),
                "zero_cell_audit": {
                    "zero_cells": zero_cells,
                    "note": ("re-verified via CTRL-ENUMERATION-AUDIT above if the "
                             "audited cell is among them") if zero_cells else "no zero cells observed",
                },
            }
        result["tail_checks"] = tail
    else:
        result["confirmatory_slope_fit"] = {
            "applicable": False,
            "reason": (f"design_infeasible: {grid['total_qualifying_cells']} qualifying "
                       f"cells found across the three tiny curves, fewer than the required "
                       f"{grid['rule']['min_cells_required_across_all_tiny_curves']}"),
        }
        result["ctrl_enumeration_audit"] = {
            "applicable": False,
            "reason": "no qualifying cells exist on any tiny curve to audit",
        }
        result["tail_checks"] = {
            "applicable": False,
            "reason": "no qualifying cells exist on any tiny curve",
        }

    # Diagnostic only: illustrative exact P_dec at B'=8 per tiny curve,
    # OUTSIDE the frozen grid, never used in the confirmatory fit or the
    # gamma=2/gamma=3 comparison. Recorded for transparency about why the
    # grid is empty (deep saturation at the smallest allowed B').
    for bits, rec in tiny.items():
        diag = exact_p_dec(rec, GRID_MIN_BPRIME_DIAG)
        result["diagnostic_illustrative_points"][bits] = {
            "note": "OUTSIDE the frozen grid; not part of the confirmatory slope fit",
            **diag,
        }

    return result


GRID_MIN_BPRIME_DIAG = 8
