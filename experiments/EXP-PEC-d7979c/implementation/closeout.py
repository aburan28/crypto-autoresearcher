def band_index(ell):
    """Karatsuba recursion bands on the value ell+1: [16,31], [32,63], ...
    Band 0 is ell+1 < 16 (poly_mul_kara delegates to schoolbook there)."""
    v = ell + 1
    if v < KARATSUBA_THRESHOLD_BANDS_FROM:
        return 0
    return int(math.floor(math.log2(v / float(KARATSUBA_THRESHOLD_BANDS_FROM)))) + 1


def truth_value(arm, params, x):
    """Ground truth y at regressor x = log2(ell), by construction."""
    a = params["log2_A_true"]
    g = params["gamma_true"]
    base = a + g * x
    if arm == "T-POWER":
        return base
    if arm == "T-BAND":
        ell = 2.0 ** x
        return base + params["delta_band"] * band_index(ell)
    if arm == "T-SATURATE":
        return base - params["kappa"] * x * x
    if arm == "T-BREAK":
        xb = math.log2(BREAKPOINT_ELL)
        if x <= xb:
            return base
        return a + g * xb + (g + params["d"]) * (x - xb)
    raise ValueError(arm)


