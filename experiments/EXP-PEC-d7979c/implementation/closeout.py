def four_point_trend(per_ell_map, ells):
    """Retirement clause (d): OLS slope of alpha_hat on log2(ell) over the four
    new ell, with a four-point interval, which must contain 0."""
    xs = [math.log2(e) for e in ells if str(e) in per_ell_map]
    ys = [per_ell_map[str(e)]["alpha_hat"] for e in ells if str(e) in per_ell_map]
    if len(xs) < 3:
        return {"n": len(xs), "slope": None, "interval": [None, None],
                "contains_zero": None,
                "note": "fewer than three points; no trend interval defined"}
    f = PE.ols(xs, ys)
    n = len(xs)
    tq = PE.t_quantile_975(n - 2)
    se = f["slope_se"]
    lo, hi = f["slope"] - tq * se, f["slope"] + tq * se
    return {"n": n, "ell": [e for e in ells if str(e) in per_ell_map],
            "alpha_hat": ys, "slope": f["slope"], "slope_se": se,
            "t_quantile_0975_df": tq, "interval": [lo, hi],
            "contains_zero": bool(lo <= 0.0 <= hi), "r2": f["r2"]}


