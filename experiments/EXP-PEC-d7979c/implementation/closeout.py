def fit_stats(xs, ys):
    """OLS plus everything the variance-aware tolerance needs."""
    f = PE.ols(xs, ys)
    n = len(xs)
    xbar = sum(xs) / n
    sxx = sum((x - xbar) ** 2 for x in xs)
    s = math.sqrt(f["sse"] / (n - 2)) if n > 2 else float("nan")
    return {"n": n, "slope": f["slope"], "intercept": f["intercept"],
            "sse": f["sse"], "r2": f["r2"], "s": s, "xbar": xbar, "Sxx": sxx}


def se_pred(st, xstar):
    return st["s"] * math.sqrt(1.0 / st["n"] + (xstar - st["xbar"]) ** 2 / st["Sxx"])


def tolerance_T(sep):
    return max(TOL_FLOOR, TOL_MULT * sep)


def classify(abs_err, T):
    """gate_verdicts_available: [PASS-WITH-POWER, FAIL, NO-POWER]."""
    if T > NO_POWER_ABOVE:
        return "NO-POWER"
    return "PASS-WITH-POWER" if abs_err <= T else "FAIL"


