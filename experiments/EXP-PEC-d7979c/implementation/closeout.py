def run_primes(root, modpoly_dir, scratch):
    procs = []
    paths = {}
    for label, bound in PRIME_BOUNDS:
        op = os.path.join(scratch, "prime_%s.json" % label)
        paths[label] = op
        pr = mp.Process(target=_prime_worker,
                        args=(label, bound, modpoly_dir, op))
        pr.start()
        procs.append((label, pr))
        log("  launched prime worker %s (2^%d)" % (label, bound))
    arms = {}
    for label, pr in procs:
        pr.join()
        log("  prime worker %s exited rc=%s" % (label, pr.exitcode))
        with open(paths[label]) as fh:
            arms[label] = json.load(fh)
        arms[label]["child_exitcode"] = pr.exitcode
    return arms


