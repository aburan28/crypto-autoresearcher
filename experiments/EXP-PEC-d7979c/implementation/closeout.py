def primes_upto(n):
    bs = bytearray([1]) * (n + 1)
    bs[0] = bs[1] = 0
    for i in range(2, int(n ** 0.5) + 1):
        if bs[i]:
            bs[i * i::i] = bytearray(len(bs[i * i::i]))
    return [i for i in range(n + 1) if bs[i]]


def enumerate_smooth_buckets(X, B):
    """EXACT integer enumeration of every B-smooth d <= X, bucketed by its
    largest prime factor P(d).  Returns (sum_d, sum_psi(d), count) per bucket.
    psi is the Dedekind psi (cyclic-kernel count): psi(d) = prod p^(e-1)(p+1),
    accumulated as an exact integer."""
    ps = primes_upto(B)
    Td, Tp, Cn = {}, {}, {}

    def rec(i, val, psi, maxp):
        Td[maxp] = Td.get(maxp, 0) + val
        Tp[maxp] = Tp.get(maxp, 0) + psi
        Cn[maxp] = Cn.get(maxp, 0) + 1
        for k in range(i, len(ps)):
            p = ps[k]
            if val > X // p:
                break
            v = val * p
            pn = psi * (p + 1)
            while True:
                rec(k + 1, v, pn, p)
                if v > X // p:
                    break
                v *= p
                pn *= p

    rec(0, 1, 1, 1)
    return Td, Tp, Cn


def delta_exact(Td, Tp, B, gammas):
    Sd = sum(Td.values())
    Sp = sum(Tp.values())
    out = {}
    for g in gammas:
        Ed = sum(t * (q ** g) for q, t in Td.items()) / Sd
        Ep = sum(t * (q ** g) for q, t in Tp.items()) / Sp
        out["%.6f" % g] = {
            "gamma": g,
            "delta_bits_d_weighted": g * math.log2(B) - math.log2(Ed),
            "delta_bits_psi_weighted": g * math.log2(B) - math.log2(Ep),
            "E_entry_ell_gamma_d_weighted": Ed,
            "E_entry_ell_gamma_psi_weighted": Ep,
        }
    return out, Sd, Sp


