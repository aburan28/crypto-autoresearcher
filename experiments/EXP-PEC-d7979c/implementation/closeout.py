GL_NODES = 96
LAP_H = 0.05
LAP_T = 25.0
RHO_DU = 0.05
UMAX = 130.0
EULER_GAMMA = 0.5772156649015328606


def _leggauss_pure(n):
    xs = [0.0] * n
    ws = [0.0] * n
    for i in range(n):
        x = math.cos(math.pi * (i + 0.75) / (n + 0.5))
        dp = 1.0
        for _ in range(100):
            p0, p1 = 1.0, 0.0
            for k in range(n):
                p2 = p1
                p1 = p0
                p0 = ((2 * k + 1) * x * p1 - k * p2) / (k + 1)
            dp = n * (x * p0 - p1) / (x * x - 1.0)
            dx = -p0 / dp
            x += dx
            if abs(dx) < 1e-16:
                break
        xs[i] = x
        ws[i] = 2.0 / ((1.0 - x * x) * dp * dp)
    return xs, ws


_GS = None
_GWS = None


def _ein(z):
    s = 0j
    for sk, wk in zip(_GS, _GWS):
        s += wk * (1.0 - cmath.exp(-z * sk)) / sk
    return s


def _saddle_xi(u):
    xi = math.log(u) + math.log(max(math.log(u), 0.5))
    for _ in range(200):
        e = math.exp(xi)
        f = (e - 1.0) / xi - u
        d = (e * xi - (e - 1.0)) / (xi * xi)
        xi -= f / d
        if abs(f) < 1e-14:
            break
    return xi


def build_rho_grid():
    global _GS, _GWS
    gx, gw = _leggauss_pure(GL_NODES)
    _GS = [0.5 * (x + 1.0) for x in gx]
    _GWS = [0.5 * w for w in gw]
    n = int(round(LAP_T / LAP_H))
    taus = [k * LAP_H for k in range(-n, n + 1)]
    m = int(round((UMAX - 1.0) / RHO_DU)) + 1
    grid = []
    for i in range(m):
        u = 1.0 + i * RHO_DU
        xi = _saddle_xi(u)
        acc = 0j
        for tau in taus:
            s = complex(-xi, tau)
            acc += cmath.exp(u * s - _ein(s) + EULER_GAMMA)
        rho = (acc * LAP_H / (2.0 * math.pi)).real
        grid.append(math.log2(max(rho, 1e-300)))
    return grid


_RHO = None


def rho(u):
    if u < 0.0:
        return 0.0
    if u <= 1.0:
        return 1.0
    if u >= UMAX:
        return 0.0
    pos = (u - 1.0) / RHO_DU
    i = int(pos)
    fr = pos - i
    return 2.0 ** (_RHO[i] + fr * (_RHO[i + 1] - _RHO[i]))


R_QUAD = 1600
V_QUAD = 1200


def _J(lny, L):
    """int_0^{min(2L,60)} e^{-r} g(r) dr with
       g(r) = rho(a*w_y) - rho(a*w_y - 1)/(a*L),  a = 1 - r/(2L), w_y = L/ln y.
    This is S(y) = int_1^X t dPsi(t,y) with Psi(t,y) = t*rho(ln t/ln y),
    stripped of the common factor e^{2L}/2 which cancels in every ratio."""
    rmax = min(2.0 * L, 60.0)
    h = rmax / R_QUAD
    wy = L / lny
    s = 0.0
    for k in range(R_QUAD + 1):
        r = k * h
        a = 1.0 - r / (2.0 * L)
        u = a * wy
        g = rho(u) - (rho(u - 1.0) / (a * L) if a > 0 else 0.0)
        wq = 1.0 if k in (0, R_QUAD) else (4.0 if k % 2 else 2.0)
        s += wq * math.exp(-r) * g
    return s * h / 3.0


def delta_dickman(log2X, log2B, gamma):
    """Delta = -log2( E_entry[ell^gamma] / B^gamma ), with
       E/B^gamma = 1 - gamma*lnB*int_0^1 B^{(v-1)gamma} R(v) dv,
       R(v) = S(B^v)/S(B)   (integration by parts of int y^gamma dS(y))."""
    L = log2X * math.log(2.0)
    lnB = log2B * math.log(2.0)
    JB = _J(lnB, L)
    if JB <= 0.0:
        return None
    h = 1.0 / V_QUAD
    acc = 0.0
    for k in range(V_QUAD + 1):
        v = k * h
        Rv = 0.0 if v <= 0.0 else _J(v * lnB, L) / JB
        f = (2.0 ** (log2B * (v - 1.0) * gamma)) * Rv
        wq = 1.0 if k in (0, V_QUAD) else (4.0 if k % 2 else 2.0)
        acc += wq * f
    integ = acc * h / 3.0
    ratio = 1.0 - gamma * lnB * integ
    if ratio <= 0.0:
        return None
    return -math.log2(ratio)


def predicted_smooth_count(X, B):
    u = math.log(X) / math.log(B)
    return X * rho(u)


