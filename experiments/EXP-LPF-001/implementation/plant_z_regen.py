def _peak_rss_gb() -> float:
    try:
        import resource
        v = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
        # macOS reports bytes, Linux kilobytes.
        return (v / (1024 ** 3)) if sys.platform == "darwin" else (v / (1024 ** 2))
    except Exception:                                    # noqa: BLE001
        return float("nan")


# ==========================================================================
# Tail / accounting primitives. Pure functions of the regenerated arrays.
# ==========================================================================
def z_full(values: np.ndarray, p_max: np.ndarray) -> np.ndarray:
    """Index-aligned Z with the driver's own TAIL-LPF-1 contribution mask;
    non-contributing positions are -inf so they can never enter a top-k."""
    z = np.full(values.shape, -np.inf, dtype=np.float64)
    m = (values > 1) & (p_max > 1)
    z[m] = np.log(values[m].astype(np.float64)) / np.log(p_max[m].astype(np.float64))
    return z


def top_indices(z: np.ndarray, rank: int) -> np.ndarray:
    part = np.argpartition(z, z.size - rank)[z.size - rank:]
    return part[np.argsort(z[part])[::-1]]


def percentiles(z: np.ndarray) -> dict:
    if z.size == 0:
        return {"p99": None, "p99_9": None, "p99_99": None}
    return {
        "p99": float(np.percentile(z, 99.0)),
        "p99_9": float(np.percentile(z, 99.9)),
        "p99_99": float(np.percentile(z, 99.99)),
    }


def histogram(z: np.ndarray) -> dict:
    counts = np.histogram(z, bins=np.array(HIST_EDGES))[0]
    return {"edges": HIST_EDGES, "counts": [int(c) for c in counts],
            "below_first_edge": int(np.count_nonzero(z < HIST_EDGES[0]))}


# ==========================================================================
# Main regeneration.
# ==========================================================================
def regenerate(D, repo_root: str, wall_budget: float) -> dict:
    t0 = time.time()
    budget_events: list[dict] = []

    def deadline(where: str) -> None:
        e = time.time() - t0
        if e > wall_budget:
            budget_events.append({"kind": "wall_clock_exceeded", "where": where,
                                  "elapsed_seconds": e,
                                  "limit_seconds": wall_budget})
            raise Refusal(
                f"WALL-CLOCK BUDGET EXCEEDED at {where}: {e:.1f}s > "
                f"{wall_budget}s. BUDGET EVENT, INSTRUMENT SIGNAL, NEVER A "
                "RESULT.")

    archived_null = json.load(open(os.path.join(repo_root, NULL_STATS_REL)))["per_cell"]

    dick = D.Dickman()
    blocks: list[dict] = []
    anchor_report: dict = {}
    cell_desc: dict = {}
    counterexample_report: dict = {}
    plant_index_disagreements: list[dict] = []

    for bits in D.FIELD_BITS:
        cell = D.CalibrationCell(bits)
        cell.small_smooth_primes = D.primes_upto(D.bsm_at_u4(bits)).tolist()
        cell_desc[str(bits)] = cell.descriptor()
        bsm_u4 = D.bsm_at_u4(bits)
        bsm_u6 = dict((u, b) for u, b in D.BSM_LADDER[bits])[6]
        _log(f"cell bits={bits}: p={cell.p} X={cell.X} Bsm(u=4)={bsm_u4} "
             f"Bsm(u=6)={bsm_u6}")

        # ---- base replicates: LPF-CAL-A k = 0..R_PLANT-1, identical stream --
        s_unif = D.Stream("calib_uniform",
                          D.MASTER_SEED + D.STREAM_OFFSETS["calib_uniform"] + bits)
        base_v: list[np.ndarray] = []
        base_pm: list[np.ndarray] = []
        base_z: list[np.ndarray] = []
        null_t_deep: list[float] = []
        null_ks: list[float] = []
        null_top10: list[np.ndarray] = []
        fact_verified = fact_total = 0
        for k in range(D.R_PLANT):
            vals = cell.draw_uniform(s_unif, k)
            res = cell.factorizer.factor(vals)
            fact_verified += res["verified_count"]
            fact_total += res["total_count"]
            if res["verified_count"] != res["total_count"]:
                raise Refusal(f"FACTORIZATION VERIFICATION FAILURE bits={bits} k={k}")
            st = D.all_statistics(vals, res["p_max"], bits, dick)
            base_v.append(vals)
            base_pm.append(res["p_max"])
            zf = z_full(vals, res["p_max"])
            base_z.append(zf)
            null_t_deep.append(float(st["t_deep"]))
            null_ks.append(float(st["ks_dick"]))
            null_top10.append(top_indices(zf, D.TAIL_RANK))
            deadline(f"base bits={bits} k={k}")
        _log(f"  base: {D.R_PLANT} uniform replicates re-drawn and factored "
             f"({fact_total} factorizations, verified fraction "
             f"{fact_verified / fact_total:.6f}, {time.time() - t0:.0f}s)")

        # ---- ANCHOR: bit-for-bit against the archived calibration ----------
        arch = archived_null[str(bits)]["LPF-CAL-A"]["LPF_null_replicate_values"]
        a_td = arch["STAT-TAIL-DEEP"][:D.R_PLANT]
        a_ks = arch["STAT-KS-DICK"][:D.R_PLANT]
        rep0_ok = (null_t_deep[0] == ANCHOR[bits]["t_deep"]
                   and null_ks[0] == ANCHOR[bits]["ks_dick"])
        all_ok = (null_t_deep == [float(x) for x in a_td]
                  and null_ks == [float(x) for x in a_ks])
        # The tenth-largest Z read off the index-aligned array must equal the
        # driver's own STAT-TAIL-DEEP, or the accounting below is misaligned.
        align_ok = all(base_z[k][null_top10[k][D.TAIL_RANK - 1]] == null_t_deep[k]
                       for k in range(D.R_PLANT))
        anchor_report[str(bits)] = {
            "replicate0_t_deep_regenerated": null_t_deep[0],
            "replicate0_t_deep_archived": ANCHOR[bits]["t_deep"],
            "replicate0_ks_dick_regenerated": null_ks[0],
            "replicate0_ks_dick_archived": ANCHOR[bits]["ks_dick"],
            "replicate0_bit_for_bit": bool(rep0_ok),
            "all_20_base_replicates_bit_for_bit_vs_archived_series": bool(all_ok),
            "index_aligned_tenth_largest_equals_STAT_TAIL_DEEP": bool(align_ok),
            "base_factorizations": fact_total,
            "base_factorization_verified_fraction": fact_verified / fact_total,
        }
        if not (rep0_ok and all_ok and align_ok):
            raise Refusal(
                f"ANCHOR FAILURE at bits={bits}. The regenerated stream does "
                "not reproduce the archived calibration bit-for-bit. STOPPING; "
                "no tail statistic is computed against a stream that cannot be "
                "reproduced.")
        _log(f"  ANCHOR bits={bits}: replicate 0 bit-for-bit OK; all 20 base "
             "replicates match the archived series; index alignment OK")

        # ---- both ladders, every rung -------------------------------------
        for family, ladder, sname in (
                ("OBJ-PLANT-SMOOTH", D.LADDER_SMOOTH, "calib_plant_smooth"),
                ("OBJ-PLANT-ROUGH", D.LADDER_ROUGH, "calib_plant_rough")):
            strm = D.Stream(sname, D.MASTER_SEED + D.STREAM_OFFSETS[sname] + bits)
            for g_i, gamma in enumerate(ladder):
                per_rep = []
                all_z: list[np.ndarray] = []
                req = eff = fb = 0
                kfv = kft = 0
                bsm6_smooth = 0
                rough_checked = 0
                rough_viol = {"q_not_above_p": 0, "q_does_not_divide": 0,
                              "r_not_below_q": 0, "r_exceeds_v_over_q": 0,
                              "z_not_below_2": 0}
                rough_max_z = -np.inf
                for k in range(D.R_PLANT):
                    kk = g_i * 1000 + k
                    pl = D.apply_plant(base_v[k], base_pm[k], gamma, family,
                                       cell, strm, kk)
                    req += pl["replaced_requested"]
                    eff += pl["replaced_effected"]
                    fb += pl["construction_fallbacks"]
                    kfv += pl["known_factorization_verification"]["verified_count"]
                    kft += pl["known_factorization_verification"]["total_count"]
                    if kfv != kft:
                        raise Refusal(
                            f"KNOWN-FACTORIZATION VERIFICATION FAILURE "
                            f"{family} bits={bits} gamma={gamma} k={k}")

                    # candidate positions: apply_plant's own first rng call
                    rng = np.random.default_rng(strm.draw_seed(kk))
                    n = base_v[k].size
                    n_rep = int(round(gamma * n))
                    cand = rng.choice(n, size=n_rep, replace=False)
                    changed = ((pl["values"][cand] != base_v[k][cand])
                               | (pl["p_max"][cand] != base_pm[k][cand]))
                    pidx = cand[changed]
                    if pidx.size != pl["replaced_effected"]:
                        plant_index_disagreements.append({
                            "family": family, "bits": bits, "gamma": gamma,
                            "replicate": k,
                            "recovered_plant_positions": int(pidx.size),
                            "apply_plant_replaced_effected":
                                int(pl["replaced_effected"]),
                            "note": ("a replacement whose (value, P_max) pair "
                                     "coincided with the sample it replaced is "
                                     "indistinguishable from a non-replacement "
                                     "and contributes an identical Z"),
                        })

                    pz = z_full(pl["values"], pl["p_max"])
                    plant_z = pz[pidx]
                    all_z.append(plant_z)

                    # STRIKE-2 counterpart: Bsm(u=6)-smooth planted values
                    bsm6_smooth += int(np.count_nonzero(pl["p_max"][pidx] <= bsm_u6))

                    # ROUGH structural bound, checked on (m, P_max, v) alone.
                    # Every quantity is below p**2 <= 2**40, so this int64
                    # integer arithmetic is exact.
                    if family == "OBJ-PLANT-ROUGH" and pidx.size:
                        m = pl["values"][pidx].astype(np.int64)
                        q = pl["p_max"][pidx].astype(np.int64)
                        v = base_v[k][pidx].astype(np.int64)
                        rough_checked += int(pidx.size)
                        rough_viol["q_not_above_p"] += int(
                            np.count_nonzero(q <= np.int64(cell.p)))
                        rough_viol["q_does_not_divide"] += int(
                            np.count_nonzero(m % q != 0))
                        r = m // q
                        rough_viol["r_not_below_q"] += int(
                            np.count_nonzero(r >= q))
                        rough_viol["r_exceeds_v_over_q"] += int(
                            np.count_nonzero(r > (v // q)))
                        rough_viol["z_not_below_2"] += int(
                            np.count_nonzero(plant_z >= 2.0))
                        if plant_z.size:
                            rough_max_z = max(rough_max_z, float(plant_z.max()))

                    # deep-tail eviction / insertion accounting
                    ptop = top_indices(pz, D.TAIL_RANK)
                    ptop_set = set(int(i) for i in ptop)
                    pidx_set = set(int(i) for i in pidx)
                    ntop = [int(i) for i in null_top10[k]]
                    survivors = sum(1 for i in ntop
                                    if i in ptop_set and i not in pidx_set)
                    evictions = D.TAIL_RANK - survivors
                    overwritten = sum(1 for i in ntop if i in pidx_set)
                    insertions = sum(1 for i in ptop if int(i) in pidx_set)
                    promoted = D.TAIL_RANK - survivors - insertions
                    ptd = D.stat_tail_deep(pz[np.isfinite(pz)])

                    per_rep.append({
                        "replicate": k,
                        "plant_count": int(pidx.size),
                        "replaced_requested": int(pl["replaced_requested"]),
                        "replaced_effected": int(pl["replaced_effected"]),
                        "construction_fallbacks": int(pl["construction_fallbacks"]),
                        "max_plant_z": (float(plant_z.max()) if plant_z.size
                                        else None),
                        "null_t_deep": null_t_deep[k],
                        "planted_t_deep": float(ptd),
                        "planted_t_deep_minus_null_t_deep":
                            float(ptd) - null_t_deep[k],
                        "plants_exceeding_this_replicates_null_t_deep": int(
                            np.count_nonzero(plant_z > null_t_deep[k])),
                        "deep_tail_insertions_plants_in_planted_top10": insertions,
                        "deep_tail_survivors_of_null_top10": survivors,
                        "deep_tail_evictions_null_top10_members_lost": evictions,
                        "deep_tail_null_top10_positions_overwritten_by_a_plant":
                            overwritten,
                        "deep_tail_promoted_null_non_top10_members": promoted,
                    })
                    deadline(f"{family} bits={bits} gamma={gamma} k={k}")

                z = np.concatenate(all_z) if all_z else np.zeros(0)
                zf = z[np.isfinite(z)]
                order = np.sort(zf)[::-1]
                topk = order[:TOP_K]
                exceed = sum(r["plants_exceeding_this_replicates_null_t_deep"]
                             for r in per_rep)
                blocks.append({
                    "family": family,
                    "bits": bits,
                    "gamma": gamma,
                    "ladder_index": g_i,
                    "replicates": D.R_PLANT,
                    "plant_count_total": int(z.size),
                    "plant_z_finite_count": int(zf.size),
                    "replacements_requested_total": int(req),
                    "replacements_effected_total": int(eff),
                    "construction_fallbacks_total": int(fb),
                    "known_factorization_verified_count": int(kfv),
                    "known_factorization_total_count": int(kft),
                    "plant_z_summary": {
                        "mean": float(zf.mean()) if zf.size else None,
                        "sd": float(zf.std(ddof=1)) if zf.size > 1 else None,
                        "min": float(zf.min()) if zf.size else None,
                        "max": float(zf.max()) if zf.size else None,
                        **percentiles(zf),
                    },
                    "plant_z_histogram": histogram(zf),
                    "plant_z_top_k_sorted_desc": [float(x) for x in topk],
                    "plant_z_top_k_K": int(topk.size),
                    "plants_exceeding_own_replicate_null_t_deep_total": int(exceed),
                    "deep_tail_accounting_totals": {
                        "insertions": sum(r["deep_tail_insertions_plants_in_planted_top10"]
                                          for r in per_rep),
                        "evictions": sum(r["deep_tail_evictions_null_top10_members_lost"]
                                         for r in per_rep),
                        "null_top10_positions_overwritten_by_a_plant": sum(
                            r["deep_tail_null_top10_positions_overwritten_by_a_plant"]
                            for r in per_rep),
                        "survivors": sum(r["deep_tail_survivors_of_null_top10"]
                                         for r in per_rep),
                        "promoted_null_non_top10": sum(
                            r["deep_tail_promoted_null_non_top10_members"]
                            for r in per_rep),
                        "null_top10_slots_examined": D.TAIL_RANK * D.R_PLANT,
                    },
                    "bsm_u6_smooth_plant_count": int(bsm6_smooth),
                    "bsm_u6_bound": int(bsm_u6),
                    "bsm_u4_bound": int(bsm_u4),
                    "rough_structural_check": ({
                        "plants_checked": rough_checked,
                        "violations": rough_viol,
                        "max_plant_z": (float(rough_max_z)
                                        if np.isfinite(rough_max_z) else None),
                        "bound_holds_on_every_value": bool(
                            sum(rough_viol.values()) == 0),
                        "chain": ("r <= v//q <= p**2/q < p < q forces "
                                  "P_max = q and Z = ln(q r)/ln q < 2"),
                    } if family == "OBJ-PLANT-ROUGH" else None),
                    "per_replicate": per_rep,
                })
                _log(f"  {family} bits={bits} gamma={gamma}: plants={z.size} "
                     f"max_z={blocks[-1]['plant_z_summary']['max']} "
                     f"exceed={exceed} "
                     f"ins={blocks[-1]['deep_tail_accounting_totals']['insertions']} "
                     f"evi={blocks[-1]['deep_tail_accounting_totals']['evictions']} "
                     f"({time.time() - t0:.0f}s)")

                # ---- the specific counterexample ---------------------------
                if (family == COUNTEREXAMPLE["family"]
                        and bits == COUNTEREXAMPLE["bits"]
                        and gamma == COUNTEREXAMPLE["gamma"]):
                    r0 = per_rep[COUNTEREXAMPLE["replicate"]]
                    counterexample_report = {
                        "locus": {k: COUNTEREXAMPLE[k] for k in
                                  ("family", "bits", "gamma", "replicate")},
                        "reported_plant_z_rounded": COUNTEREXAMPLE["reported_plant_z"],
                        "regenerated_max_plant_z": r0["max_plant_z"],
                        "regenerated_max_plant_z_rounded_to_4dp": round(
                            r0["max_plant_z"], 4),
                        "max_plant_z_matches_report_at_4dp": bool(
                            round(r0["max_plant_z"], 4)
                            == COUNTEREXAMPLE["reported_plant_z"]),
                        "reported_null_t_deep": COUNTEREXAMPLE["reported_null_t_deep"],
                        "regenerated_null_t_deep": r0["null_t_deep"],
                        "null_t_deep_bit_for_bit": bool(
                            r0["null_t_deep"] == COUNTEREXAMPLE["reported_null_t_deep"]),
                        "reported_plant_t_deep": COUNTEREXAMPLE["reported_plant_t_deep"],
                        "regenerated_plant_t_deep": r0["planted_t_deep"],
                        "plant_t_deep_bit_for_bit": bool(
                            r0["planted_t_deep"]
                            == COUNTEREXAMPLE["reported_plant_t_deep"]),
                        "planted_t_deep_minus_null_t_deep":
                            r0["planted_t_deep_minus_null_t_deep"],
                        "plants_exceeding_null_t_deep":
                            r0["plants_exceeding_this_replicates_null_t_deep"],
                        "deep_tail_insertions": r0[
                            "deep_tail_insertions_plants_in_planted_top10"],
                        "deep_tail_evictions": r0[
                            "deep_tail_evictions_null_top10_members_lost"],
                    }

    return {
        "blocks": blocks,
        "anchor": anchor_report,
        "cells": cell_desc,
        "counterexample": counterexample_report,
        "plant_index_disagreements": plant_index_disagreements,
        "budget_events": budget_events,
        "wall_clock_seconds": time.time() - t0,
    }


# ==========================================================================
# Mechanically generated summary views. MECH-GEN-1: nothing hand-written.
# ==========================================================================
def build_report(D, reg: dict, meta: dict) -> dict:
    rows = []
    for b in reg["blocks"]:
        acc = b["deep_tail_accounting_totals"]
        rows.append({
            "family": b["family"], "bits": b["bits"], "gamma": b["gamma"],
            "plant_count_total": b["plant_count_total"],
            "max_plant_z": b["plant_z_summary"]["max"],
            "p99_99_plant_z": b["plant_z_summary"]["p99_99"],
            "plants_exceeding_own_replicate_null_t_deep":
                b["plants_exceeding_own_replicate_null_t_deep_total"],
            "deep_tail_insertions": acc["insertions"],
            "deep_tail_evictions": acc["evictions"],
            "bsm_u6_smooth_plant_count": b["bsm_u6_smooth_plant_count"],
            "rough_bound_holds": (b["rough_structural_check"]["bound_holds_on_every_value"]
                                  if b["rough_structural_check"] else None),
        })

    def agg(pred) -> dict:
        sel = [b for b in reg["blocks"] if pred(b)]
        ins = sum(b["deep_tail_accounting_totals"]["insertions"] for b in sel)
