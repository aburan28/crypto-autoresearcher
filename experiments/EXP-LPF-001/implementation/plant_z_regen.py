"""EXP-LPF-001 / RUN-LPF-001-plantz -- AUXILIARY planted-Z regeneration.

TASK-20260801-063. PERTURB-TAIL-1: NO SENTENCE MAY REST ON AN UNARCHIVED ARRAY.

WHAT THIS IS. RR-LPF-1's D1 asserted a structural property of the planted-Z
upper tail whose per-sample arrays were never archived, so the assertion is not
checkable against the archive. This script regenerates every PLANTED value at
every rung of both ladders at both cells, from the frozen driver's own
construction functions on the frozen driver's own streams, computes their Z,
and archives the distribution, the upper tail, the per-replicate exceedance
counts against each replicate's OWN null tenth-largest Z, and the deep-tail
eviction and insertion accounting.

WHAT THIS IS NOT. It is not a new experiment, it adjudicates nothing, it
freezes nothing, it selects no branch and it states no disposition. It writes
OBSERVATIONS. RR-LPF-2 is authored at TASK-20260801-066 and reviewed at
TASK-20260801-068.

INTEGRITY CONSTRAINTS, ALL ENFORCED IN CODE.

  1. THE DRIVER IS NOT MODIFIED. This file IMPORTS lpf001_driver as a module
     and asserts its sha256 is DRIVER_SHA256_REQUIRED before doing anything.
  2. STRUCTURAL BLINDNESS. Only the calibration-side machinery is called:
     Stream/draw_seed, CalibrationCell.draw_uniform, Factorizer.factor,
     primes_upto, bsm_at_u4, Dickman, all_statistics, z_values,
     stat_tail_deep, apply_plant and, through apply_plant,
     build_smooth_replacement / build_rough_replacement. NOTHING in the
     driver's section 8 (deterministic_factor_base, int1_fibre_invariants,
     upper_triangle_indices), no run_measurement, no _independent_pmax_recheck.
     The module tripwire _REAL_OBJECT_TOUCHED is asserted False at exit.
  3. NO FACTORIZATION OF PLANTS. Planted factorizations are known by
     construction; the Factorizer is applied ONLY to the uniform base
     replicates, exactly as LPF-CAL-A does, because the plant bases are those
     replicates and their P_max is needed to form the base arrays.
  4. THE ANCHOR. The archived null values on replicate 0 at both cells must
     reproduce BIT-FOR-BIT or the run stops. All 20 base replicates per cell
     are additionally re-checked against the archived per-replicate null
     series.
  5. MECH-GEN-1. Every summary reported anywhere is generated by this script
     from the regenerated arrays and archived beside them. Nothing is
     hand-transcribed.

INDEXING. Exactly run_calibration's: base replicates are the LPF-CAL-A uniform
replicates k = 0..R_PLANT-1 off stream `calib_uniform`; the plant streams are
`calib_plant_smooth` / `calib_plant_rough` addressed at g_i * 1000 + k, where
g_i is the ladder index of gamma.

PLANT-INDEX RECOVERY. apply_plant returns arrays, not the replaced positions.
The positions are recovered WITHOUT re-implementing any construction: the
first use of apply_plant's generator is `rng.choice(n, size=n_rep,
replace=False)`, so drawing that same first call from a generator seeded with
the same Stream.draw_seed reproduces the candidate index set exactly. Effected
replacements are then the candidates whose (value, P_max) pair actually
changed; the count is cross-checked against apply_plant's own
`replaced_effected` and any disagreement is recorded, not smoothed over.
"""

