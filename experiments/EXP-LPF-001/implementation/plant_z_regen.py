def print_tables(rep: dict) -> None:
    print("")
    print("=== PER (family, cell, rung) SUMMARY -- generated from the arrays ===")
    hdr = (f"{'family':18s} {'bits':>4s} {'gamma':>7s} {'plants':>8s} "
           f"{'max_Z':>10s} {'exceed':>7s} {'ins':>5s} {'evi':>5s} "
           f"{'Bsm6smooth':>11s} {'roughOK':>8s}")
    print(hdr)
    for r in rep["summary_rows"]:
        mz = "None" if r["max_plant_z"] is None else f"{r['max_plant_z']:.6f}"
        print(f"{r['family']:18s} {r['bits']:4d} {r['gamma']:7.4f} "
              f"{r['plant_count_total']:8d} {mz:>10s} "
              f"{r['plants_exceeding_own_replicate_null_t_deep']:7d} "
              f"{r['deep_tail_insertions']:5d} {r['deep_tail_evictions']:5d} "
              f"{r['bsm_u6_smooth_plant_count']:11d} "
              f"{str(r['rough_bound_holds']):>8s}")
    print("")
    print("=== EVICTION / INSERTION COUNTS (quotient is arithmetic only) ===")
    for name, a in [("ALL", rep["aggregates"]["all"])] + \
            [(f"{k}", v) for k, v in rep["aggregates"]["by_family"].items()] + \
            [(f"{k} gamma<=0.05", v) for k, v in
             rep["aggregates"]["by_family_gamma_le_0p05"].items()]:
        q = a["evictions_over_insertions_ARITHMETIC_ON_THE_ARCHIVED_COUNTS"]
        qs = "n/a" if q is None else f"{q:.4f}"
        print(f"{name:42s} evictions={a['evictions']:6d} "
              f"insertions={a['insertions']:6d} quotient={qs:>8s} "
              f"overwritten={a['null_top10_positions_overwritten_by_a_plant']:6d} "
              f"promoted={a['promoted_null_non_top10']:6d} "
              f"slots={a['null_top10_slots_examined']:6d}")
    print("")
    print("=== ROUGH STRUCTURAL BOUND ===")
    print(json.dumps(rep["rough_structural_bound"], indent=2))
    print("")
    print("=== COUNTEREXAMPLE CHECK ===")
    print(json.dumps(rep["counterexample_check"], indent=2))
    print("")
    print("=== ANCHOR ===")
    print(json.dumps(rep["anchor"], indent=2))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(
        description="EXP-LPF-001 auxiliary planted-Z tail regeneration")
    ap.add_argument("--repo-root", default=os.getcwd())
    ap.add_argument("--out-report", required=True)
    ap.add_argument("--out-raw", required=True)
    ap.add_argument("--wall-clock-seconds", type=float, default=900.0)
    args = ap.parse_args(argv)

    repo_root = os.path.abspath(args.repo_root)
    driver_path = os.path.join(repo_root, DRIVER_REL)

    # ---- refusal gate 1: the driver must hash to the frozen value ----------
    got = _sha256_file(driver_path)
    _log(f"driver sha256 = {got}")
    if got != DRIVER_SHA256_REQUIRED:
        print(f"REFUSED: lpf001_driver.py sha256 {got} != "
              f"{DRIVER_SHA256_REQUIRED}. The frozen driver has been modified; "
              "this auxiliary script regenerates nothing against a driver it "
              "cannot bind to.", file=sys.stderr)
        return 3
    _log("driver sha256 matches the frozen DRIVER_SHA256; import permitted")

    sys.path.insert(0, repo_root)
    sys.path.insert(0, os.path.dirname(driver_path))
    import lpf001_driver as D                             # noqa: E402

    if D._REAL_OBJECT_TOUCHED:
        print("REFUSED: tripwire already set at import.", file=sys.stderr)
        return 3

    started = datetime.now(timezone.utc).isoformat(timespec="seconds")
    t0 = time.time()
    meta = {
        "started_at_utc": started,
        "regen_script_sha256": _sha256_file(os.path.abspath(__file__)),
        "driver_sha256": got,
        "driver_sha256_required": DRIVER_SHA256_REQUIRED,
        "driver_unmodified": True,
        "master_seed": D.MASTER_SEED,
        "stream_offsets_used": {
            "calib_uniform": D.STREAM_OFFSETS["calib_uniform"],
            "calib_plant_smooth": D.STREAM_OFFSETS["calib_plant_smooth"],
            "calib_plant_rough": D.STREAM_OFFSETS["calib_plant_rough"]},
        "stream_seed_formula": "MASTER_SEED + STREAM_OFFSETS[name] + bits",
        "plant_stream_index_formula": "g_i * 1000 + k, exactly run_calibration's",
        "replicates_per_rung": D.R_PLANT,
        "n_per_sample_set": D.N_PER_SAMPLE_SET,
        "tail_rank": D.TAIL_RANK,
        "ladder_smooth": list(D.LADDER_SMOOTH),
        "ladder_rough": list(D.LADDER_ROUGH),
        "field_bits": list(D.FIELD_BITS),
        "top_k_archived": TOP_K,
        "wall_clock_budget_seconds": args.wall_clock_seconds,
        "environment": D.environment_record("plantz-auxiliary"),
    }

    status = "completed_valid"
    failure_class = None
    failure_detail = None
    reg = {"blocks": [], "anchor": {}, "cells": {}, "counterexample": {},
           "plant_index_disagreements": [], "budget_events": [],
           "wall_clock_seconds": 0.0}
    try:
        reg = regenerate(D, repo_root, args.wall_clock_seconds)
    except Refusal as exc:
        status = "invalid_measurement" if "ANCHOR" in str(exc) else "failed"
        failure_class = ("resource_exhaustion" if "BUDGET" in str(exc)
                         else "invalid_measurement")
        failure_detail = str(exc)
        print(f"STOPPED: {exc}", file=sys.stderr)

    # ---- refusal gate 2: the tripwire must still be False -------------------
    touched = bool(D._REAL_OBJECT_TOUCHED)
    if touched:
        print("INTEGRITY FAILURE: _REAL_OBJECT_TOUCHED is True at exit.",
              file=sys.stderr)
        status = "invalid_measurement"
        failure_class = "implementation_error"
        failure_detail = "ATS-LPF-1 clause 5 tripwire set"
    assert not touched, "ATS-LPF-1 clause 5: the real object was touched"

    meta["finished_at_utc"] = datetime.now(timezone.utc).isoformat(timespec="seconds")
    meta["wall_clock_seconds"] = time.time() - t0
    meta["peak_rss_gb"] = _peak_rss_gb()
    meta["LPF_real_object_touched"] = touched
    meta["LPF_budget_event"] = reg["budget_events"]
    meta["status"] = status
    meta["failure_class"] = failure_class
    meta["failure_detail"] = failure_detail

    report = build_report(D, reg, meta)
    os.makedirs(os.path.dirname(os.path.abspath(args.out_report)), exist_ok=True)
    with open(args.out_report, "w") as fh:
        json.dump(report, fh, indent=2, default=D._json_default)
        fh.write("\n")

    raw = {
        "run_id": RUN_ID,
        "experiment_id": D.EXPERIMENT_ID,
        "task_id": TASK_ID,
        "stage": "auxiliary-plant-z-regeneration",
        "status": status,
        "claim_tier": "toy",
        "interpretation": "NONE",
        "certificate": {
            "kind": "none",
            "reason": ("No discrete logarithm is computed and no relation is "
                       "claimed. The integrity analogue is the anchor: the "
                       "regenerated stream reproduces the archived calibration "
                       "null statistics bit-for-bit, plus 100 percent "
                       "known-factorization verification on every planted "
                       "value.")},
        "LPF_real_object_touched": touched,
        "LPF_tripwire_asserted_false_at_exit": not touched,
        "LPF_budget_event": reg["budget_events"],
        "LPF_measurement_arm_invoked": False,
        "driver_sha256": got,
        "driver_sha256_unchanged": got == DRIVER_SHA256_REQUIRED,
        "regen_script_sha256": meta["regen_script_sha256"],
        "anchor": report["anchor"],
        "rough_structural_bound": report["rough_structural_bound"],
        "counterexample_check": report["counterexample_check"],
        "summary_rows": report["summary_rows"],
        "aggregates": report["aggregates"],
        "plant_index_recovery_disagreements": report[
            "plant_index_recovery_disagreements"],
        "blocks_archived_in": args.out_report,
        "block_count": len(reg["blocks"]),
        "meta": meta,
    }
    os.makedirs(os.path.dirname(os.path.abspath(args.out_raw)), exist_ok=True)
    with open(args.out_raw, "w") as fh:
        json.dump(raw, fh, indent=2, default=D._json_default)
        fh.write("\n")

    if status == "completed_valid":
        print_tables(report)
    _log(f"status={status} wall_clock={meta['wall_clock_seconds']:.1f}s "
         f"peak_rss_gb={meta['peak_rss_gb']:.3f} "
         f"real_object_touched={touched}")
    _log(f"report -> {args.out_report}")
    _log(f"raw    -> {args.out_raw}")
    return 0 if status == "completed_valid" else 4


