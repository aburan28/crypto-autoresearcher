#!/usr/bin/env python3
"""Build the four C-4 (e) gate-power mutants of model_v2.py.

Each mutant is a byte copy of model_v2.py with exactly ONE line replaced, as
the amendment names them:

  M1  drop L from TPR
  M2  tabulate floor((m-1)/2)  (oracle exponent +d at even m)
  M3  swap the time and store halves
  M4  use s = min(S, ceil(log2 B / d))

Usage:
  python3 make_mutants.py --write     # (re)write code/v2/mutants/*.py
  python3 make_mutants.py --verify    # exit 1 unless the committed mutant
                                      # files equal a fresh regeneration
Library use: build_all() returns {mutant_id: source_text}.
"""
from __future__ import annotations

import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DRIVER = os.path.join(HERE, "model_v2.py")
MUTANT_DIR = os.path.join(HERE, "mutants")

MUTATIONS = {
    "M1": {
        "file": "M1_drop_L_from_TPR.py",
        "what": "drop L from TPR",
        "old": "    TPR = N + L - m * d  # MUTATION SITE M1\n",
        "new": "    TPR = N - m * d  # MUTATION SITE M1 -- MUTANT: L dropped\n",
    },
    "M2": {
        "file": "M2_tabulate_floor_m_minus_1_half.py",
        "what": "tabulate floor((m-1)/2)",
        "old": "    return m // 2  # MUTATION SITE M2\n",
        "new": "    return (m - 1) // 2  # MUTATION SITE M2 -- MUTANT: floor((m-1)/2)\n",
    },
    "M3": {
        "file": "M3_swap_time_and_store_halves.py",
        "what": "swap the time and store halves",
        "old": "        time_half, store_half = (m - s) * d, s * d  # MUTATION SITE M3\n",
        "new": "        time_half, store_half = s * d, (m - s) * d  # MUTATION SITE M3 -- MUTANT: swapped\n",
    },
    "M4": {
        "file": "M4_ceil_budget_cap.py",
        "what": "use s = min(S, ceil(log2 B / d))",
        "old": "    return min(S, math.floor(log2_budget / d))  # MUTATION SITE M4\n",
        "new": "    return min(S, math.ceil(log2_budget / d))  # MUTATION SITE M4 -- MUTANT: ceil\n",
    },
}


def build_all() -> dict:
    with open(DRIVER, "r", encoding="utf-8") as fh:
        src = fh.read()
    out = {}
    for mid, spec in MUTATIONS.items():
        count = src.count(spec["old"])
        if count != 1:
            raise SystemExit(f"{mid}: mutation site found {count} times, need exactly 1")
        header = (f"# GATE-POWER MUTANT {mid} of model_v2.py ({spec['what']}).\n"
                  f"# Generated by make_mutants.py; ONE line differs from the driver.\n"
                  f"# Not a model of anything: it exists so C-IMPL-GATE can be shown to fail it.\n")
        out[mid] = header + src.replace(spec["old"], spec["new"])
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--verify", action="store_true")
    a = ap.parse_args()
    built = build_all()
    if a.write:
        os.makedirs(MUTANT_DIR, exist_ok=True)
        for mid, text in built.items():
            with open(os.path.join(MUTANT_DIR, MUTATIONS[mid]["file"]), "w",
                      encoding="utf-8") as fh:
                fh.write(text)
        print("wrote", ", ".join(sorted(built)))
        return 0
    bad = []
    for mid, text in built.items():
        p = os.path.join(MUTANT_DIR, MUTATIONS[mid]["file"])
        if not os.path.exists(p) or open(p, encoding="utf-8").read() != text:
            bad.append(mid)
    print("verify:", "OK" if not bad else f"MISMATCH {bad}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
