def closure_dimension(delta: int, cols: List[List[int]]) -> int:
    """delta is a 16-bit packed vector of four GF(2^4) nibbles, nibble i at
    bits 4i..4i+3.  cols[j] is column j of the matrix as a list of 4 nibbles.

    Returns the GF(2)-dimension of the smallest GF(2)-subspace of GF(2^4)^4
    containing v0 = Delta_i * m_i (i the least index with Delta_i != 0) and
    closed under the four maps T_j(u) = u_j * m_j.  Each T_j is GF(2)-LINEAR
    (coordinate extraction is GF(2)-linear and w -> w * m_j is GF(2)-linear),
    so closing on a spanning set suffices."""
    i = 0
    while ((delta >> (4 * i)) & 0xF) == 0:
        i += 1
    lam = (delta >> (4 * i)) & 0xF
    v0 = 0
    for r in range(4):
        v0 |= gmul4(lam, cols[i][r]) << (4 * r)

    basis: List[int] = []          # row-echelon basis of 16-bit words
    pivots: List[int] = []

    def add(v: int) -> bool:
        for p, b in zip(pivots, basis):
            if v >> p & 1:
                v ^= b
        if v == 0:
            return False
        p = v.bit_length() - 1
        basis.append(v)
        pivots.append(p)
        # keep sorted by pivot descending for a stable reduction order
        order = sorted(range(len(basis)), key=lambda t: -pivots[t])
        basis[:] = [basis[t] for t in order]
        pivots[:] = [pivots[t] for t in order]
        return True

    work = []
    if add(v0):
        work.append(v0)
    while work:
        u = work.pop()
        for j in range(4):
            uj = (u >> (4 * j)) & 0xF
            if uj == 0:
                continue
            w = 0
            for r in range(4):
                w |= gmul4(uj, cols[j][r]) << (4 * r)
            if w and add(w):
                work.append(w)
    return len(basis)


def phase_gate() -> Dict:
    mats, sel = build_matrices()
    results = {}
    for name in ("target", "null_1", "null_2"):
        mat = mats[name]
        cols = [[mat[r][j] for r in range(4)] for j in range(4)]
        t0 = time.time()
        hist = collections.Counter()
        for delta in range(1, 1 << 16):
            hist[closure_dimension(delta, cols)] += 1
        el = time.time() - t0
        results[name] = {
            "matrix_rows": [[hex(x) for x in row] for row in mat],
            "deltas_tested": (1 << 16) - 1,
            "dimension_histogram": {str(k): v for k, v in sorted(hist.items())},
            "count_reaching_dim_16": hist.get(16, 0),
            "max_dimension": max(hist),
            "min_dimension": min(hist),
            "wall_clock_seconds": round(el, 3),
        }
    return {"phase": "gate", "per_matrix": results}


