# GF(2^8) -- for the OD-1 graph phase.  Reference multiplication only; no
# tables are trusted.
# ===========================================================================

MOD8 = 0x11B  # x^8 + x^4 + x^3 + x + 1


def gmul8(a: int, b: int) -> int:
    a &= 0xFF
    b &= 0xFF
    r = 0
    while b:
        if b & 1:
            r ^= a
        b >>= 1
        a <<= 1
        if a & 0x100:
            a ^= MOD8
    return r & 0xFF


# AES MixColumns, circulant with first row (02,03,01,01); M[i][j] = c[(j-i)%4].
M8 = (
    (0x02, 0x03, 0x01, 0x01),
    (0x01, 0x02, 0x03, 0x01),
    (0x01, 0x01, 0x02, 0x03),
    (0x03, 0x01, 0x01, 0x02),
)

# ===========================================================================
# GF(2^4) -- for the gate phase.  Modulus x^4 + x + 1 (primitive), matching
# the TASK-20260731-705 validator's gate701c.py as described in section 7.4.
# ===========================================================================

MOD4 = 0x13  # x^4 + x + 1


def gmul4(a: int, b: int) -> int:
    a &= 0xF
    b &= 0xF
    r = 0
    while b:
        if b & 1:
            r ^= a
        b >>= 1
        a <<= 1
        if a & 0x10:
            a ^= MOD4
    return r & 0xF


def circulant(first_row: Sequence[int]) -> Tuple[Tuple[int, ...], ...]:
    """M[i][j] = first_row[(j - i) mod 4], the same convention as the AES
    MixColumns matrix hard-coded above."""
    c = list(first_row)
    return tuple(tuple(c[(j - i) % 4] for j in range(4)) for i in range(4))


def rank_gf(mat, mul, inv_of) -> int:
    """Gauss-Jordan rank over a field with the supplied multiplication."""
    m = [list(row) for row in mat]
    n = len(m)
    row = 0
    for col in range(n):
        piv = None
        for r in range(row, n):
            if m[r][col]:
                piv = r
                break
        if piv is None:
            continue
        m[row], m[piv] = m[piv], m[row]
        iv = inv_of(m[row][col])
        m[row] = [mul(iv, x) for x in m[row]]
        for r in range(n):
            if r != row and m[r][col]:
                f = m[r][col]
                m[r] = [x ^ mul(f, y) for x, y in zip(m[r], m[row])]
        row += 1
    return row


def inv4(a: int) -> int:
    for x in range(1, 16):
        if gmul4(a, x) == 1:
            return x
    raise ZeroDivisionError(a)


def inv8(a: int) -> int:
    for x in range(1, 256):
        if gmul8(a, x) == 1:
            return x
    raise ZeroDivisionError(a)


def subgroup_generated(gens, mul, order_of_group: int) -> List[int]:
    """Multiplicative subgroup generated by a set of nonzero field elements."""
    seen = {1}
    stack = [1]
    while stack:
        x = stack.pop()
        for g in gens:
            if g == 0:
                continue
            y = mul(x, g)
            if y not in seen:
                seen.add(y)
                stack.append(y)
    return sorted(seen)


# ===========================================================================
# The (lambda, k) graph, over an arbitrary field size.
# ===========================================================================

def build_lambda_k_graph(mat, mul, q: int):
    """Nodes (lambda, k), lambda in {1..q-1}, k in 0..3.
    Edges (lambda,k) -> (lambda*mat[j][k], j) for every j.
    An edge whose target scalar is 0 (possible only if mat has a zero entry)
    leaves the node set and is DROPPED, which is recorded explicitly."""
    nodes = [(lam, k) for lam in range(1, q) for k in range(4)]
    index = {n: i for i, n in enumerate(nodes)}
    fwd: List[List[int]] = [[] for _ in nodes]
    rev: List[List[int]] = [[] for _ in nodes]
    dropped = 0
    for (lam, k) in nodes:
        u = index[(lam, k)]
        for j in range(4):
            t = mul(lam, mat[j][k])
            if t == 0:
                dropped += 1
                continue
            v = index[(t, j)]
            fwd[u].append(v)
            rev[v].append(u)
    return nodes, index, fwd, rev, dropped


def bfs_dist(adj: List[List[int]], src: int) -> List[int]:
    n = len(adj)
    dist = [-1] * n
    dist[src] = 0
    dq = collections.deque([src])
    while dq:
        u = dq.popleft()
        du = dist[u] + 1
        for v in adj[u]:
            if dist[v] < 0:
                dist[v] = du
                dq.append(v)
    return dist


def all_pairs_stats(adj: List[List[int]], nodes) -> Dict:
    n = len(adj)
    ecc = [0] * n
    diameter = -1
    realizing = None
    unreachable_pairs = 0
    for s in range(n):
        d = bfs_dist(adj, s)
        mx, arg = -1, None
        for t in range(n):
            if d[t] < 0:
                unreachable_pairs += 1
                continue
            if d[t] > mx:
                mx, arg = d[t], t
        ecc[s] = mx
        if mx > diameter:
            diameter = mx
            realizing = (nodes[s], nodes[arg], mx)
    dist_hist = collections.Counter(ecc)
    return {
        "n_nodes": n,
        "diameter": diameter,
        "radius": min(ecc),
        "eccentricity_distribution": {str(k): v for k, v in sorted(dist_hist.items())},
        "realizing_pair_at_diameter": {
            "source": {"lambda": hex(realizing[0][0]), "k": realizing[0][1]},
            "target": {"lambda": hex(realizing[1][0]), "k": realizing[1][1]},
            "distance": realizing[2],
        },
        "ordered_pairs_with_no_path": unreachable_pairs,
    }


def scc_kosaraju(fwd: List[List[int]], rev: List[List[int]]) -> List[List[int]]:
    n = len(fwd)
    visited = [False] * n
    order: List[int] = []
    for s in range(n):
        if visited[s]:
            continue
        stack = [(s, 0)]
        visited[s] = True
        while stack:
            u, i = stack.pop()
            if i < len(fwd[u]):
                stack.append((u, i + 1))
                v = fwd[u][i]
                if not visited[v]:
                    visited[v] = True
                    stack.append((v, 0))
            else:
                order.append(u)
    comp = [-1] * n
    comps: List[List[int]] = []
    for s in reversed(order):
        if comp[s] >= 0:
            continue
        cid = len(comps)
        cur = [s]
        comp[s] = cid
        stack = [s]
        while stack:
            u = stack.pop()
            for v in rev[u]:
                if comp[v] < 0:
                    comp[v] = cid
                    cur.append(v)
                    stack.append(v)
        comps.append(cur)
    return comps


