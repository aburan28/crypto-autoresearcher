# The three matrices, fixed here BEFORE the gate is run.
#
# target : AES-shaped GF(2^4) analogue, circulant first row (02,03,01,01).
# null_1 : the identity interface (ShiftRows + AddRoundKey, no MixColumns).
#          Unchanged from the BATCH-002 specification; it is the sensitivity
#          anchor, not the Step-3 negation.
# null_2 : REDESIGNED.  Selection rule, fixed a priori and stated in the
#          report before measurement:
#            (1) H := the order-3 subgroup of GF(2^4)^* , i.e. GF(4)^* , the
#                multiplicative group of the subfield GF(4) < GF(2^4).  It is
#                proper (3 | 15, 3 != 15).  It is chosen among the two proper
#                nontrivial subgroups (orders 3 and 5) on the STRUCTURAL
#                ground that it is the only one that is the multiplicative
#                group of a subfield, which is what makes the predicted stall
#                hand-checkable -- the same standard the gate imposes on
#                null_1 ("sensitivity is demonstrated, not assumed").
#            (2) Among 4x4 circulants with all entries in H, enumerate first
#                rows alpha^(5*e) for e in {0,1,2}^4 in lexicographic order of
#                (e0,e1,e2,e3) and take the FIRST invertible one.
#          That rule is deterministic and yields exactly ONE candidate, which
#          is then verified and run once.
TARGET_FIRST_ROW = (0x2, 0x3, 0x1, 0x1)


def _alpha_pow4(e: int) -> int:
    x = 1
    for _ in range(e % 15):
        x = gmul4(x, 0x2)
    return x


def select_null2() -> Dict:
    """Executes the a-priori selection rule and records the whole enumeration."""
    H = sorted({_alpha_pow4(5 * t) for t in range(3)})
    trace = []
    chosen = None
    for e0 in range(3):
        for e1 in range(3):
            for e2 in range(3):
                for e3 in range(3):
                    row = tuple(_alpha_pow4(5 * e) for e in (e0, e1, e2, e3))
                    mat = circulant(row)
                    rk = rank_gf(mat, gmul4, inv4)
                    trace.append({
                        "exponent_tuple": [e0, e1, e2, e3],
                        "first_row": [hex(x) for x in row],
                        "rank": rk,
                        "invertible": rk == 4,
                    })
                    if rk == 4 and chosen is None:
                        chosen = row
                    if chosen is not None:
                        return {
                            "subgroup_H": [hex(x) for x in H],
                            "subgroup_order": len(H),
                            "group_order": 15,
                            "proper": len(H) < 15,
                            "enumeration_trace_until_first_invertible": trace,
                            "selected_first_row": [hex(x) for x in chosen],
                        }
    raise RuntimeError("no invertible circulant over H -- would itself be the finding")


def matrix_facts(name: str, mat) -> Dict:
    entries = [mat[i][j] for i in range(4) for j in range(4)]
    gens = sorted({e for e in entries if e != 0})
    sub = subgroup_generated(gens, gmul4, 15) if gens else [1]
    rk = rank_gf(mat, gmul4, inv4)
    nodes, index, fwd, rev, dropped = build_lambda_k_graph(mat, gmul4, 16)
    comps = scc_kosaraju(fwd, rev)
    sizes = collections.Counter(len(c) for c in comps)
    # component structure described by the lambda-cosets they occupy
    comp_lambda_sets = []
    for c in sorted(comps, key=len, reverse=True)[:6]:
        lams = sorted({nodes[u][0] for u in c})
        comp_lambda_sets.append({
            "size": len(c),
            "lambdas": [hex(x) for x in lams],
            "indices_k": sorted({nodes[u][1] for u in c}),
        })
    return {
        "name": name,
        "matrix_rows": [[hex(x) for x in row] for row in mat],
        "all_entries_nonzero": all(e != 0 for e in entries),
        "distinct_entries": [hex(x) for x in sorted(set(entries))],
        "rank_over_GF(2^4)": rk,
        "invertible": rk == 4,
        "subgroup_generated_by_entries": [hex(x) for x in sub],
        "subgroup_order": len(sub),
        "subgroup_is_proper": len(sub) < 15,
        "lambda_k_graph_over_GF(2^4)": {
            "node_count": len(nodes),
            "edges_dropped_to_zero_scalar": dropped,
            "scc_count": len(comps),
            "strongly_connected": len(comps) == 1,
            "scc_size_histogram": {str(k): v for k, v in sorted(sizes.items())},
            "largest_components": comp_lambda_sets,
        },
    }


def build_matrices() -> Tuple[Dict, Dict]:
    sel = select_null2()
    mats = {
        "target": circulant(TARGET_FIRST_ROW),
        "null_1": tuple(tuple(1 if i == j else 0 for j in range(4)) for i in range(4)),
        "null_2": circulant([int(x, 16) for x in sel["selected_first_row"]]),
    }
    return mats, sel


def phase_construction() -> Dict:
    t0 = time.time()
    mats, sel = build_matrices()
    facts = {name: matrix_facts(name, m) for name, m in mats.items()}
    return {
        "phase": "construction",
        "field": "GF(2^4), modulus 0x13 (x^4+x+1), alpha=0x2 primitive",
        "null_2_selection": sel,
        "matrices": facts,
        "wall_clock_seconds": round(time.time() - t0, 3),
    }


