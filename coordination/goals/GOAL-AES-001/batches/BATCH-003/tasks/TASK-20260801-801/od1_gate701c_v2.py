def phase_graph() -> Dict:
    t0 = time.time()
    nodes, index, fwd, rev, dropped = build_lambda_k_graph(M8, gmul8, 256)
    assert dropped == 0, "AES M has no zero entry; no edge may be dropped"

    fwd_stats = all_pairs_stats(fwd, nodes)
    rev_stats = all_pairs_stats(rev, nodes)

    # Independent re-confirmation of strong connectivity, three ways:
    #  (i) single-source forward and reverse reachability from (0x01, k=0);
    #  (ii) Kosaraju SCC decomposition;
    #  (iii) implied by the all-pairs BFS above (no unreachable ordered pair).
    d0 = bfs_dist(fwd, index[(1, 0)])
    r0 = bfs_dist(rev, index[(1, 0)])
    comps = scc_kosaraju(fwd, rev)

    # ---- 2-step graph G^2.  The OD-1 extension consumes TWO interfaces per
    # graph edge (Step 1 at one interface, Step 2's upgrade at the next), so
    # the object it needs is walks of EVEN length.
    g2: List[List[int]] = []
    for u in range(len(nodes)):
        s = set()
        for v in fwd[u]:
            s.update(fwd[v])
        g2.append(sorted(s))
    self_loops_g2 = sum(1 for u in range(len(nodes)) if u in set(g2[u]))
    g2_rev: List[List[int]] = [[] for _ in nodes]
    for u in range(len(nodes)):
        for v in g2[u]:
            g2_rev[v].append(u)
    g2_stats = all_pairs_stats(g2, nodes)
    g2_comps = scc_kosaraju(g2, g2_rev)

    # ---- n_star: the quantity the extension proposition actually uses.
    # A collision Delta of pi^(0) with least nonzero coordinate index i and
    # value mu = Delta_i yields GLOBAL invariance of pi^(2) at the four nodes
    # S0(mu, i) = {(mu * M[k][i], k) : k = 0..3}.  Each further pair of
    # interfaces advances every held node by one G^2 step.  n_star is the
    # worst case, over all 1020 possible (mu, i), of the number of G^2 steps
    # needed for S0 to cover ALL 1020 nodes.
    n_star = -1
    n_star_witness = None
    per_start = {}
    for (mu, i) in nodes:
        s0 = [index[(gmul8(mu, M8[k][i]), k)] for k in range(4)]
        dist = [-1] * len(nodes)
        dq = collections.deque()
        for u in set(s0):
            dist[u] = 0
            dq.append(u)
        while dq:
            u = dq.popleft()
            du = dist[u] + 1
            for v in g2[u]:
                if dist[v] < 0:
                    dist[v] = du
                    dq.append(v)
        m = max(dist)
        per_start[(mu, i)] = m
        if m > n_star:
            n_star = m
            n_star_witness = (mu, i)
    n_star_hist = collections.Counter(per_start.values())

    return {
        "phase": "graph",
        "object": "directed (lambda,k) graph of verify_derivation.py claim C11",
        "field": "GF(2^8), modulus 0x11B",
        "matrix": "AES MixColumns circulant, first row (02,03,01,01)",
        "node_count": len(nodes),
        "edges_dropped_to_zero_scalar": dropped,
        "forward_graph": fwd_stats,
        "reverse_graph": rev_stats,
        "strong_connectivity_recheck": {
            "forward_reachable_from_0x01_k0": sum(1 for x in d0 if x >= 0),
            "reverse_reachable_from_0x01_k0": sum(1 for x in r0 if x >= 0),
            "kosaraju_scc_count": len(comps),
            "largest_scc_size": max(len(c) for c in comps),
            "strongly_connected": len(comps) == 1,
            "independent_of_C11": True,
        },
        "two_step_graph_G2": {
            "note": "edges of G2 are walks of length exactly 2 in G",
            "nodes_with_self_loop": self_loops_g2,
            "scc_count": len(g2_comps),
            "strongly_connected": len(g2_comps) == 1,
            **g2_stats,
        },
        "n_star": {
            "definition": "max over the 1020 possible (mu,i) of the number of "
                          "G2-steps for S0(mu,i) = {(mu*M[k][i], k) : k=0..3} "
                          "to cover all 1020 nodes",
            "value": n_star,
            "witness_mu_i": {"mu": hex(n_star_witness[0]), "i": n_star_witness[1]},
            "distribution": {str(k): v for k, v in sorted(n_star_hist.items())},
        },
        "wall_clock_seconds": round(time.time() - t0, 3),
    }


